 <h2><b>Q: Under what circumstances is the promoter required to compensate the allottee?</b></h2><br>
    <p class="answer">A1: The promoter must compensate the allottee in the following scenarios:</p>
    <ul>
        <p><b>Incorrect or False Statements:</b> If the allottee sustains loss or damage due to incorrect or false statements in the notice, advertisement, prospectus, or brochure.</p>
        <p><b>Discontinuance of Promoter’s Business:</b> If the allottee wishes to withdraw from the project due to the promoter's business discontinuance (suspension or revocation of registration or other reasons as per Section 18).</p>
        <p><b>Failure to Deliver Possession:</b> If the promoter fails to deliver possession of the apartment/plot as per the terms and conditions of the agreement for sale.</p>
    </ul>
    <p class="answer">In these cases, the promoter must return the entire amount paid by the allottee, along with interest and compensation.</p>

    <h2><b>Q: What is the rate of interest payable by the promoter to the allottee?</b></h2><br>
    <p class="answer">A2: The rate of interest payable by the promoter to the allottee is:</p>
    <ul class="answer">
        <li><b>State Bank of India (SBI) Highest Marginal Cost of Lending Rate (HMCLR) + 2%</b></li>
    </ul>

    <h2><b>Q: What should be done if the State Bank of India (SBI) Marginal Cost of Lending Rate (MCLR) is not applicable?</b></h2><br>
    <p class="answer">A3: If the SBI MCLR is not in use, it should be replaced by the benchmark lending rates that the SBI may fix from time to time for lending to the general public.</p><br>

    <h2><b>Q: What happens if the allottee fails to pay as per the agreed terms?</b></h2><br>
    <p class="answer">A4: If the allottee fails to make payments as per the agreement, the allottee shall also be liable to pay interest. This interest rate is similarly defined as:</p>
    <ul class="answer">
        <li><b>State Bank of India (SBI) Highest Marginal Cost of Lending Rate (HMCLR) + 2%</b></li>
    </ul>

    <h2><b>Q: How is the rate of interest determined if the MCLR is not used?</b></h2><br>
    <p class="answer">A5: If MCLR is not used, the interest rate should be determined based on the benchmark lending rates set by the SBI for lending to the general public.</p><br>

 <h2><b>Q: What is the timeline for the promoter to pay a refund to the allottee?</b></h2><br>
    <p class="answer">A1: The promoter must pay the refund to the allottee within ninety days from the date on which the refund, along with the applicable interest and compensation, becomes due.</p><br>

    <h2><b>Q: What does the refund include?</b></h2><br>
    <p class="answer">A2: The refund must include:</p>
    <ul class="answer">
        <li>1. The entire amount paid by the allottee.</li>
        <li>2. Applicable interest.</li>
        <li>3. Compensation, if any.</li>
    </ul>

    <h2><b>Q: What happens if the promoter fails to make the refund within the stipulated period?</b></h2><br>
    <p class="answer">A3: The Act or associated rules and regulations may provide further remedies or actions that can be taken if the promoter fails to process the refund within the specified ninety-day period. This may include legal actions or penalties as defined by the regulatory framework.</p><br>





