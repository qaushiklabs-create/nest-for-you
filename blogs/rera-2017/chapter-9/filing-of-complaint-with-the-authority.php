 <h2><b>Q: How can an aggrieved person file a complaint with the Authority?</b></h2><br>
    <p class="answer">A: An aggrieved person can file a complaint with the Authority by following these steps:</p>
    <ul class="answer">
        <p><strong>1. Form and Documentation:</strong> The complaint must be filed in Form ‘CRA’ in triplicate.</p>
        <p><strong>2. Fees:</strong> The complaint must be accompanied by a fee as prescribed in Schedule III, payable via a demand draft or a banker’s cheque drawn on a Scheduled bank in favor of “Haryana Real Estate Regulatory Authority.”</p>
        <p><strong>3. Submission:</strong> Submit the form and documents to the Authority as outlined in the regulations.</p>
    </ul>

    <h2><b>Q: What is the process followed by the Authority for deciding a complaint?</b></h2><br>
    <p class="answer">A: The Authority follows a summary procedure for inquiry:</p>
    <ul class="answer">
        <p><strong>1. Issuance of Notice:</strong> Upon receipt of the complaint, the Authority issues a notice to the respondent detailing the alleged contravention and specifies the date and time of the hearing.</p>
        <p><strong>2. Response:</strong> The respondent must file a reply to the complaint within the timeframe specified in the notice.</p>
        <p><strong>3. Hearing:</strong>
            <ul>
                <li>1. The Authority schedules and communicates a date and time for further hearings.</li>
                <li>2. At the hearing, the Authority explains the alleged contravention.</li>
                <li>3. If the respondent pleads guilty, the Authority records the plea and may impose a penalty.</li>
                <li>4. If the respondent contests the complaint, the Authority demands an explanation.</li>
            </ul>
        </p>
    </ul>

    <h2><b>Q: What actions can the Authority take if it requires further inquiry into the complaint?</b></h2><br>
    <p class="answer">A: If the Authority determines that further inquiry is needed, it may:</p>
    <ul class="answer">
        <li><strong>1. Order Production of Evidence:</strong> Request the production of documents or other evidence.</li>
        <li><strong>2. Carry Out Inquiry:</strong> Conduct an inquiry based on the evidence and submissions.</li>
        <li><strong>3. Summon Witnesses:</strong> Summon and enforce the attendance of witnesses or require them to produce documents relevant to the case.</li>
    </ul>

    <h2><b>Q: What happens if the respondent is found to be in contravention of the Act or rules?</b></h2><br>
    <p class="answer">A: If the Authority finds that the respondent is in contravention of the Act or rules, it will:</p>
    <ul class="answer">
        <li><strong>1. Pass Orders:</strong> Issue orders, which may include imposing penalties in accordance with the Act or rules.</li>
        <li><strong>2. Dismiss the Complaint:</strong> If the respondent is not found to be in contravention, the Authority may dismiss the complaint with reasons recorded in writing.</li>
    </ul>

    <h2><b>Q: What happens if a person fails to appear before the Authority?</b></h2><br>
    <p class="answer">A: If a person fails to appear or present themselves as required, the Authority can proceed with the inquiry in their absence after recording the reasons for doing so.</p><br>

    <h2><b>Q: What should be done if a party to the complaint is represented by an authorized person?</b></h2><br>
    <p class="answer">A: If a party is represented by an authorized person, a copy of the authorization and the written consent of the authorized person must be attached to the complaint or the reply to the notice of the complaint.</p><br>

    <h2><b>Q: How are the day-to-day functions of the Authority managed?</b></h2><br>
    <p class="answer">A: The day-to-day functions of the Authority, not covered by the Act or rules, are managed as specified by regulations made by the Authority.</p><br>

<h2><b>Q: How can an aggrieved person file a complaint for interest and compensation with the adjudicating officer?</b></h2><br>
    <p class="answer">A: To file a complaint for interest and compensation, an aggrieved person should:</p>
    <ul class="answer">
        <p><strong>1. Use Form:</strong> Submit the complaint in Form ‘CAO’, in triplicate.</p>
        <p><strong>2. Fee Payment:</strong> Pay the fee as specified in Schedule III, using a demand draft or banker’s cheque drawn on a Scheduled bank in favor of “Haryana Real Estate Regulatory Authority,” payable at the branch where the Authority's office is located.</p>
        <p><strong>3. Submission:</strong> File the form and fee at the appropriate office of the adjudicating officer.</p>
    </ul>

    <h2><b>Q: What is the procedure followed by the adjudicating officer for adjudging interest and compensation?</b></h2><br>
    <p class="answer">A: The adjudicating officer follows a summary procedure:</p>
    <ul class="answer">
        <p><strong>1. Issuance of Notice:</strong> Upon receipt of the complaint, the officer issues a notice with details of the alleged contravention and relevant documents to the respondent.</p>
        <p><strong>2. Response:</strong> The respondent must reply to the complaint within the time specified in the notice.</p>
        <p><strong>3. Hearing:</strong>
            <ul>
                <li>1. The notice may specify a date for further hearings.</li>
                <li>2. At the hearing, the adjudicating officer explains the alleged contravention.</li>
                <li>3. If the respondent pleads guilty, the officer records the plea and may order payment of interest and compensation as per the Act.</li>
                <li>4. If the respondent contests, the officer demands an explanation.</li>
            </ul>
        </p>
    </ul>

    <h2><b>Q: What actions can the adjudicating officer take if further inquiry is needed?</b></h2><br>
    <p class="answer">A: If further inquiry is required, the adjudicating officer may:</p>
    <ul class="answer">
        <li><strong>1. Order Production of Evidence:</strong> Request documents or other evidence.</li>
        <li><strong>2. Carry Out Inquiry:</strong> Conduct an inquiry based on submissions and evidence.</li>
        <li><strong>3. Summon Witnesses:</strong> Enforce the attendance of persons who may provide useful evidence or documents.</li>
    </ul>

    <h2><b>Q: What happens if the adjudicating officer finds the respondent liable for interest and compensation?</b></h2><br>
    <p class="answer">A: If the adjudicating officer finds the respondent liable:</p>
    <ul class="answer">
        <li><strong>1. Order Payment:</strong> The officer will issue a written order specifying the payment of interest as per the rules and any additional compensation deemed appropriate.</li>
        <li><strong>2. Dismissal:</strong> If the respondent is found not liable, the complaint may be dismissed with written reasons provided.</li>
    </ul>

    <h2><b>Q: What if a person fails to appear before the adjudicating officer?</b></h2><br>
    <p class="answer">A: If a person fails to appear or present themselves, the adjudicating officer can proceed with the inquiry in their absence, recording reasons for doing so.</p><br>

    <h2><b>Q: How are the day-to-day functions of the adjudicating officer managed?</b></h2><br>
    <p class="answer">A: The day-to-day functioning of the adjudicating officer, not covered by the Act or rules, is specified by regulations made by the Authority.</p><br>

    <h2><b>Q: What should be done if a party to the complaint is represented by an authorized person?</b></h2><br>
    <p class="answer">A: If a party is represented by an authorized person, a copy of the authorization and the written consent of the authorized person must be attached to the complaint or the reply to the notice of the complaint.</p><br>



