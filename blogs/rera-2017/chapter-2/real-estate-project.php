<h2><b>Q: What is required to apply for registration of a real estate project with the Authority?</b></h2><br>
    <p class="answer">A: To apply for registration, you need to submit a written application in Form ‘REP-I’ in triplicate to the Authority. Along with this form, you must provide:</p>
    <ul class="answer">
        <li>1. An authenticated copy of the promoter's PAN card.</li>
        <li>2. The annual report for the last three financial years, including the audited profit and loss account, balance sheet, cash flow statement, director’s report, and auditor's report. If the annual report is unavailable, provide the audited profit and loss account, balance sheet, cash flow statement, and auditor's report for the last three years.</li>
        <li>3. Details of the number of open and covered parking areas available in the project.</li>
        <li>4. An authenticated copy of the legal title deed showing the promoter’s title to the land, along with valid documents for the chain of title.</li>
        <li>5. Details of any encumbrances on the land, including rights, title, interest, dues, litigation, and involved parties, supported by a non-encumbrance certificate from the revenue authority.</li>
        <li>6. If the promoter is not the landowner, provide details of the owner's consent and copies of relevant agreements (collaboration, development, joint development, etc.), along with documents reflecting the owner's title.</li>
        <li>7. The name, photograph, contact details, and address of the promoter (if an individual), and the same details for the chairman, partners, directors, or authorized person if the promoter is an entity.</li>
    </ul><br>

    <h2><b>Q: How should the registration fee be paid?</b></h2><br>
    <p class="answer">A: The registration fee should be paid at the time of application submission. You can make the payment through a demand draft or banker’s cheque in favor of "Haryana Real Estate Regulatory Authority," drawn on any Scheduled bank, or via an online payment mode, as specified.</p><br>

    <h2><b>Q: What declaration must be included in the application?</b></h2><br>
    <p class="answer">A: The application must include a declaration in Form ‘REP-II’ under clause (l) of sub-section (2) of section 4. This declaration should state that the promoter will not discriminate against any allottee based on sex, caste, creed, color, religion, etc. However, the promoter may have differential pricing for units, apartments, or plots.</p><br>
 <h2><b>Q: What information must a promoter of an ongoing project provide to the Authority?</b></h2><br>
    <p class="answer">A: The promoter must submit the following information:</p>
    <ul class="answer">
        <li><strong>Financial Details:</strong> The total amount collected from allottees, the money spent on the project, and the remaining balance/unspent amount.</li>
        <li><strong>Project Status:</strong> Details on the extent of development completed and pending, including the original completion time disclosed to allottees, any delays, and the revised time frame for completing the project. This information must be certified by an engineer, architect, and chartered accountant.</li>
    </ul>

    <h2><b>Q: How should the size of an apartment be disclosed?</b></h2><br>
    <p class="answer">A: The promoter must disclose the size of the apartment based on the carpet area, even if it was sold based on other metrics such as super area or built-up area. This disclosure does not affect the validity of the agreement with the allottees.</p><br>

    <h2><b>Q: How should the area of a plot be disclosed in a plotted development?</b></h2><br>
    <p class="answer">A: For plotted developments, the promoter must disclose the area of the plot being sold according to the demarcation or zoning plan approved by the competent authority.</p><br>

    <h2><b>Q: What are the requirements for depositing funds into a separate bank account?</b></h2><br>
    <p class="answer">A: Within three months of applying for project registration, the promoter must deposit 70% of the amount already received from allottees into a separate bank account. These funds must be used exclusively for land and construction costs, as specified. This includes:</p>
    <ul class="answer">
        <li><strong>Land Cost:</strong> Expenses related to the purchase, lease, registration, stamp duty, and brokerage.</li>
        <li><strong>Construction Cost:</strong> On-site expenditure for physical development, including statutory charges and external development charges (EDC).</li>
    </ul>

    <h2><b>Q: What should a promoter do if a completion certificate or part completion certificate is refused by the competent authority?</b></h2><br>
    <p class="answer">A: If an application for a completion or part completion certificate is refused, the promoter must apply for project registration with the Haryana Real Estate Regulatory Authority within 30 days of receiving the refusal communication. This applies to refusals received before, on, or after July 31, 2017.</p><br>
<h2><b>Q: What happens upon the successful registration of a real estate project?</b></h2><br>
    <p class="answer">A: Upon successful registration, the Authority issues a registration certificate in Form ‘REP-III’ to the promoter. This certificate includes a registration number and is valid for the period stipulated for the completion of the project, as mentioned in the promoter’s application. However, the registration is contingent upon the validity of the promoter’s licenses and other permissions. If the stipulated registration period exceeds the validity of these licenses or permissions, the promoter must renew them in time. Failure to do so may result in the cancellation of the registration, though the promoter will be given an opportunity to be heard before any cancellation.</p><br>

    <h2><b>Q: What occurs if the application for project registration is rejected?</b></h2><br>
    <p class="answer">A: If the application is rejected, the Authority will notify the promoter using Form ‘REP-IV’. The Authority may also provide the promoter with an opportunity to rectify any defects or issues identified in the application. The promoter will have thirty days from the date of the communication to address and correct these defects.</p><br>

 <h2><b>Q: How can a promoter apply for an extension of the project registration?</b></h2><br>
    <p class="answer">A: A promoter seeking an extension of the project registration must submit an application in Form REP-V, in triplicate, to the Authority. This application should be made within three months prior to the expiration of the current registration.</p><br>

    <h2><b>Q: What should the application for extension of registration include?</b></h2><br>
    <p class="answer">A: The application must include:</p>
    <ul class="answer">
       <p><strong>Payment:</strong><br><br> A demand draft or banker’s cheque in favor of “Haryana Real Estate Regulatory Authority,” drawn on any Scheduled bank, or an online payment for an amount equivalent to half of the registration fees prescribed under sub-rule (2) of rule 3.<br><br>
        <strong>Explanatory Note:</strong><br><br> A detailed explanation outlining the reasons for the delay in the project’s completion and the need for the extension. This should be supported by relevant documents.</p> 
    </ul>

    <h2><b>Q: Can the extension fee be waived under any circumstances?</b></h2><br>
    <p class="answer">A: Yes, if the extension of registration is due to force majeure, court orders, government policies or guidelines, or other decisions, the Authority may, at its discretion, waive the extension fee.</p><br>

    <h2><b>Q: How will the promoter be informed about the extension or rejection of the registration?</b></h2><br>
    <p class="answer">A: If the extension is granted, the Authority will inform the promoter using Form ‘REP-VI’. If the application for extension is rejected, the Authority will notify the promoter using Form REP-IV.</p><br>

    <h2><b>Q: What happens if the application for extension has defects?</b></h2><br>
    <p class="answer">A: If there are defects in the application for extension, the Authority may provide the promoter with an opportunity to rectify these defects. The promoter will have thirty days from the date of the communication to address and correct the issues.</p><br>

 <h2><b>Q: What happens when a project registration is revoked?</b></h2><br>
    <p class="answer">A: When a project registration is revoked, the Authority will notify the promoter using Form ‘REP-IV’.</p><br>

    <h2><b>Q: Is the promoter given a chance to respond before the registration is revoked?</b></h2><br>
    <p class="answer">A: Yes, the promoter will be given an opportunity to be heard before the revocation of the project registration. This means the promoter can present their case or respond to any issues before the final decision on revocation is made.</p><br>
 <h2><b>Q: What is required for the agreement for sale?</b></h2><br>
    <p class="answer">A: The agreement for sale must be in accordance with Annexure ‘A’. This document outlines the specific format and terms required for the agreement between the promoter and the allottee.</p><br>

    <h2><b>Q: How do documents signed before the agreement for sale affect the allottees' rights?</b></h2><br>
    <p class="answer">A: Any application letter, allotment letter, or other document signed by the allottees before the execution and registration of the formal agreement for sale does not limit the rights and interests of the allottees. Their rights under the agreement for sale, the Act, and any associated rules or regulations are not diminished by these preliminary documents.</p><br>



