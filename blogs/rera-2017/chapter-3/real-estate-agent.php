<h2><b>Q: What is required for a real estate agent to apply for registration?</b></h2><br>
    <p class="answer">A: To apply for registration, every real estate agent must submit an application in writing to the Authority in Form REA-I, in triplicate. The application must be accompanied by the following documents:</p>
    <ul class="answer">
        <li>1. <strong>Enterprise Details:</strong> Brief details about the enterprise, including its name, registered address, and type (e.g., proprietorship, partnership, company).</li>
        <li>2. <strong>Registration Particulars:</strong> Details of registration such as bye-laws, memorandum of association, articles of association, or other relevant documents.</li>
        <li>3. <strong>Agent Information:</strong> Name, address, contact details, and photograph of the real estate agent if an individual; or of partners, directors, etc., in case of other entities.</li>
        <li>4. <strong>PAN Card:</strong> Authenticated copy of the PAN card of the real estate agent.</li>
        <li>5. <strong>Address Proof:</strong> Authenticated copy of the address proof for the place of business.</li>
        <li>6. <strong>Additional Documents:</strong> Any other information and documents specified by regulations.</li>
    </ul>

    <h2><b>Q: How should the registration fee be paid?</b></h2><br>
    <p class="answer">A: The registration fee should be paid at the time of application submission. It can be paid either by a demand draft or a banker’s cheque in favor of “Haryana Real Estate Regulatory Authority” drawn on any Scheduled bank, or through an online payment mode, as specified in Schedule II.</p><br>
    
    <h2><b>Q: What is the time frame for the Authority to process the registration application?</b></h2><br>
    <p class="answer">A: The Authority must process the registration application within thirty days of receiving it. During this period, the Authority will either grant the registration or reject the application.</p><br>

    <h2><b>Q: What happens if there are defects in the application?</b></h2><br>
    <p class="answer">A: If there are defects in the application, the Authority may grant the real estate agent an opportunity to rectify these defects. The real estate agent will have thirty days from the date of communication regarding the defects to make the necessary corrections.</p><br>

    <h2><b>Q: How will the real estate agent be notified of the registration decision?</b></h2><br>
    <p class="answer">A: Upon successful registration, the Authority will issue a registration certificate with a registration number in Form REA-II. If the application is rejected, the Authority will inform the applicant using Form REA-III.</p><br>

    <h2><b>Q: What is the validity period of the registration granted to a real estate agent?</b></h2><br>
    <p class="answer">A: The registration granted under this rule is valid for a period of five years.</p><br>

 <h2><b>Q: How can a real estate agent apply for the renewal of their registration?</b></h2><br>
    <p class="answer">A: A real estate agent must apply for the renewal of their registration by submitting an application in Form REA-IV, in triplicate, within three months prior to the expiry of their current registration.</p><br>

    <h2><b>Q: What documents and fees are required for the renewal application?</b></h2><br>
    <p class="answer">A: The renewal application must be accompanied by:</p>
    <ul class="answer">
        <p><strong>Fees:</strong><br><br> A demand draft or banker’s cheque in favor of “Haryana Real Estate Regulatory Authority” drawn on any Scheduled bank, or through online payment, as specified in Schedule II.<br><br>
        <strong>Updated Documents:</strong><br><br> All updated documents specified in clauses (a) to (f) of sub-rule (1) of rule 9, which include enterprise details, registration particulars, agent information, PAN card, address proof, and any other required documents.</p>
    </ul>

    <h2><b>Q: How will the real estate agent be notified about the renewal decision?</b></h2><br>
    <p class="answer">A: Upon approval of the renewal application, the Authority will inform the real estate agent using Form REA-V. If the application is rejected, the Authority will communicate this using Form REA-III.</p><br>

    <h2><b>Q: What happens if there are defects in the renewal application?</b></h2><br>
    <p class="answer">A: If there are defects in the application, the real estate agent will be given an opportunity to rectify them. The Authority will provide a period of thirty days from the date of communication regarding such defects for the agent to make the necessary corrections.</p><br>

    <h2><b>Q: What is the validity period of the renewed registration?</b></h2><br>
    <p class="answer">A: The registration renewed under this rule will be valid for a period of five years.</p><br>

 <h2><b>Q: Under what circumstances can the registration of a real estate agent be revoked?</b></h2><br>
    <p class="answer">A: The Authority may revoke the registration granted to a real estate agent or its renewal if necessary. Specific grounds for revocation are typically outlined by the Authority's regulations and rules.</p><br>

    <h2><b>Q: How will a real estate agent be informed of the revocation of their registration?</b></h2><br>
    <p class="answer">A: If the registration or its renewal is revoked, the Authority will inform the real estate agent using Form REA-III.</p><br>

<h2><b>Q: What are the requirements for maintaining books of accounts and records for a real estate agent?</b></h2><br>
    <p class="answer">A: The real estate agent is required to maintain and preserve its books of account, records, and documents in accordance with the provisions of the Income Tax Act, 1961, and the rules made thereunder.</p><br>

    <h2><b>Q: Why is it important for a real estate agent to comply with these accounting and record-keeping requirements?</b></h2><br>
    <p class="answer">A: Compliance with these requirements ensures transparency, accuracy in financial reporting, and adherence to legal obligations. It also facilitates audits and reviews by the relevant authorities.</p><br>



