 <h2><b>Q: What triggers the appointment process for the Chairperson or Members of the Authority?</b></h2><br>
    <p class="answer">A: The appointment process is triggered when a vacancy for the Chairperson or any Member of the Authority exists, arises, or is expected to arise. The Government will then refer the matter to the Selection Committee to address these vacancies.</p><br>

    <h2><b>Q: How does the Selection Committee select candidates for the Chairperson or Member positions?</b></h2><br>
    <p class="answer">A: The Selection Committee can follow a procedure deemed appropriate for the selection process. This may include appointing a Search Committee to suggest a panel of names for the Chairperson or Member positions.</p><br>

    <h2><b>Q: What is the role of the Search Committee in the selection process?</b></h2><br>
    <p class="answer">A: The Search Committee, if appointed, is responsible for suggesting a panel of names for the positions of Chairperson or Member to the Selection Committee.</p><br>

    <h2><b>Q: How many candidates does the Selection Committee recommend to the Government for each vacancy?</b></h2><br>
    <p class="answer">A: The Selection Committee is required to select and recommend two candidates for each vacancy to the Government.</p><br>

    <h2><b>Q: What is the timeline for the Selection Committee to make its recommendation?</b></h2><br>
    <p class="answer">A: The Selection Committee must make its recommendation to the Government within sixty days from the date of the reference made by the Government.</p><br>

    <h2><b>Q: What is the Government’s timeline for appointing a Chairperson or Member once recommendations are received?</b></h2><br>
    <p class="answer">A: The Government is required to appoint one of the two recommended candidates within thirty days of receiving the recommendation from the Selection Committee.</p><br>
    
     <h2><b>Q: What is the salary structure for the Chairperson of the Authority?</b></h2><br>
    <p class="answer">A: The salary for the Chairperson depends on their previous service:</p>
    <ul>
        <li>1. If the Chairperson has served in the Central or State Government, they will receive a salary equivalent to that of the Chief Secretary of the State Government.</li>
        <li>2. If the Chairperson has not been in Central or State Government service, they will receive a consolidated monthly salary of ₹2,50,000.</li>
    </ul>

    <h2><b>Q: What salary do the Members of the Authority receive?</b></h2><br>
    <p class="answer">A: The salary for the Members is as follows:</p>
    <ul>
        <li>1. If a Member has served in the Central or State Government, they will receive a salary equivalent to that of a Principal Secretary of the State Government.</li>
        <li>2. If the Member has not been in Central or State Government service, they will receive a consolidated monthly salary of ₹2,00,000.</li>
    </ul>

    <h2><b>Q: How much earned leave are the Chairperson and Members entitled to?</b></h2><br>
    <p class="answer">A: Both the Chairperson and Members are entitled to thirty days of earned leave for every completed year of service.</p><br>

    <h2><b>Q: Are the Chairperson and Members entitled to any residential benefits?</b></h2><br>
    <p class="answer">A: Yes, the Chairperson and Members are entitled to residential houses as per their entitlement.</p><br>

    <h2><b>Q: What about transportation benefits for the Chairperson and Members?</b></h2><br>
    <p class="answer">A: The Chairperson and Members are also entitled to vehicles as per their entitlement.</p><br>

    <h2><b>Q: Who determines the other allowances and conditions of service for the Chairperson and Members?</b></h2><br>
    <p class="answer">A: All other allowances and conditions of service for the Chairperson and Members are determined by the State Government and may be updated from time to time.</p><br>
    
    <h2><b>Q: What administrative powers does the Chairperson of the Authority have regarding staff matters?</b></h2><br>
    <p class="answer">A: The Chairperson has several administrative powers related to staff, including:</p>
    <ul>
        <li>1. Deciding on staff strength, wages, salary structures, emoluments, perquisites, and personnel policies, with prior approval from the Government.</li>
        <li>2. Handling the creation and abolition of posts, appointments, promotions, and confirmations for employees in Group ‘A’ and ‘B’, subject to Government approval.</li>
        <li>3. Accepting resignations of employees in Group ‘C’ and ‘D’.</li>
        <li>4. Accepting resignations of Group ‘A’ and ‘B’ employees and Members, with prior Government approval.</li>
    </ul>

    <h2><b>Q: Can the Chairperson authorize tours for Members, officers, or employees?</b></h2><br>
    <p class="answer">A: Yes, the Chairperson has the authority to authorize tours for Members, officers, or employees, both within the State and outside.</p><br>

    <h2><b>Q: Who has the authority to handle medical claims and leave matters?</b></h2><br>
    <p class="answer">A: The Chairperson is responsible for matters related to the reimbursement of medical claims and the granting or rejection of leave.</p><br>

    <h2><b>Q: Does the Chairperson have any authority regarding vehicle usage for official purposes?</b></h2><br>
    <p class="answer">A: Yes, the Chairperson can grant permission for the hiring of vehicles for official use.</p><br>

    <h2><b>Q: What about the nomination of staff for training or conferences?</b></h2><br>
    <p class="answer">A: The Chairperson has the power to nominate staff for attending seminars, conferences, and training courses, both within the State and outside.</p><br>

    <h2><b>Q: Can the Chairperson invite guest experts for training courses?</b></h2><br>
    <p class="answer">A: Yes, the Chairperson can grant permission for the invitation of guest(s) or experts to conduct training courses.</p><br>
    
     <h2><b>Q: How are the salaries and allowances of the officers and employees of the Authority determined?</b></h2><br>
    <p class="answer">A: The salaries and allowances of the officers and employees of the Authority are regulated according to the rules and regulations applicable to officers and employees of the State Government.</p><br>

    <h2><b>Q: What other conditions of service are regulated for officers and employees of the Authority?</b></h2><br>
    <p class="answer">A: In addition to salaries and allowances, other conditions of service include:</p>
    <ul>
        <li>1. Pay</li>
        <li>2. Leave</li>
        <li>3. Joining time and joining time pay</li>
        <li>4. Age of superannuation</li>
        <li>5. Other terms and conditions of service</li>
    </ul>

    <h2><b>Q: Can the Government make exceptions to these rules and regulations?</b></h2><br>
    <p class="answer">A: Yes, the Government has the power to relax the provisions of these rules for any class or category of officers or employees if deemed necessary.</p><br>
    
     <h2><b>Q: What additional powers does the Authority have beyond those specified in clause (iv) of sub-section (2) of section 35?</b></h2><br>
    <p class="answer">A: The Authority has several additional powers, including:</p>
    <ul>
        <li>1. Requiring promoters, allottees, or real estate agents to provide information, explanations, or documents within a reasonable time as needed.</li>
        <li>2. Calling upon experts or consultants from various fields such as urban planning, economics, real estate, law, and engineering to assist in inquiries or proceedings.</li>
        <li>3. Inquiring into the payment of penalties, interest, or compensation to ensure that the promoter has not:</li>
        <ul>
            <li>1. Withdrawn amounts from the designated account for the project.</li>
            <li>2. Used amounts paid by allottees for other projects.</li>
            <li>3. Recovered penalty or compensation amounts from the allottees.</li>
        </ul>
    </ul>

    <h2><b>Q: How does the Authority ensure compliance with the payment of penalties, interest, or compensation by the promoter?</b></h2><br>
    <p class="answer">A: The Authority ensures compliance by:</p>
    <ul>
        <li>1. Inquiring into whether the promoter has withdrawn penalty amounts from the designated project account.</li>
        <li>2. Verifying that the promoter has not used amounts paid by allottees for other projects.</li>
        <li>3. Checking that the promoter has not recovered penalty or compensation amounts from the allottees.</li>
    </ul>

    <h2><b>Q: What is the process for adjudging compensation under sections 12, 14, 18, and 19?</b></h2><br>
    <p class="answer">A: For adjudging compensation, the Authority:</p>
    <ul>
        <li>1. Appoints one or more officers with expertise in judicial or quasi-judicial matters, who are not below the rank of Class-I Officer or Additional District Judge.</li>
        <li>2. Consults with the Government to make these appointments.</li>
        <li>3. Ensures that the adjudicating officer provides a reasonable opportunity for all parties to be heard before determining the compensation.</li>
    </ul>






