 <h2><b>Q: How are orders passed by the adjudicating officer, Authority, or Appellate Tribunal enforced?</b></h2><br>
    <p class="answer">A: Orders passed by the adjudicating officer, the Authority, or the Appellate Tribunal are enforced as follows:</p><br>
    <ul class="answer">
        <p><strong>1. Enforcement as Civil Court Orders:</strong><br>
            <ul>
                <li>1. Every order issued is enforceable in the same manner as a decree or order made by a civil court in a pending suit.</li>
                <li>2. If the adjudicating officer, Authority, or Appellate Tribunal cannot execute the order, it may be sent to a civil court for enforcement.</li>
            </ul>
        </p>
        <p><strong>2. Role of the Civil Court:</strong>
            <ul>
                <li>1. The civil court is responsible for executing the order if the adjudicating officer, Authority, or Appellate Tribunal is unable to do so.</li>
            </ul>
        </p>
    </ul>

    <h2><b>Q: What provisions are made for compounding offenses under the Act?</b></h2><br>
    <p class="answer">A: For offenses punishable with imprisonment under the Act:</p>
    <ul class="answer">
        <li>1. The court may accept a specified amount for compounding the offense.</li>
        <li>2. The amount for compounding is detailed in a specific Table referred to in the Act, which outlines the permissible amount for settling offenses without proceeding to imprisonment.</li>
    </ul>

