<h2><b>Q: What are the requirements for filing an appeal under section 44?</b></h2><br>
    <p class="answer">A: To file an appeal under section 44, you must:</p>
    <ul>
        <li>1. Submit the appeal in Form ‘AAT’ in triplicate.</li>
        <li>2. Attach the following documents:</li>
        <ul>
            <li>1. A true copy of the order against which the appeal is filed.</li>
            <li>2. Copies of documents relied upon and referred to in the appeal.</li>
            <li>3. An index of the documents.</li>
        </ul>
    </ul>

    <h2><b>Q: What is the fee structure for filing an appeal?</b></h2><br>
    <p class="answer">A: Every appeal must be accompanied by a fee as specified in Schedule III. The fee should be paid in the form of a demand draft or a banker’s cheque drawn on a Scheduled Bank in favor of the Appellate Tribunal.</p><br>

    <h2><b>Q: When is an appeal considered to be filed if sent by post?</b></h2><br>
    <p class="answer">A: An appeal sent by post is deemed to have been filed on the day it is received in the office of the Appellate Tribunal.</p><br>

    <h2><b>Q: What if a party to the appeal is represented by an authorized person?</b></h2><br>
    <p class="answer">A: If a party is represented by an authorized person, you must include:</p>
    <ul>
        <li>1. A copy of the authorization to act as such.</li>
        <li>2. The written consent of the authorized person, both in original.</li>
    </ul>
    
    <h2><b>Q: How are vacancies for Members of the Appellate Tribunal filled?</b></h2><br>
    <p class="answer">A: When a vacancy arises or is expected to arise for a Member of the Appellate Tribunal, the Government makes a reference to the Selection Committee to fill the vacancy.</p><br>

    <h2><b>Q: What is the procedure followed by the Selection Committee for selecting Members?</b></h2><br>
    <p class="answer">A: The Selection Committee may:</p>
    <ul>
        <li>1. Follow a procedure deemed fit, which may include appointing a Search Committee.</li>
        <li>2. The Search Committee suggests a panel of names for appointment as Members.</li>
    </ul>

    <h2><b>Q: How many candidates does the Selection Committee recommend for each vacancy?</b></h2><br>
    <p class="answer">A: The Selection Committee selects two candidates for each vacancy and recommends these candidates to the Government.</p><br>

    <h2><b>Q: What is the timeline for the Selection Committee to make its recommendation?</b></h2><br>
    <p class="answer">A: The Selection Committee must make its recommendation to the Government within sixty days from the date of reference.</p><br>

 <h2><b>Q: What is the monthly salary of the Chairperson of the Appellate Tribunal?</b></h2><br>
    <p class="answer">A: The Chairperson of the Appellate Tribunal is paid a monthly salary equivalent to the last drawn salary as a Judge of a High Court.</p><br>

    <h2><b>Q: How is the salary of a Member of the Appellate Tribunal determined?</b></h2><br>
    <p class="answer">A: The Member is paid a monthly salary equivalent to the maximum of the scale of pay of an Additional Secretary to the Government of India. If the Member held a higher position in the Government before becoming a Member, the salary corresponding to the post at which they retired will be paid.</p><br>

    <h2><b>Q: Are there any specific leave entitlements for the Chairperson and Members?</b></h2><br>
    <p class="answer">A: Yes, both the Chairperson and Members are entitled to thirty days of earned leave for every completed year of service.</p><br>

    <h2><b>Q: What benefits are provided to the Chairperson and Members in terms of accommodation and transportation?</b></h2><br>
    <p class="answer">A: The Chairperson and Members are entitled to residential houses and vehicles as per their entitlement.</p><br>

    <h2><b>Q: Who determines the other allowances and conditions of service for the Chairperson and Members?</b></h2><br>
    <p class="answer">A: All other allowances and conditions of service are determined by the State Government from time to time.</p><br>


    <h2><b>Q: How are the conditions of service for officers and employees of the Appellate Tribunal regulated?</b></h2><br>
    <p class="answer">A: The conditions of service for officers and employees of the Appellate Tribunal, including aspects such as pay, allowances, leave, joining time, age of superannuation, and other service conditions, are regulated according to the rules and regulations applicable to officers and employees of the Government who draw corresponding scales of pay.</p><br>

    <h2><b>Q: Can the Government make exceptions to the rules governing the service conditions of the Appellate Tribunal’s officers and employees?</b></h2><br>
    <p class="answer">A: Yes, the Government has the power to relax the provisions of these rules for any class or category of officers or employees, as needed.</p><br>

<h2><b>Q: What additional powers does the Appellate Tribunal have beyond those specified in clause (g) of sub-section (4) of section 53?</b></h2><br>
    <p class="answer">A: In addition to the powers specified in clause (g) of sub-section (4) of section 53, the Appellate Tribunal has the authority to:</p>
    <ul class="answer">
        <li><strong>1. Request Information:</strong> Require the promoter(s), allottee(s), or real estate agent(s) to provide written information, explanations, or documents within a reasonable time as deemed necessary.</li>
        <li><strong>2. Engage Experts:</strong> Call upon experts or consultants from various fields, such as urban planning, economics, commerce, accountancy, real estate, competition, construction, architecture, law, or engineering, to assist in the conduct of any inquiry or proceedings before it.</li>
    </ul>
     <h2><b>Q: What are the administrative powers of the Chairperson of the Appellate Tribunal?</b></h2><br>
    <p class="answer">A: The Chairperson of the Appellate Tribunal has the following administrative powers:</p>
    <ul class="answer">
        <p><strong>1. Staff and Compensation Matters:</strong>
            <ul>
                <li><strong>1. Staff Strength and Salaries:</strong> Manage staff strength, wages, salary structures, emoluments, perquisites, and personnel policies, subject to prior Government approval.</li>
                <li><strong>2. Creation and Abolition of Posts:</strong> Handle matters related to the creation and abolition of posts with prior Government approval.</li>
                <li><strong>3. Appointments and Promotions:</strong> Oversee appointments, promotions, and confirmations for all posts with prior Government approval.</li>
            </ul>
        </p>
        <p><strong>2. Resignations and Tours:</strong>
            <ul>
                <li><strong>1. Acceptance of Resignations:</strong> Accept resignations from Members or officers, with prior Government approval.</li>
                <li><strong>2. Tour Authorization:</strong> Authorize tours for any Member, officer, or employee within and outside the State.</li>
            </ul>
        </p>
        <p><strong>3. Administrative and Financial Matters:</strong>
            <ul>
                <li><strong>1. Medical Claims:</strong> Handle matters related to the reimbursement of medical claims.</li>
                <li><strong>2. Leave Grants:</strong> Grant or reject leave requests.</li>
                <li><strong>3. Vehicle Hiring:</strong> Permit the hiring of vehicles for official use.</li>
                <li><strong>4. Nominations:</strong> Approve nominations for attending seminars, conferences, and training courses, both within and outside the State.</li>
            </ul>
        </p>
        <p><strong>4. Guest and Training Management:</strong>
            <ul>
                <li><strong>1. Guest Invitations:</strong> Grant permission for inviting guests or experts to conduct training courses.</li>
            </ul>
        </p>
        <p><strong>5. Staff Welfare and Assets:</strong>
            <ul>
                <li><strong>1. Welfare Expenses:</strong> Manage expenses related to staff welfare.</li>
                <li><strong>2. Capital Assets:</strong> Sanction new capital assets or authorize the scrapping/writing off of unserviceable or beyond-economical-repair assets.</li>
            </ul>
        </p>
        <p><strong>6. Disciplinary Actions:</strong>
            <ul>
                <li><strong>1. Disciplinary Actions:</strong> Handle all matters relating to disciplinary action against any officer or employee.</li>
            </ul>
        </p>
    </ul>

