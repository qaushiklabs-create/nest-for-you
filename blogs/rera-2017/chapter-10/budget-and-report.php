 <h2><b>Q: What is required of the Authority at the end of each financial year regarding budget and accounts?</b></h2><br>
    <p class="answer">A: At the end of each financial year, the Authority must:</p>
    <ul>
        <li><strong>1. Prepare a Budget:</strong> Develop an annual budget.</li>
        <li><strong>2. Maintain Accounts:</strong> Keep proper accounts and other relevant records.</li>
        <li><strong>3. Annual Statement of Accounts:</strong> Prepare an annual statement of accounts in Form ‘ASA’.</li>
    </ul>

    <h2><b>Q: How long must the Authority preserve its accounts and records?</b></h2><br>
    <p class="answer">A: The Authority must preserve the accounts and other relevant records for a minimum period of five years.</p><br>

    <h2><b>Q: Who must sign the accounts and other relevant records prepared by the Authority?</b></h2><br>
    <p class="answer">A: The accounts and other relevant records must be signed by:</p>
    <ul class="answer">
        <li>1. The Chairperson</li>
        <li>2. The Members</li>
        <li>3. The Secretary</li>
        <li>4. The officer in-charge of Finance and Accounts</li>
    </ul>

    <h2><b>Q: What should be done with the accounts of the Authority and the audit report?</b></h2><br>
    <p class="answer">A: The accounts and audit report must be submitted to the Government as soon as possible and then laid before the Parliament.</p><br>

 <h2><b>Q: What is the requirement for the Authority regarding the preparation of its annual report?</b></h2><br>
    <p class="answer">A: The Authority must prepare its annual report in Form ‘ARA’. Additionally, the Authority may include any other matters deemed fit for reporting to the Government.</p><br>

    <h2><b>Q: What steps must be followed for the annual report after its preparation?</b></h2><br>
    <p class="answer">A: The following steps must be taken:</p>
    <ul class="answer">
        <p><strong>Adoption:</strong> The annual report must be adopted at a meeting of the Authority.</p>
        <p><strong>Signing and Authentication:</strong> It must be signed by the Chairperson and Members and authenticated by affixing the common seal of the Authority.</p>
        <p><strong>Submission:</strong> The report, along with the requisite number of copies, must be submitted to the Government within one hundred and eighty days immediately following the close of the financial year for which the report is prepared.</p>
    </ul>

    <h2><b>Q: By when should the annual report be submitted to the Government?</b></h2><br>
    <p class="answer">A: The annual report must be submitted to the Government within one hundred and eighty days immediately following the close of the financial year for which it has been prepared.</p><br>



