<h2><b>What is Form ‘CAO’?</b></h2><br>
    <p class="answer">Form ‘CAO’ is used to file a complaint with an Adjudicating Officer, specifically for claims related to interest and compensation under sections 31 and 71 of the Real Estate (Regulation and Development) Act. This form is utilized when a complainant seeks compensation for delays or deficiencies in real estate transactions.</p><br>

    <h2><b>What details are required in the "Particulars of the Complainant(s)" section?</b></h2><br>
    <p class="answer">You need to provide:</p>
    <ul>
        <li>1. Name(s) of the complainant.</li>
        <li>2. Address of the existing office/residence of the complainant.</li>
        <li>3. Address for service of all notices.</li>
        <li>4. Contact Details (phone number, email, fax number, etc.).</li>
        <li>5. Details of the allottees such as the apartment, plot, or building involved.</li>
    </ul>

    <h2><b>What information should be included about the respondents?</b></h2>
    <p class="answer">The information required includes:</p>
    <ul>
        <li>1. Name(s) of the respondent.</li>
        <li>2. Office address of the respondent.</li>
        <li>3. Address for service of all notices.</li>
        <li>4. Contact Details (phone number, email, fax number, etc.).</li>
        <li>5. Registration number and address of the project.</li>
    </ul>

    <h2><b>How should you explain the "Facts of the Case"?</b></h2><br>
    <p class="answer">Provide a concise and clear statement of the facts and grounds for the claim. This should detail:</p>
    <ul>
        <li>1. The issues with the promoter.</li>
        <li>2. Specific instances or evidence of delays or deficiencies.</li>
        <li>3. Any contractual or regulatory breaches.</li>
    </ul>

    <h2><b>What should be included in the "Compensation(s) Sought" section?</b></h2><br>
    <p class="answer">Detail the compensation being sought, including:</p>
    <ul>
        <li>1. The specific amount or type of compensation requested.</li>
        <li>2. Grounds for the claim, including how the compensation amount was calculated.</li>
        <li>3. Legal provisions or regulations relied upon to support the claim.</li>
    </ul>

    <h2><b>What is the significance of the "Claim Not Pending with Any Other Court" declaration?</b></h2><br>
    <p class="answer">This declaration confirms that the issue raised in the complaint is not currently being addressed by any other court, authority, or tribunal. It ensures that the complaint is being handled exclusively by the Adjudicating Officer.</p><br>

    <h2><b>What details are needed regarding the fee payment?</b></h2><br>
    <p class="answer">Provide:</p>
    <ul>
        <li>1. Amount of the fee.</li>
        <li>2. Name of the bank where the demand draft or banker’s cheque is drawn, or details of online payment.</li>
        <li>3. Demand draft number, banker’s cheque number, or online payment transaction number.</li>
    </ul>

    <h2><b>What documents must be enclosed with the complaint?</b></h2><br>
    <p class="answer">The enclosures should include:</p>
    <ul>
        <li>1. Copies of documents relied upon and referred to in the complaint.</li>
        <li>2. An index of documents for reference.</li>
        <li>3. Other relevant documents as annexed with the complaint.</li>
    </ul>

    <h2><b>What is required in the "Verification" section?</b></h2><br>
    <p class="answer">The verification section requires:</p>
    <ul>
        <li>1. A statement confirming that the details provided in the form are true to the complainant’s knowledge and belief.</li>
        <li>2. The complainant’s signature and date.</li>
        <li>3. The complainant’s name in full block letters, with details of their relationship to the complaint.</li>
    </ul>

    <h2><b>What are the formatting and presentation requirements for Form ‘CAO’?</b></h2><br>
    <p class="answer">The complaint should be:</p>
    <ul>
        <li>1. Filed in English or accompanied by an English translation.</li>
        <li>2. Typewritten, lithographed, or printed in double spacing on one side of standard petition paper.</li>
        <li>3. With an inner margin of about 4 cm, right margin of 2.5 cm, and left margin of 5 cm.</li>
        <li>4. Paginated, indexed, and stitched together in paper book form.</li>
    </ul>

    <h2><b>What additional requirements are there for filing the complaint?</b></h2><br>
    <p class="answer">Along with the complaint, you need to provide:</p>
    <ul>
        <li>1. An empty file-size envelope with the full address of the respondent.</li>
        <li>2. Additional envelopes if there are multiple respondents.</li>
    </ul>
