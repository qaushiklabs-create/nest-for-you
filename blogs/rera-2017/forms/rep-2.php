<h2><b>Q1: What is Form ‘REP-II’?</b></h2>
    <p class="answer">A1: Form ‘REP-II’ is a declaration, supported by an affidavit, required for the registration of a real estate project. It must be signed by the promoter or an authorized person representing the promoter.</p>

    <h2><b>Q2: Who should sign Form ‘REP-II’?</b></h2><br>
    <p class="answer">A2: The form should be signed by the promoter of the proposed project or a person duly authorized by the promoter. The authorization should be dated and included in the form.</p><br>

    <h2><b>Q3: What must the promoter declare about the land title?</b></h2><br>
    <p class="answer">A3: The promoter must declare:</p>
    <ul class="answer">
        <li><strong>1. Land Title:</strong> Whether they have a legal title to the land or if someone else holds the title. If the promoter is not the owner, they must provide details of the owner’s consent and any relevant agreements or documents.</li>
    </ul>

    <h2><b>Q4: What should the promoter declare about encumbrances on the land?</b></h2><br>
    <p class="answer">A4: The promoter must state that the land is free from encumbrances or provide details of any encumbrances, including rights, titles, interests, dues, or ongoing litigation.</p><br>

    <h2><b>Q5: What is required regarding the project completion timeline‘REP-II’?</b></h2><br>
    <p class="answer">A5: The promoter must declare the time period within which the project will be completed.</p><br>

    <h2><b>Q6: How should funds from allottees be managed according to the declaration?</b></h2><br>
    <p class="answer">A6: The promoter must declare that seventy percent of the amounts realized from allottees will be deposited into a separate account maintained in a scheduled bank. This account will cover construction and land costs and the funds will be used only for this purpose.</p><br>

    <h2><b>Q7: How should withdrawals from the separate account be managed‘REP-II’?</b></h2><br>
    <p class="answer">A7: Withdrawals from the separate account should be proportional to the project's percentage of completion. The promoter must ensure that withdrawals are certified by an engineer, architect, and a chartered accountant to match the project's progress.</p><br>

    <h2><b>Q8: What are the auditing requirements for the project funds‘REP-II’?</b></h2><br>
    <p class="answer">A8: The promoter must get the accounts audited within six months after the end of each financial year by a practicing chartered accountant. The audit must confirm that funds were used for the project and withdrawals were proportional to the project's completion.</p><br>

    <h2><b>Q9: What must the promoter do regarding pending approvals?</b></h2><br>
    <p class="answer">A9: The promoter must ensure that all pending approvals from competent authorities are obtained in a timely manner.</p><br>

    <h2><b>Q: What other documents or compliance is required from the promoter?</b></h2><br>
    <p class="answer">A: The promoter must provide all other documents as prescribed by the Act and the associated rules and regulations.</p><br>

    <h2><b>Q: What is the stance on discrimination in allotment‘REP-II’?</b></h2><br>
    <p class="answer">A: The promoter must declare that they will not discriminate against any allottee on the grounds of sex, caste, creed, religion, etc., during the allotment of apartments, plots, or buildings.</p><br>

    <h2><b>Q: What is included in the verification section of Form ‘REP-II’?</b></h2><br>
    <p class="answer">A: The verification section requires the deponent to affirm that the contents of the affidavit are true and correct, and that no material information has been concealed. The place and date of verification must be mentioned.</p><br>


