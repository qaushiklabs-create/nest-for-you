 <h2><b>Q: What is Form ‘REP-IV’?</b></h2><br>
    <p class="answer">A: Form ‘REP-IV’ is an official communication from the Real Estate Authority that informs a promoter of the rejection of an application for project registration, extension of registration, or the revocation of an existing project registration.</p><br>

    <h2><b>Q: What are the possible reasons for receiving Form ‘REP-IV’?</b></h2><br>
    <p class="answer">A: You might receive Form ‘REP-IV’ for one of the following reasons:</p>
    <ul>
        <li>1. Rejection of your application for the registration of a new project.</li>
        <li>2. Rejection of your application for an extension of an existing project's registration.</li>
        <li>3. Revocation of an existing project registration.</li>
    </ul>

    <h2><b>Q: What details are included in Form ‘REP-IV’?</b></h2><br>
    <p class="answer">A: Form ‘REP-IV’ includes:</p>
    <ul>
        <li>1. The name and address of the Real Estate Authority issuing the notice.</li>
        <li>2. The name and address of the recipient.</li>
        <li>3. The application or registration number.</li>
        <li>4. The date of the communication.</li>
        <li>5. A statement indicating whether the application is rejected or the registration is revoked.</li>
        <li>6. The reasons for the rejection or revocation.</li>
    </ul>

    <h2><b>Q: How should the reasons for rejection or revocation be provided?</b></h2><br>
    <p class="answer">A: The form includes a section where the reasons for the rejection of the application or the revocation of the registration are clearly stated. This provides the promoter with an explanation for the decision.</p><br>

    <h2><b>Q: What information is required to be filled in the "Place" and "Date" sections?</b></h2><br>
    <p class="answer">A: The "Place" section should specify where the form is issued from, and the "Date" section should indicate the date on which the intimation is sent.</p><br>

    <h2><b>Q: Who signs Form ‘REP-IV’?</b></h2><br>
    <p class="answer">A: Form ‘REP-IV’ is signed and sealed by an authorized officer of the Real Estate Authority.</p><br>

    <h2><b>Q: What should a promoter do upon receiving Form ‘REP-IV’?</b></h2><br>
    <p class="answer">A: Upon receiving Form ‘REP-IV’, the promoter should:</p>
    <ul>
        <li>1. Review the reasons for rejection or revocation provided in the form.</li>
        <li>2. Address the issues or reasons cited to potentially resolve the matter, if applicable.</li>
        <li>3. Consult legal or professional advice if needed to understand the implications and possible actions to be taken.</li>
    </ul>
