 <h2><b>Q: What is Form ‘REA-II’?</b></h2><br>
    <p class="answer">A: Form ‘REA-II’ is the certificate issued to a real estate agent upon approval of their registration application. It authorizes the agent to facilitate the sale or purchase of properties in real estate projects registered under the relevant real estate regulations.</p><br>

    <h2><b>Q: What details are included in Form ‘REA-II’?</b></h2><br>
    <p class="answer">A: Form ‘REA-II’ includes:</p>
    <ul>
        <li><strong>1. Registration Details:</strong>
            <ul>
                <li>Name and details of the individual or firm granted registration.</li>
                <li>Registration number and the effective date of registration.</li>
            </ul>
        </li>
        <li><strong>2. Conditions of Registration:</strong> Obligations and restrictions imposed on the real estate agent.</li>
        <li><strong>3. Validity Period:</strong> The duration for which the registration is valid.</li>
        <li><strong>4. Consequences of Non-Compliance:</strong> Potential actions that may be taken by the authority if the conditions are not met.</li>
    </ul>

    <h2><b>Q: What are the conditions mentioned in Form ‘REA-II’?</b></h2><br>
    <p class="answer">A: The conditions for the real estate agent include:</p>
    <ul>
        <li><strong>1. Registration Compliance:</strong> The agent must not facilitate transactions involving properties not registered with the Authority.</li>
        <li><strong>2. Record Keeping:</strong> Maintenance and preservation of books of account and records.</li>
        <li><strong>3. Fair Trade Practices:</strong> Avoidance of unfair trade practices as defined under the Act.</li>
        <li><strong>4. Provision of Information:</strong> Ensuring the allottee receives all necessary information and documents.</li>
        <li><strong>5. Assistance to Allottees and Promoters:</strong> Helping both parties exercise their rights and fulfill obligations during transactions.</li>
        <li><strong>6. Compliance with Regulations:</strong> Adherence to the Act and other applicable laws.</li>
        <li><strong>7. Other Functions:</strong> Performing additional functions as specified by the Authority.</li>
    </ul>

    <h2><b>Q: How long is the registration valid according to Form ‘REA-II’?</b></h2><br>
    <p class="answer">A: The registration is valid for a period of five years from the date specified in the certificate, unless renewed by the Authority.</p><br>

    <h2><b>Q: What happens if the real estate agent does not fulfill the conditions?</b></h2><br>
    <p class="answer">A: If the conditions are not met, the Authority may take necessary actions against the real estate agent, including the possibility of revoking the registration.</p><br>

    <h2><b>Q: What is required to renew the registration?</b></h2><br>
    <p class="answer">A: To renew the registration, the agent must apply to the Authority before the registration expires and comply with any requirements specified by the Act or rules and regulations made thereunder.</p><br>

    <h2><b>Q: How is Form ‘REA-II’ issued and what should be checked?</b></h2><br>
    <p class="answer">A: Form ‘REA-II’ is issued by the Real Estate Authority once the registration application is approved. Ensure all details are correct, including the name, registration number, and validity dates, and that it includes the Authority’s signature and seal.</p><br>

    <h2><b>Q: Where should Form ‘REA-II’ be displayed?</b></h2><br>
    <p class="answer">A: The registered real estate agent should display Form ‘REA-II’ at their place of business to show their authorized status.</p>
