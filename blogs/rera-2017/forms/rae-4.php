<h2><b>Q: What is Form ‘REA-IV’?</b></h2><br>
    <p class="answer">A: Form ‘REA-IV’ is an application form used by a real estate agent to apply for the renewal of their registration with the Real Estate Authority. It ensures the continuation of their registration after the initial certificate expires.</p><br>

    <h2><b>Q: What details are required in Form ‘REA-IV’?</b></h2><br>
    <p class="answer">A: Form ‘REA-IV’ requires the following details and documents:</p>
    <ul>
        <li><strong>1. Applicant Details:</strong>
            <ul>
                <li><strong>Individual:</strong> Name, father’s name, occupation, address, and contact details.</li>
                <li><strong>Firm/Society/Company:</strong> Name, address, registration certificate, major activities, contact details, and details of partners/directors.</li>
            </ul>
        </li>
        <li><strong>2. Registration Information:</strong> Registration certificate number and expiry date.</li>
        <li><strong>3. Documents to be Submitted:</strong>
            <ul>
                <li><strong>Payment Proof:</strong> Demand draft/bankers cheque or online payment details for the renewal fee.</li>
                <li><strong>Authenticated Copies:</strong> Registration certificate, address proof of the business, PAN card, and any registration in other states or territories if applicable.</li>
                <li><strong>Additional Information:</strong> As specified by regulations.</li>
            </ul>
        </li>
    </ul>

    <h2><b>Q: How should the payment for the renewal fee be made?</b></h2><br>
    <p class="answer">A: The payment should be made via:</p>
    <ul>
        <li><strong>1. Demand Draft/Bankers Cheque:</strong> Drawn in favor of “Haryana Real Estate Regulatory Authority.”</li>
        <li><strong>2. Online Payment:</strong> Provide details such as date paid, transaction number, and any confirmation of the payment.</li>
    </ul>

    <h2><b>Q: What is the significance of including a photograph of the proprietor or partners/directors?</b></h2><br>
    <p class="answer">A: The photograph is used for identification and verification purposes, ensuring that the details provided in the application are accurate and match the individual or representatives of the firm/company.</p><br>

    <h2><b>Q: What does the affirmation and declaration section of Form ‘REA-IV’ entail?</b></h2><br>
    <p class="answer">A: The affirmation and declaration section is a statement by the applicant affirming that all the details provided in the application are accurate and complete. It ensures that no material information has been omitted or concealed.</p><br>

    <h2><b>Q: What should be done if any of the documents or details change after the renewal application is submitted?</b></h2><br>
    <p class="answer">A: If there are any changes in the documents or details after submission, the applicant should promptly inform the Real Estate Authority and provide updated information or documents as required.</p><br>

    <h2><b>Q: What happens if the renewal application is rejected?</b></h2><br>
    <p class="answer">A: If the renewal application is rejected, the Real Estate Authority will issue a notice stating the reasons for rejection. The applicant will need to address these issues and may need to reapply or take corrective action as specified in the notice.</p><br>

    <h2><b>Q: How is Form ‘REA-IV’ submitted?</b></h2><br>
    <p class="answer">A: Form ‘REA-IV’ is typically submitted:</p>
    <ul>
        <li><strong>1. In Person:</strong> Directly to the Real Estate Authority’s office.</li>
        <li><strong>2. By Post:</strong> Mailed to the address of the Real Estate Authority.</li>
        <li><strong>3. Online:</strong> If an online submission process is available and applicable.</li>
    </ul>

    <h2><b>Q: How long before the expiry of the registration should Form ‘REA-IV’ be submitted?</b></h2><br>
    <p class="answer">A: It is advisable to submit the renewal application well before the registration expires to ensure there is no lapse in registration. Typically, a few months prior to the expiry date is recommended.</p><br>

   
