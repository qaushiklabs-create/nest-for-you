 <h2><b>Q: What is Form ‘REA-V’?</b></h2><br>
    <p class="answer">A: Form ‘REA-V’ is used to issue a renewal certificate for a real estate agent's registration under section 9 of the Real Estate Act. It continues the agent's authorization to operate and facilitate real estate transactions.</p><br>

    <h2><b>Q: What details are included in Form ‘REA-V’?</b></h2><br>
    <p class="answer">A: Form ‘REA-V’ includes the following details:</p>
    <ul>
        <li><strong>Recipient Information:</strong>
            <ul>
                <li><strong>For an individual:</strong> Name, father’s name, Tehsil, District, and State.</li>
                <li><strong>For a firm/society/company:</strong> Name and address of the firm/society/company.</li>
            </ul>
        </li>
        <li><strong>Registration Details:</strong> Renewal of registration with reference to the previous registration certificate number and date.</li>
        <li><strong>Conditions for Renewal:</strong>
            <ul>
                <li>Compliance with the Act and regulations.</li>
                <li>Maintenance of records and documents.</li>
                <li>Prohibition of unfair trade practices.</li>
                <li>Facilitation of necessary information to allottees.</li>
                <li>Assistance in the exercise of rights and obligations during transactions.</li>
            </ul>
        </li>
        <li><strong>Validity Period:</strong> The renewal is valid for five years, with specific start and end dates.</li>
        <li><strong>Compliance Warning:</strong> The Authority may take action, including revocation of registration, if conditions are not met.</li>
    </ul>

    <h2><b>Q: What are the conditions mentioned in Form ‘REA-V’ for the renewal of registration?</b></h2><br>
    <p class="answer">A: The conditions include:</p>
    <ul>
        <li><strong>Non-facilitation of Unregistered Projects:</strong> Agents must not handle transactions for projects not registered with the Authority.</li>
        <li><strong>Maintenance of Records:</strong> Agents must maintain and preserve accounts and documents as required by the rules.</li>
        <li><strong>Avoidance of Unfair Trade Practices:</strong> Compliance with fair trade practices and prohibition of unfair practices.</li>
        <li><strong>Provision of Information:</strong> Agents must provide all relevant information and documents to the allottees at the time of booking.</li>
        <li><strong>Assistance in Transactions:</strong> Helping allottees and promoters exercise their rights and fulfill their obligations.</li>
        <li><strong>Compliance with Legal Provisions:</strong> Adherence to the Act, rules, and any other applicable laws.</li>
        <li><strong>Additional Functions:</strong> Performing any additional functions as specified by the Authority.</li>
    </ul>

    <h2><b>Q: What happens if the conditions in Form ‘REA-V’ are not fulfilled?</b></h2><br>
    <p class="answer">A: If the conditions are not fulfilled, the Real Estate Authority may take necessary action, including the possibility of revoking the renewal of registration.</p><br>

    <h2><b>Q: How long is the registration valid under Form ‘REA-V’?</b></h2><br>
    <p class="answer">A: The registration is valid for a period of five years from the date specified in the form, unless renewed again by the Authority.</p><br>

    <h2><b>Q: How is Form ‘REA-V’ issued?</b></h2><br>
    <p class="answer">A: Form ‘REA-V’ is issued by the Real Estate Authority once the renewal application is approved. It is typically signed and sealed by an authorized officer of the Authority.</p><br>

    <h2><b>Q: What should an agent do if they wish to continue operating beyond the five-year validity period?</b></h2><br>
    <p class="answer">A: The agent must apply for renewal of registration before the expiry of the current registration period, following the process outlined in Form ‘REA-IV’ and providing all required documents and fees.</p><br>

    <h2><b>Q: What are the consequences of not renewing the registration on time?</b></h2><br>
    <p class="answer">A: If the registration is not renewed on time, the real estate agent may not be legally permitted to facilitate real estate transactions, potentially leading to legal consequences and loss of business opportunities.</p><br>

   
