  <h2><b>Q: What is Form ‘REP-III’?</b></h2><br>
    <p class="answer">A: Form ‘REP-III’ is the Registration Certificate granted to a real estate project under section 5 of the Haryana Real Estate (Regulation and Development) Act, 2016. It officially registers the project with the Real Estate Authority.</p><br>

    <h2><b>Q: What details must be specified in Form ‘REP-III’?</b></h2><br>
    <p class="answer">A: The certificate must specify:</p>
    <ul>
        <li>1. The project registration number.</li>
        <li>2. Full details of the project, including its address.</li>
        <li>3. In case of an individual: Name, father's name, and location details.</li>
        <li>4. In case of a firm, society, company, or competent authority: Name and registered office address.</li>
    </ul>

    <h2><b>Q: What conditions are attached to the registration‘REP-III’?</b></h2><br>
    <p class="answer">A: The registration is granted subject to several conditions, including:</p>
    <ul>
        <li>1. Entering into an agreement for sale with allottees as per government guidelines.</li>
        <li>2. Offering to execute and register a conveyance deed for the unit, apartment, plot, or building.</li>
        <li>3. Conveying or allowing usage of common areas as per HRERA Rules.</li>
        <li>4. Depositing seventy percent of the amounts realized in a separate account for construction and land costs.</li>
        <li>5. Registration validity for a specified period unless extended.</li>
        <li>6. Compliance with applicable Acts, rules, and regulations.</li>
        <li>7. Not contravening any other applicable laws.</li>
        <li>8. Complying with all other terms and conditions as conveyed by the Authority.</li>
    </ul>

    <h2><b>Q: What is the validity period of the registration‘REP-III’?</b></h2><br>
    <p class="answer">A: The registration is valid for a specified period starting from a given date and ending on another date. The exact duration is mentioned in the certificate and may be extended by the Authority as needed.</p><br>

    <h2><b>Q: What actions can the Authority take if the conditions are not fulfilled‘REP-III’?</b></h2><br>
    <p class="answer">A: If the promoter fails to meet the conditions, the Authority may take necessary actions, including revoking the registration granted, in accordance with the Act and applicable rules and regulations.</p><br>

    <h2><b>Q: Who signs Form ‘REP-III’?</b></h2><br>
    <p class="answer">A: Form ‘REP-III’ is signed and sealed by an authorized officer of the Real Estate Authority.</p><br>

    <h2><b>Q: What information should be included in the “Dated” and “Place” sections?</b></h2><br>
    <p class="answer">A: The “Dated” section should include the date on which the registration certificate is issued, and the “Place” section should specify the location where the certificate is issued.</p><br>



