    <h2><b>Q: What is Form ‘REP-V’?</b></h2><br>
    <p class="answer">A: Form ‘REP-V’ is an application used to request an extension of the registration for a real estate project. It is submitted to the Real Estate Authority when the initial registration period is about to expire and the promoter seeks additional time to complete the project.</p><br>

    <h2><b>Q: What information needs to be provided in the application‘REP-V’?</b></h2><br>
    <p class="answer">A: The application should include:</p>
    <ul>
        <li>1. The project details, including the name and registration certificate number.</li>
        <li>2. The expiry date of the current registration.</li>
    </ul>

    <h2><b>Q: What documents and information must be submitted with Form ‘REP-V’?</b></h2><br>
    <p class="answer">A: The following documents and information must be included:</p>
    <ul>
        <li><strong>1. Extension Fee Payment:</strong> A demand draft or banker’s cheque in favor of “Haryana Real Estate Regulatory Authority,” or details of online payment including date and transaction number.</li>
        <li><strong>2. Project Plan:</strong> Authenticated plan of the project showing the current stage of development or construction works.</li>
        <li><strong>3. Explanatory Note:</strong> An explanation of the state of development and reasons for not completing the project within the originally declared timeline.</li>
        <li><strong>4. Valid Permissions/Approvals:</strong> Authenticated copy of permissions or approvals from the competent authority, valid for the extended period.</li>
        <li><strong>5. Original Registration Certificate:</strong> The original project registration certificate.</li>
        <li><strong>6. Additional Information:</strong> Any other information specified by regulations, if applicable.</li>
    </ul>

    <h2><b>Q: How should the extension fee be paid‘REP-V’?</b></h2><br>
    <p class="answer">A: The extension fee can be paid by:</p>
    <ul>
        <li>1. A demand draft or banker’s cheque drawn in favor of “Haryana Real Estate Regulatory Authority.”</li>
        <li>2. Online payment, with details such as date of payment and transaction number provided.</li>
    </ul>

    <h2><b>Q: What details should be included in the explanatory note?</b></h2><br>
    <p class="answer">A: The explanatory note should cover:</p>
    <ul>
        <li>1. The current status of development or construction.</li>
        <li>2. Reasons for delays or reasons for not completing the project within the originally declared period.</li>
    </ul>

    <h2><b>Q: What is the importance of the authenticated project plan‘REP-V’?</b></h2><br>
    <p class="answer">A: The authenticated project plan is crucial as it shows the current stage of development and construction. It helps the Real Estate Authority assess the progress and understand the scope of work completed.</p><br>

    <h2><b>Q: What should be done with the original project registration certificate?</b></h2><br>
    <p class="answer">A: The original project registration certificate should be submitted along with the application for extension. This allows the Authority to update or extend the registration details accordingly.</p><br>

    <h2><b>Q: Where should the application be sent?</b></h2><br>
    <p class="answer">A: The application should be sent to the Real Estate Authority, with the address provided on the form.</p><br>

    <h2><b>Q: What should be included in the “Place” and “Date” sections‘REP-V’?</b></h2><br>
    <p class="answer">A:</p>
    <ul>
        <li><strong>1. Place:</strong> The location where the application is being submitted.</li>
        <li><strong>2. Date:</strong> The date on which the application is being completed and signed.</li>
    </ul>
