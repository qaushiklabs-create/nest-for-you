<h2><b>Q: What is Form ‘REP-VI’?</b></h2><br>
    <p class="answer">A: Form ‘REP-VI’ is the official certificate issued by the Real Estate Authority granting an extension to the registration of a real estate project. This form extends the validity of the project registration beyond the original expiration date.</p><br>

    <h2><b>Q: What information must be included in Form ‘REP-VI’?</b></h2><br>
    <p class="answer">A: The certificate must include:</p>
    <ul>
        <li>1. The name of the project and its registration certificate number.</li>
        <li>2. The details of the promoter, including whether they are an individual or an entity such as a firm or company.</li>
        <li>3. The period of extension granted and the new validity date of the registration.</li>
    </ul>

    <h2><b>Q: What conditions are attached to the extension of registration?</b></h2><br>
    <p class="answer">A: The extension of registration is granted subject to the following conditions:</p>
    <ul>
        <li><strong>1. Conveyance Deed:</strong> The promoter must offer to execute and register a conveyance deed for the Plot/Unit/Apartment, including parking if applicable.</li>
        <li><strong>2. Separate Account:</strong> Seventy percent of the amounts realized must be deposited in a separate bank account to cover construction and land costs.</li>
        <li><strong>3. Extended Validity:</strong> The registration is extended by a specified period and is valid until a new date.</li>
        <li><strong>4. Compliance:</strong> The promoter must comply with the provisions of the Act and applicable rules and regulations.</li>
        <li><strong>5. Legal Compliance:</strong> The promoter must not contravene any other laws applicable to the project.</li>
        <li><strong>6. Revocation:</strong> If conditions are not met, the Authority may take action, including revoking the registration.</li>
    </ul>

    <h2><b>Q: How is the period of extension specified?</b></h2><br>
    <p class="answer">A: The extension period is specified in days, weeks, or months, and the new end date of the registration is also provided.</p><br>

    <h2><b>Q: What should be done if the conditions of the extension are not fulfilled?</b></h2><br>
    <p class="answer">A: If the promoter fails to meet the conditions outlined in the certificate, the Real Estate Authority may take necessary actions, including potentially revoking the extended registration.</p><br>

    <h2><b>Q: Who signs Form ‘REP-VI’?</b></h2><br>
    <p class="answer">A: Form ‘REP-VI’ is signed and sealed by an authorized officer of the Real Estate Authority.</p><br>

    <h2><b>Q: What should be included in the “Dated” and “Place” sections?</b></h2><br>
    <p class="answer">A:</p>
    <ul>
        <li><strong>1. Date:</strong> The date on which the certificate is issued.</li>
        <li><strong>2. Place:</strong> The location where the certificate is issued from.</li>
    </ul>

    <h2><b>Q: What steps should a promoter take after receiving Form ‘REP-VI’?</b></h2><br>
    <p class="answer">A: After receiving Form ‘REP-VI’, the promoter should:</p>
    <ul>
        <li>1. Review and understand the conditions attached to the extension.</li>
        <li>2. Ensure compliance with all specified conditions.</li>
        <li>3. Continue project development according to the extended timeline.</li>
        <li>4. Maintain proper records and documentation as required.</li>
    </ul>
   
