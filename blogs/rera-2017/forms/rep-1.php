 <h2><b>Q: What is Form ‘REP-I’?</b></h2><br>
    <p class="answer">A: Form ‘REP-I’ is an application used to seek registration for a real estate project with the Real Estate Authority in Haryana. It ensures compliance with the regulatory requirements set under the Haryana Real Estate (Regulation and Development) Act, 2016.</p><br>

    <h2><b>Q: To whom should the application be addressed ‘REP-I’?</b></h2><br>
    <p class="answer">A: The application should be addressed to <strong>The Real Estate Authority, Haryana.</strong></p><br>

    <h2><b>Q: What details are required about the applicant ‘REP-I’?</b></h2><br>
    <p class="answer">A: The details required include:</p>
    <ul class="answer">
        <li><strong>1. Status of the applicant:</strong> Individual, company, proprietorship firm, etc.</li>
        <li><strong>2. For an individual:</strong> Name, father’s name, occupation, address, contact details, and promoter’s details.</li>
        <li><strong>3. For firms/societies/companies:</strong> Name, address, registration certificate, main objects, contact details, and details of authorized persons.</li>
    </ul>

    <h2><b>Q: What financial information must be provided ‘REP-I’?</b></h2><br>
    <p class="answer">A: You need to provide:</p>
    <ul class="answer">
        <li><strong>1. PAN Number:</strong> The PAN number of the promoter.</li>
        <li><strong>2. Bank Details:</strong> Details of the bank where the project account will be maintained.</li>
    </ul>

    <h2><b>Q: What should be included about the project land ‘REP-I’?</b></h2><br>
    <p class="answer">A: You need to include:</p>
    <ul class="answer">
        <li><strong>1. Land Details:</strong> Details of the land held by the applicant.</li>
        <li><strong>2. Encumbrances:</strong> Information about encumbrances or no encumbrance certificate.</li>
        <li><strong>3. Landowner Consent:</strong> If the applicant isn’t the landowner, consent details and agreements with the landowner.</li>
    </ul>

    <h2><b>Q: What information about previous projects should be provided ‘REP-I’?</b></h2><br>
    <p class="answer">A: Provide brief details of projects launched in the last five years, including their current status, any delays, pending cases, and type of land and payments pending.</p><br>

    <h2><b>Q: What are the registration fee payment options ‘REP-I’?</b></h2><br>
    <p class="answer">A: The registration fee can be paid by demand draft/banker’s cheque in favor of <strong>“Haryana Real Estate Regulatory Authority”</strong> or through online payment. Provide the relevant details or transaction number.</p><br>

    <h2><b>Q: What documents need to be enclosed with the application ‘REP-I’?</b></h2><br>
    <p class="answer">A: Required documents include:</p>
    <ul class="answer">
        <li><strong>1. PAN Card:</strong> Authenticated copy of the PAN card of the promoter.</li>
        <li><strong>2. Financial Statements:</strong> Annual reports or financial statements for the last three years.</li>
        <li><strong>3. Title Deeds:</strong> Title deeds and land encumbrance details.</li>
        <li><strong>4. Permissions and Licenses:</strong> Legal permissions, licenses, and plans related to the project.</li>
        <li><strong>5. Project Plans:</strong> Site and layout plans, floor plans, and details of amenities.</li>
        <li><strong>6. Agreements:</strong> Agreements and proposed documents for sale and allotment.</li>
        <li><strong>7. Involved Parties:</strong> Details about parking spaces, real estate agents, contractors, and others involved.</li>
    </ul>

    <h2><b>Q: What additional documents and information are needed for ongoing projects ‘REP-I’?</b></h2><br>
    <p class="answer">A: Additional documents and information as required under rule 4 and other provisions of the Act or regulations should be enclosed, which may include updated project details, compliance documents, etc.</p><br>

    <h2><b>Q: What declaration is required at the end of the application ‘REP-I’?</b></h2><br>
    <p class="answer">A: A solemn affirmation and declaration must be made confirming that the particulars provided are correct to the best of the applicant’s knowledge and that no material information has been concealed.</p><br>

    <h2><b>Q: Where and when should the application be submitted ‘REP-I’?</b></h2><br>
    <p class="answer">A: The application should be submitted to <strong>The Real Estate Authority, Haryana.</strong> The date and place should be mentioned at the end of the application form.</p><br>



