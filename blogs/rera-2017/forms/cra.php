 <h2><b>What is Form ‘CRA’?</b></h2><br>
    <p class="answer">Form ‘CRA’ is used to file a complaint with the Real Estate Regulatory Authority. It is intended for individuals or entities to formally raise grievances or issues related to real estate projects or transactions that fall under the jurisdiction of the Authority.</p><br>

    <h2><b>What information must be included in Form ‘CRA’?</b></h2><br>
    <p class="answer">The following information is required:</p>
    <ul>
        <li><b>Particulars of the Complainant(s):</b>
            <ul>
                <li>Name(s), address, and contact details.</li>
                <li>Address for service of notices.</li>
            </ul>
        </li>
        <li><b>Particulars of the Respondent(s):</b>
            <ul>
                <li>Name(s), office address, and contact details.</li>
                <li>Address for service of notices.</li>
            </ul>
        </li>
        <li><b>Jurisdiction:</b> Declaration that the complaint falls within the Authority’s jurisdiction.</li>
        <li><b>Facts of the Case:</b> A concise statement of the facts and grounds for the complaint.</li>
        <li><b>Reliefs Sought:</b> Specific reliefs the complainant is seeking and the grounds for these claims, including any legal provisions relied upon.</li>
        <li><b>Interim Order:</b> Request for any interim orders pending the final decision and reasons for the request.</li>
        <li><b>Pending Matters:</b> Declaration that the complaint is not pending before any other court or authority.</li>
        <li><b>Fee Details:</b> Details of the fee payment (demand draft, banker’s cheque, or online payment).</li>
        <li><b>List of Enclosures:</b> Documents relied upon, index of documents, and any other relevant documents.</li>
    </ul>

    <h2><b>What should be included in the "Facts of the Case" section?</b></h2><br>
    <p class="answer">This section should include:</p>
    <ul>
        <li>A clear and concise statement of the relevant facts.</li>
        <li>The grounds for the complaint, explaining the issues in detail.</li>
        <li>Specific reference to any applicable sections of the Real Estate (Regulation and Development) Act or related regulations.</li>
    </ul>

    <h2><b>What are the requirements for filing Form ‘CRA’?</b></h2><br>
    <p class="answer">Requirements include:</p>
    <ul>
        <li>The complaint must be in English or accompanied by an English translation if in another Indian language.</li>
        <li>It should be typewritten or printed in double spacing, with specified margins.</li>
        <li>The complaint must be paginated, indexed, and stitched in paper book form.</li>
        <li>An empty file-size envelope with the respondent’s address must be provided.</li>
        <li>Additional envelopes are required if there are multiple respondents.</li>
    </ul>

    <h2><b>What should be included in the "Reliefs Sought" section?</b></h2><br>
    <p class="answer">In this section:</p>
    <ul>
        <li>Clearly specify the reliefs being sought.</li>
        <li>Explain the grounds for each relief and reference any relevant legal provisions or regulations that support the request.</li>
    </ul>

    <h2><b>What is the purpose of the "Interim Order" section?</b></h2><br>
    <p class="answer">The "Interim Order" section is where the complainant can request temporary measures or orders to address immediate concerns or prevent further issues while the complaint is being reviewed. The complainant must provide reasons for requesting such orders.</p><br>

    <h2><b>What is the significance of the verification section in Form ‘CRA’?</b></h2><br>
    <p class="answer">The verification section is a formal declaration by the complainant affirming that the information provided in the form is true and complete to their knowledge. It confirms that no material facts have been concealed.</p><br>

    <h2><b>What documents are required to be enclosed with the complaint?</b></h2><br>
    <p class="answer">Required enclosures include:</p>
    <ul>
        <li>Copies of documents relied upon and referenced in the complaint.</li>
        <li>An index of documents.</li>
        <li>Any other relevant documents as mentioned in the complaint.</li>
    </ul>

    <h2><b>How should the appeal be presented?</b></h2><br>
    <p class="answer">The complaint should be:</p>
    <ul>
        <li>Fairly and legibly typewritten or printed.</li>
        <li>Paginated and indexed.</li>
        <li>Presented along with an empty envelope with the respondent’s address and additional envelopes if there are multiple respondents.</li>
    </ul>


