 <h2><b>Q: What is Form ‘REA-I’?</b></h2><br>
    <p class="answer">A: Form ‘REA-I’ is the application used to request registration as a real estate agent. This registration allows the agent to facilitate the sale or purchase of real estate properties in projects that are registered under the Real Estate (Regulation and Development) Act.</p><br>

    <h2><b>Q: What information must be provided in Form ‘REA-I’?</b></h2><br>
    <p class="answer">A: The form requires the following information:</p>
    <ul>
        <li><strong>1. Applicant Details:</strong>
            <ul>
                <li><strong>1. For an Individual:</strong> Name, father’s name, occupation, address, and contact details.</li>
                <li><strong>2. For a Firm/Society/Company:</strong> Name, address, registration certificate, major activities, contact details, and details of partners or directors.</li>
            </ul>
        </li>
        <li><strong>2. Status of the Applicant:</strong> Whether the applicant is an individual, company, proprietorship firm, society, partnership firm, or limited liability partnership.</li>
        <li><strong>3. Business Information:</strong> Details about the applicant’s registration and organizational documents, such as bye-laws or articles of association.</li>
        <li><strong>4. Proofs and Documents:</strong> Address proof of the place of business and details of registration in other states or union territories, if applicable.</li>
    </ul>

    <h2><b>Q: What documents are required to be submitted with Form ‘REA-I’?</b></h2><br>
    <p class="answer">A: The following documents must be submitted:</p>
    <ul>
        <li><strong>1. Registration Fee:</strong> Demand draft or banker’s cheque for the specified amount in favor of “Haryana Real Estate Regulatory Authority,” or details of online payment including transaction number.</li>
        <li><strong>2. PAN Card:</strong> Authenticated copy of the PAN card of the real estate agent.</li>
        <li><strong>3. Other Registrations:</strong> Authenticated copy of registration as a real estate agent in any other state or union territory, if applicable.</li>
    </ul>

    <h2><b>Q: How should the registration fee be paid?</b></h2><br>
    <p class="answer">A: The registration fee can be paid via:</p>
    <ul>
        <li><strong>1. Demand Draft or Banker’s Cheque:</strong> Drawn in favor of “Haryana Real Estate Regulatory Authority.”</li>
        <li><strong>2. Online Payment:</strong> Provide details such as date of payment and transaction number.</li>
    </ul>

    <h2><b>Q: What is required in the “Status of the Applicant” section?</b></h2><br>
    <p class="answer">A: You need to specify whether the applicant is an individual, company, proprietorship firm, society, partnership firm, or limited liability partnership. Provide relevant details based on the type of applicant.</p><br>

    <h2><b>Q: What is the purpose of the authenticated copy of the PAN card?</b></h2><br>
    <p class="answer">A: The authenticated copy of the PAN card serves as a verification of the applicant’s identity and financial credibility.</p><br>

    <h2><b>Q: What should be included in the “Details of registration in any other State or Union Territory” section?</b></h2><br>
    <p class="answer">A: If the applicant is already registered as a real estate agent in another state or union territory, provide details and an authenticated copy of that registration.</p><br>

    <h2><b>Q: What should be included in the “Business Information” section?</b></h2><br>
    <p class="answer">A: Include details about the applicant’s registration status, such as:</p>
    <ul>
        <li>1. Organizational documents (bye-laws, memorandum of association, articles of association).</li>
        <li>2. Proof of address of the business premises.</li>
    </ul>

    <h2><b>Q: What declaration must be made in the form?</b></h2><br>
    <p class="answer">A: The applicant must solemnly affirm and declare that the particulars provided are correct to the best of their knowledge and belief, and that no material information has been concealed.</p><br>

    <h2><b>Q: Where should the completed Form ‘REA-I’ be submitted?</b></h2><br>
    <p class="answer">A: The completed form should be submitted to the Real Estate Authority, with the address provided on the form.</p><br>

   

