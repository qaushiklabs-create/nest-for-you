   <h2><b>Q: What is Form ‘AAT’?</b></h2><br>
    <p class="answer">A: Form ‘AAT’ is used to file an appeal to the Real Estate Appellate Tribunal against an order issued by the Real Estate Authority or an Adjudicating Officer under the Real Estate (Regulation and Development) Act.</p><br>

    <h2><b>Q: What details are required in Form ‘AAT’?</b></h2><br>
    <p class="answer">A: The following details are required:</p>
    <ul>
        <li><strong>Particulars of the Appellants:</strong>
            <ul>
                <li>Name(s), address, and contact details.</li>
                <li>Address for service of notices.</li>
            </ul>
        </li>
        <li><strong>Particulars of the Respondents:</strong>
            <ul>
                <li>Name(s), office address, and contact details.</li>
                <li>Address for service of notices.</li>
            </ul>
        </li>
        <li><strong>Jurisdiction:</strong> Confirmation that the appeal falls within the Tribunal’s jurisdiction.</li>
        <li><strong>Limitation:</strong> Declaration that the appeal is within the limitation period or reasons for delay if filed late.</li>
        <li><strong>Facts of the Case:</strong> A concise statement of facts and grounds of appeal against the specific order.</li>
        <li><strong>Reliefs Sought:</strong> Specific reliefs the appellant is seeking, including grounds and legal provisions relied upon.</li>
        <li><strong>Interim Order:</strong> Request for any interim orders pending the final decision.</li>
        <li><strong>Matter Not Pending Elsewhere:</strong> Declaration that the matter is not pending before any other court or tribunal.</li>
        <li><strong>Fee Details:</strong> Details of the payment made for filing the appeal (demand draft, banker’s cheque, or online payment).</li>
        <li><strong>List of Enclosures:</strong> Attested copy of the order, documents relied upon, index, and other relevant documents.</li>
    </ul>

    <h2><b>Q: What should be included in the "Facts of the Case" section?</b></h2><br>
    <p class="answer">A: This section should include:</p>
    <ul>
        <li>1. A brief and concise statement of the facts of the case.</li>
        <li>2. Grounds of appeal against the specific order of the Authority or Adjudicating Officer.</li>
        <li>3. Relevant sections of the Act, rules, or regulations the appeal is based on.</li>
    </ul>

    <h2><b>Q: What are the requirements for filing Form ‘AAT’?</b></h2><br>
    <p class="answer">A: The requirements are:</p>
    <ul>
        <li>1. The appeal should be in English or accompanied by an English translation if in another Indian language.</li>
        <li>2. The document should be type-written, with margins and pagination as specified.</li>
        <li>3. An empty file-size envelope with the respondent’s address must be submitted.</li>
        <li>4. If there are multiple respondents, additional envelopes for each respondent are required.</li>
    </ul>

    <h2><b>Q: How should the appeal be presented?</b></h2><br>
    <p class="answer">A: The appeal should be:</p>
    <ul>
        <li>1. Fairly and legibly type-written or printed in double spacing.</li>
        <li>2. Paginated, indexed, and stitched in paper book form.</li>
        <li>3. Accompanied by an empty envelope bearing the full address of each respondent.</li>
    </ul>

    <h2><b>Q: What happens if the appeal is filed after the limitation period?</b></h2><br>
    <p class="answer">A: If the appeal is filed after the limitation period, the appellant must specify the reasons for the delay. The Appellate Tribunal will review the reasons and decide whether to accept the delayed appeal.</p><br>

    <h2><b>Q: What is the significance of the verification section in Form ‘AAT’?</b></h2><br>
    <p class="answer">A: The verification section is where the appellant confirms that the information provided in the appeal is true to their knowledge and belief and that no material facts have been concealed. This is a legal affirmation of the accuracy of the appeal content.</p><br>

    <h2><b>Q: What documents are required to be enclosed with the appeal?</b></h2><br>
    <p class="answer">A: Required enclosures include:</p>
    <ul>
        <li>1. An attested true copy of the order being appealed.</li>
        <li>2. Copies of documents relied upon and referenced in the appeal.</li>
        <li>3. An index of documents.</li>
        <li>4. Other documents as mentioned in the appeal.</li>
    </ul>

