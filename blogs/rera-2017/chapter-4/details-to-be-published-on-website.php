 <h2><b>Q: What kind of information does the Authority need to publish on its website for each registered project?</b></h2><br>
    <p class="answer">A: The Authority must publish detailed information about each registered project, including:</p>
    <ul class="answer">
        <p><b>Promoter Details:</b><br><br>
            <ul>
                <li>1. Profile of the promoter or group.</li>
                <li>2. Background and work experience of the promoter.</li>
                <li>3. Track record in real estate development.</li>
                <li>4. Details of ongoing and completed projects.</li>
                <li>5. Information on any ongoing litigation related to the real estate projects.</li>
                <li>6. Web links to the promoter’s and project’s websites.</li>
            </ul>
        </p>
        <p><b>Project Details:</b><br>
            <ul>
                <li>1. Advertisement and prospectus issued for the project.</li>
                <li>2. Compliance and registration details, including approvals, sanctions, and project plans.</li>
            </ul>
        </p>
    </ul>

    <h2><b>Q: What specific information about the promoter must be published?</b></h2><br>
    <p class="answer">A: The information about the promoter that must be published includes:</p>
    <ul class="answer">
        <p><b>Promoter or Group Profile:</b>
            <ul>
                <li>1. Brief details of the enterprise, including name, registered address, and type (e.g., proprietorship, company).</li>
                <li>2. Background, work experience, and contact details of the promoter or key individuals.</li>
                <li>3. If the entity is newly incorporated, details of the parent entity.</li>
            </ul>
        </p>
        <p><b>Track Record:</b>
            <ul>
                <li>1. Experience in real estate development, including completed and ongoing projects, project status, delays, and payments pending.</li>
            </ul>
        </p>
        <p><b>Litigations:</b>
            <ul>
                <li>1. Details of ongoing litigation related to the promoter’s projects in the past five years.</li>
            </ul>
        </p>
    </ul>

    <h2><b>Q: How should information about the promoter's track record be presented?</b></h2><br>
    <p class="answer">A: The promoter's track record should include:</p>
    <ul class="answer">
        <li>1. Years of experience in real estate development.</li>
        <li>2. Number of completed projects and constructed area in the past five years.</li>
        <li>3. Number of ongoing projects and proposed construction area.</li>
        <li>4. Details of ongoing and completed projects, including project status, delays, and payment details.</li>
    </ul>

    <h2><b>Q: What information regarding litigations must be disclosed?</b></h2><br>
    <p class="answer">A: Information on ongoing litigation related to the promoter’s real estate projects in the past five years must be disclosed.</p><br>

    <h2><b>Q: What specific details about the real estate project need to be published?</b></h2><br>
    <p class="answer">A: The project details to be published include:</p>
    <ul class="answer">
        <p><b>Advertisement and Prospectus:</b>
            <ul>
                <li>1. Copies of any advertisements and prospectuses issued for the project.</li>
            </ul>
        </p>
        <p><b>Compliance and Registration:</b>
            <ul>
                <li>1. Authenticated copies of approvals and sanctions from competent authorities.</li>
                <li>2. Original and subsequent sanctioned zoning/building plans and specifications.</li>
                <li>3. Details of the registration granted by the Authority under the Act.</li>
            </ul>
        </p>
    </ul>

    <h2><b>Q: How should the information about compliance and approvals be presented?</b></h2><br>
    <p class="answer">A: Information about compliance and approvals should include:</p>
    <ul class="answer">
        <li>Authenticated copies of approvals and sanctions received.</li>
        <li>Sanctioned zoning/building plans and specifications of the project or phases.</li>
        <li>Registration details granted by the Authority.</li>
    </ul>
    
     <h2><b>Q: What details about apartments, plots, and parking must be published for each project?</b></h2><br>
    <p class="answer">A: The following details must be published:</p>
    <ul class="answer">
        <p><b>Apartments and Plots:</b>
            <ul>
                <li>Number, Type, and Carpet Area: Details of the number, type, and carpet area of apartments for sale, including areas of exclusive balconies, verandahs, and open terraces. For plotted projects, details of the number, type, and area of plots must be provided.</li>
            </ul>
        </p>
        <p><b>Parking Spaces:</b>
            <ul>
                <li>Number and Area: Details of the number and area of garages or parking spaces for sale.</li>
                <li>Types of Parking: Information on the number and areas of parking spaces, including surface, stilt, and basement parking as per sanctioned building/site plans.</li>
            </ul>
        </p>
    </ul>

    <h2><b>Q: What information about real estate agents must be published?</b></h2><br>
    <p class="answer">A: The following information about real estate agents must be published:</p>
    <ul class="answer">
        <li>Names and Addresses: Names and addresses of real estate agents associated with the project.</li>
        <li>Registration Number: Registration numbers issued by the Authority.</li>
    </ul>

    <h2><b>Q: What details must be provided about consultants, contractors, and other professionals involved in the project?</b></h2><br>
    <p class="answer">A: Details must include:</p>
    <ul class="answer">
        <li>Name and Address: Name and address of each consultant, contractor, architect, structural engineer, etc.</li>
        <li>Firms and Associations: Names of associated firms, associations, or enterprises.</li>
        <li>Year of Establishment: Year of establishment of each firm or enterprise.</li>
        <li>Key Projects: Names and profiles of key projects completed by these professionals.</li>
    </ul>

    <h2><b>Q: What location details should be published for the project?</b></h2><br>
    <p class="answer">A: The following location details must be published:</p>
    <ul class="answer">
        <li>Revenue Estate and District: Details of the location in the revenue estate, Tehsil, and District.</li>
        <li>Land Boundaries: Clear demarcation of land boundaries including latitudes and longitudes.</li>
    </ul>

    <h2><b>Q: What must be included in the Development Works Plan?</b></h2><br>
    <p class="answer">A: The Development Works Plan must include:</p>
    <ul class="answer">
        <li>Plan of Development Works: Details of the development works and proposed facilities, including basic infrastructure such as water supply, sewerage, drainage, electricity, and more.</li>
        <li>Amenities: A detailed description of amenities including access, design for utilities, and public health services.</li>
        <li>Gantt or Milestone Charts: Charts showing the plan of development works, proposed facilities, and timelines.</li>
    </ul>

    <h2><b>Q: What financial details about the promoter need to be published?</b></h2><br>
    <p class="answer">A: The financial details include:</p>
    <ul class="answer">
        <li>PAN Card: Authenticated copy of the promoter’s PAN card.</li>
        <li>Annual Report: Annual reports including liabilities, debt-to-asset ratio, profit and loss account, balance sheet, cash flow statement, and auditor’s report for the preceding three financial years. For newly incorporated entities, details of the parent entity should be provided.</li>
    </ul>

    <h2><b>Q: What updates must be uploaded on the project webpage quarterly?</b></h2><br>
    <p class="answer">A: Quarterly updates should include:</p>
    <ul class="answer">
        <li>Bookings: Number and types of apartments or plots booked.</li>
        <li>Parking Spaces: Number of garages/parking spaces booked.</li>
        <li>Project Status: Status of construction of buildings and common areas with photographs.</li>
        <li>Approvals Status: Details on received approvals, approvals applied for, planned applications, and any modifications or amendments.</li>
    </ul>

    <h2><b>Q: What approvals and legal documents must be published?</b></h2><br>
    <p class="answer">A: The following approvals and legal documents must be published:</p>
    <ul class="answer">
        <li>Authentic Copies: Copies of the licence, land use permissions, sanctioned building plans, and other relevant sanctions.</li>
        <li>Phase-wise Approvals: For projects developed in phases, authenticated copies of approvals for each phase must be provided.</li>
    </ul>
    
    <h2><b>Q: What legal documents must be published for each real estate project?</b></h2><br>
    <p class="answer">A: The following legal documents must be published:</p>
    <ul class="answer">
        <li><b>Application Form, Allotment Letter, Agreement for Sale, and Conveyance Deed:</b> The proforma of these documents should be made available.</li>
        <li><b>Legal Title Deed:</b> Authenticated copy of the legal title deed reflecting the land title.</li>
        <li><b>Land Title Search Report:</b> A report from an experienced advocate (at least ten years).</li>
        <li><b>Encumbrances Details:</b> Information on encumbrances, including rights, title, interest, dues, and litigation. A non-encumbrance certificate from the concerned revenue authority (Tehsildar or above) must be provided.</li>
        <li><b>Consent of Land Owner:</b> If the promoter is not the landowner, details of the consent of the landowner(s) and copies of the registered collaboration agreement, development agreement, joint development agreement, or any other relevant agreement.</li>
        <li><b>Sanction/Approval Letter:</b> Details of sanctions or approvals from banks or financial institutions for home loan tie-ups.</li>
        <li><b>Contact Details:</b> Name, address, contact numbers, and email addresses of the promoter, authorized persons, and other officials related to the project.</li>
    </ul>

    <h2><b>Q: What information must be available on the website for projects that have been revoked or penalized?</b></h2><br>
    <p class="answer">A: The following information must be available on the website for such projects:</p>
    <ul class="answer">
        <li><b>Revocation or Penalty Details:</b> The Authority must maintain a database of projects that have been revoked or penalized and ensure that relevant information is updated on its website.</li>
    </ul>

    <h2><b>Q: What details about registered real estate agents must be published?</b></h2><br>
    <p class="answer">A: For real estate agents registered with the Authority, the following details must be published:</p>
    <ul class="answer">
        <li><b>Registration Number and Validity:</b> Registration number and the validity period of the registration.</li>
        <li><b>Enterprise Details:</b> Brief details of the enterprise, including name, registered address, and type (proprietorship, society, partnership, company, etc.).</li>
        <li><b>Registration Particulars:</b> Details of registration, including bye-laws, memorandum of association, articles of association, etc.</li>
        <li><b>Personal Details:</b> Name, address, contact details, and photograph of the real estate agent (if an individual) or of partners, directors, etc. (if a company or other entity).</li>
        <li><b>PAN Card:</b> Authenticated copy of the PAN card.</li>
        <li><b>Address Proof:</b> Authenticated copy of the address proof and contact details of the place of business, including address, contact numbers, and email IDs.</li>
    </ul>

    <h2><b>Q: What information should be published for real estate agents whose registration applications were rejected or revoked?</b></h2><br>
    <p class="answer">A: The following details should be published:</p>
    <ul class="answer">
        <li><b>Registration Number and Validity:</b> Registration number and validity period (if previously registered).</li>
        <li><b>Enterprise Details:</b> Brief details of the enterprise, including name, registered address, and type.</li>
        <li><b>Personal Details:</b> Name, address, contact details, and photograph of the real estate agent or relevant individuals.</li>
    </ul>


