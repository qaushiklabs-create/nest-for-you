  <h2><b>Q: What is included in the definition of a "building" under this Act?</b></h2><br>
    <p class="answer">A: A "building" includes any building or part of a building used for any purpose, whether it is actually being used for that purpose or not. It also includes land, godowns, out-houses, gardens, lawns, wells, and other appurtenances, as well as furniture, fittings, and machinery installed in the building. However, it does not include a room in a hotel, hostel, or boarding house.</p><br>
    
    <h2><b>Q: Who is a "Controller" as defined in this Act?</b></h2><br>
    <p class="answer">A: A "Controller" is any person appointed by the State Government to perform the functions of a controller under this Act.</p><br>
    
    <h2><b>Q: How is a "landlord" defined in this Act?</b></h2><br>
    <p class="answer">A: A "landlord" is any person entitled to receive rent for any building or rented land, either on their own behalf or on behalf of others. This includes trustees, guardians, receivers, executors, or administrators, as well as tenants who sublet the property in accordance with the Act. It also includes anyone who derives their title from a landlord.</p><br>
    
    <h2><b>Q: What is considered a "non-residential building"?</b></h2><br>
    <p class="answer">A: A "non-residential building" is a building mainly used for business or trade purposes. It can also be used partly for business and partly for residence, provided that the person conducting business or trade in the building also resides there. If a building is let out separately for residential and non-residential purposes to more than one person, the portion used for residence is not treated as a non-residential building.</p><br>
    
    <h2><b>Q: What does "prescribed" mean in this Act?</b></h2><br>
    <p class="answer">A: "Prescribed" means prescribed by rules made under this Act.</p><br>
    
    <h2><b>Q: What is meant by "rented land"?</b></h2><br>
    <p class="answer">A: "Rented land" refers to any land that is let separately, primarily for business or trade purposes.</p><br>
    
    <h2><b>Q: How is a "residential building" defined?</b></h2><br>
    <p class="answer">A: A "residential building" is any building that is not classified as a non-residential building.</p><br>
    
    <h2><b>Q: Who is considered a "tenant" under this Act?</b></h2><br>
    <p class="answer">A: A "tenant" is any person who pays rent for a building or rented land. This includes tenants who continue in possession after the termination of their tenancy and, upon their death, certain heirs mentioned in the Schedule appended to the Act who were ordinarily residing with them at the time of death. It does not include persons placed in occupation by the tenant without the written consent of the landlord or municipal bodies managing the rent collection for certain properties.</p><br>
    
    <h2><b>Q: What is an "urban area" as defined in the Act?</b></h2><br>
    <p class="answer">A: An "urban area" is any area administered by a municipal body, notified area committee, or the Faridabad Complex Administration. It can also include any area declared by the State Government by notification to be an urban area for the purposes of this Act.</p><br>

  <h2><b>Q: What power does the State Government have under this section of the Act?</b></h2><br>
    <p class="answer">A: The State Government has the authority to direct that all or any provisions of this Act shall not apply to a particular building or rented land or to any class of buildings or rented lands.</p><br>
    
    <h2><b>Q: Can the State Government exempt specific buildings from the provisions of the Act?</b></h2><br>
    <p class="answer">A: Yes, the State Government can exempt specific buildings or rented lands, or a class of buildings or rented lands, from the provisions of this Act.</p><br>
    
    <h2><b>Q: Is the exemption from the Act applicable to all buildings and rented lands by default?</b></h2><br>
    <p class="answer">A: No, exemptions are not automatic. The State Government must issue a directive for the exemption of specific buildings, rented lands, or classes of buildings or rented lands from the provisions of the Act.</p><br>

 <h2><b>Q: What powers does the Controller have regarding the fair rent of a building or rented land?</b></h2><br>
    <p class="answer">A: The Controller, upon application by the tenant or landlord, shall determine the fair rent for a building or rented land. The fair rent is set after holding any inquiries the Controller deems necessary and becomes operative from the date of the application.</p><br>
    
    <h2><b>Q: How does the Controller determine the basic rent for buildings constructed on or before December 31, 1961?</b></h2><br>
    <p class="answer">A: For buildings constructed on or before December 31, 1961, or land let out before this date, the basic rent is determined based on the rent prevailing in the locality for similar buildings or rented land let out to a new tenant during the year 1962.</p><br>
    
    <h2><b>Q: How is the basic rent determined for buildings constructed after December 31, 1961?</b></h2><br>
    <p class="answer">A: For buildings constructed after December 31, 1961, or land let out after this date, the basic rent is determined based on the rent agreed upon between the landlord and the tenant before the date of application. If no rent was agreed upon, it is based on the prevailing rent for similar buildings or rented land at the date of the application.</p><br>
    
    <h2><b>Q: Can the Controller adjust the basic rent amount? If so, how?</b></h2><br>
    <p class="answer">A: Yes, the Controller can adjust the basic rent by allowing an increase or decrease up to twenty-five percent. This adjustment is based on the rise or fall in the general price level, as indicated by the All-India Wholesale Price Index Numbers published by the Government of India, for the calendar year immediately preceding the date of application.</p><br>
    
    <h2><b>Q: What happens if fair rent has already been fixed under the East Punjab Urban Rent Restriction Act, 1949?</b></h2><br>
    <p class="answer">A: If fair rent has already been fixed under the East Punjab Urban Rent Restriction Act, 1949, the landlord or tenant of such building or land may still apply to have the fair rent fixed under the current Act.</p><br>
    
    <h2><b>Q: Can the Controller fix fair rent based on a compromise between parties?</b></h2><br>
    <p class="answer">A: Yes, the Controller can fix fair rent based on a compromise between the parties involved. Such a rent determination is binding only on the parties and their heirs.</p><br>

 <h2><b>Q: Can the fair rent of a building or rented land be changed immediately after it has been fixed under Section 4?</b></h2><br>
    <p class="answer">A: No, once the fair rent has been fixed under Section 4, no further increase or decrease in such fair rent is permissible for a period of five years.</p>
    <br>
    <h2><b>Q: Under what circumstances can an increase in fair rent be allowed during the five-year period?</b></h2><br>
    <p class="answer">A: An increase in fair rent may be allowed if any addition, improvement, or alteration has been carried out at the expense of the landlord in the building or rented land that is in the tenant's occupation, and the tenant requests the increase.</p><br>
    
    <h2><b>Q: When can a decrease in fair rent be allowed?</b></h2><br>
    <p class="answer">A: A decrease in fair rent may be allowed in cases where there is a decrease or diminution in the accommodation or amenities provided.</p><br>
    
    <h2><b>Q: Who decides disputes between the landlord and tenant regarding any increase or decrease in fair rent?</b></h2><br>
    <p class="answer">A: Any dispute between the landlord and tenant regarding an increase or decrease in fair rent under this section shall be decided by the Controller.</p><br>

 <h2><b>Q: What restriction is placed on landlords after the fair rent of a building or rented land is fixed under Section 4?</b></h2><br>
    <p class="answer">A: The landlord is not allowed to claim or receive any premium, additional sum, or rent in excess of the fixed fair rent.</p><br>
    
    <h2><b>Q: Can a landlord charge an advance amount after the fair rent is fixed?</b></h2><br>
    <p class="answer">A: Yes, the landlord can stipulate for and receive an advance amount, but it should not exceed one month's rent.</p><br>
    
    <h2><b>Q: What is the status of any agreement that requires the tenant to pay an amount in addition to the fair rent?</b></h2><br>
    <p class="answer">A: Any agreement that requires the payment of a sum in addition to the fair rent or rent in excess of the fair rent is considered null and void.</p><br>

 <h2><b>Q: What can a tenant do if the landlord refuses to receive rent or grant a receipt for it?</b></h2><br>

    <p class="answer">A: If the landlord refuses to receive rent or provide a receipt, the tenant can apply to the Controller for permission to deposit the rent in the Controller's office.</p><br>
    
    <h2><b>Q: What does the Controller do when a tenant applies to deposit rent due to the landlord's refusal?</b></h2><br>
    <p class="answer">A: The Controller will examine the application, and if satisfied that there are sufficient grounds, the Controller will accept the deposit after the tenant pays the required fee.</p><br>
    
    <h2><b>Q: What is the status of the rent once it is deposited with the Controller?</b></h2><br>
    <p class="answer">A: The deposit of rent with the Controller is considered as payment made by the tenant to the landlord in respect of the rent due.</p><br>
    
    <h2><b>Q: What happens after the Controller receives the rent deposit?</b></h2><br>
    <p class="answer">A: After receiving the deposit, the Controller will notify the landlord of the receipt and pay the deposited amount to the landlord.</p><br>
    
     <h2><b>Q: What can a tenant do if they have paid a sum to the landlord that, under the provisions of this Act, should not have been paid?</b></h2><br>
    <p class="answer">A: The tenant can recover the sum from the landlord or their legal representative within six months after the date of payment.</p><br>
    
    <h2><b>Q: How can a tenant recover an amount that should not have been paid to the landlord?</b></h2><br>
    <p class="answer">A: The tenant can recover the amount by deducting it from any rent payable to the landlord within six months, or through any other method of recovery.</p><br>
    
    <h2><b>Q: What is the time limit for a tenant to recover an overpaid amount?</b></h2><br>
    <p class="answer">A: The tenant has six months from the date of payment to recover the overpaid amount.</p><br>
    
    <h2><b>Q: What does the term "legal representative" mean in the context of this section?</b></h2><br>
    <p class="answer">A: The term "legal representative" has the same meaning as assigned in the Code of Civil Procedure, 1908, and includes the joint family in the case of joint family property, of which the deceased person was a member.</p><br>

    <h2><b>Q: Under what condition is a landlord entitled to increase the rent of a building or rented land?</b></h2><br>
    <p class="answer">A: A landlord is entitled to increase the rent if, after the commencement of the tenancy, a fresh rate, cess, or tax is levied by a local authority, or if there is an increase in the existing rate, cess, or tax.</p><br>
    
    <h2><b>Q: What is the limit on the increase in rent due to a fresh rate, cess, or tax?</b></h2><br>
    <p class="answer">A: The increase in rent cannot exceed the amount of the new rate, cess, or tax, or the increase in the existing rate, cess, or tax.</p><br>
    
    <h2><b>Q: From when is the tenant liable to pay the increased rent due to a new or increased rate, cess, or tax?</b></h2><br>
    <p class="answer">A: The tenant is liable to pay the increased rent from the date of dispatch of the written notice of demand sent by the landlord under registered cover.</p><br>
    
    <h2><b>Q: Can a landlord recover the amount of the rate, cess, or tax from the tenant if the rent increase is not covered by this section?</b></h2><br>
    <p class="answer">A: No, the landlord cannot recover the amount of the rate, cess, or tax, or any portion thereof, from the tenant unless it is covered under the provisions of this section.</p><br>

  <h2><b>Q: What rights do tenants have regarding amenities such as electricity, sewage, or water supply in their locality?</b></h2><br>
    <p class="answer">A: If these amenities have been made available by the State Government or a local authority, tenants in the locality are entitled to enjoy them, subject to the provisions outlined in the law.</p><br>
    
    <h2><b>Q: What can a tenant do if the landlord fails to agree or provide the requested amenities within the specified time?</b></h2><br>
    <p class="answer">A: If the landlord fails to agree in writing within 30 days or provide the amenities within 90 days after the tenant's written request, the tenant may apply to the Controller. The Controller can then permit the tenant to arrange for the amenities at the landlord's expense, allowing the tenant to deduct the cost from future rent payments.</p><br>
    
    <h2><b>Q: What is the maximum rate at which a tenant can deduct expenses for providing amenities from the rent?</b></h2><br>
    <p class="answer">A: The rate of deduction of expenses from the rent cannot exceed 50% of the amount of rent.</p><br>
    
    <h2><b>Q: Under what circumstances may the Controller reject a tenant's application for providing amenities?</b></h2><br>
    <p class="answer">A: The Controller may reject the application if providing the amenities would cause undue hardship to the landlord, considering the landlord's source of income or if the expenses involved are disproportionate to the benefits gained.</p><br>
    
    <h2><b>Q: What happens if there is a dispute regarding the amount spent by the tenant on providing amenities?</b></h2><br>
    <p class="answer">A: In case of a dispute, the Controller will decide the appropriate amount after conducting an inquiry based on an application submitted by the tenant.</p><br>
    
    <h2><b>Q: Is the landlord entitled to increase the rent after the tenant has provided an amenity?</b></h2><br>
    <p class="answer">A: Yes, the landlord can increase the rent by 8% per annum of the amount spent on providing the amenity, but only after the tenant has recovered the expenses incurred for installing the amenity.</p><br>
    
    <h2><b>Q: What must the tenant do after providing the amenity?</b></h2><br>
    <p class="answer">A: The tenant must immediately send the details of the expenses incurred to the landlord.</p>
    <br>
    <h2><b>Q: When is rent enhancement disallowed despite the landlord's entitlement?</b></h2><br>
    <p class="answer">A: Rent enhancement is not allowed until the tenant has fully recovered the amount spent on providing the amenity.</p><br>





