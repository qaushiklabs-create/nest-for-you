 <h2><b>Q: What is the restriction on landlords regarding amenities provided to tenants?</b></h2><br>
    <p class="answer">A: A landlord cannot, without just and sufficient cause, cut off or withhold any amenities enjoyed by the tenant.</p><br>
    
    <h2><b>Q: What can the Controller do if a tenant fails to put the landlord in possession of the building or rented land?</b></h2><br>
    <p class="answer">A: The Controller may make an order directing the tenant to put the landlord in possession of the building or rented land. The Controller can also provide the tenant a reasonable time, up to three months, to comply with this order.</p><br>
    
    <h2><b>Q: Under what conditions can a landlord apply to the Controller to regain possession of a residential building?</b></h2><br>
    <p class="answer">A: A landlord can apply if:
    <ul>
        <li>1. The landlord requires the building for their own occupation and is not occupying another residential building in the same urban area.</li>
        <li>2. The building is needed for the use of the landlord's son for professional purposes or residence.</li>
        <li>3. The building was let to the tenant because of their service or employment, and the tenant has ceased to be in such service.</li>
        <li>4. The tenant has another residential building reasonably sufficient for their requirements in the urban area.</li>
        <li>5. The landlord is a member of the armed forces requiring the building for family occupation and has appropriate certification.</li>
    </ul>
    </p>
    
    <h2><b>Q: Can a landlord apply for possession of rented land?</b></h2><br>
    <p class="answer">A: Yes, a landlord can apply for possession of rented land if they require it for their own use, are not occupying any other rented land for business purposes in the same urban area, and have not vacated such land without sufficient cause after the commencement of the 1949 Act.</p><br>
    
    <h2><b>Q: What conditions allow a landlord to apply for possession of a building or rented land for improvement or safety reasons?</b></h2><br>
    <p class="answer">A: A landlord can apply if they require the property to carry out building work at the instance of the State Government, local authority, or improvement trust, or if the property has become unsafe or unfit for human habitation.</p><br>
    
    <h2><b>Q: What is the time frame for the Controller to dispose of an application under sub-clause (v) of clause (a) of sub-section (3)?</b></h2><br>
    <p class="answer">A: The application should be disposed of, as far as possible, within one month. If the claim is accepted, the Controller will direct the tenant to put the landlord in possession within fifteen days from the date of the order.</p><br>
    
    <h2><b>Q: What happens if a landlord does not use the building or rented land after obtaining possession?</b></h2><br>
    <p class="answer">A: If the landlord does not occupy the property, or if it was obtained on behalf of a family member or for a specific purpose, and that purpose is not met within twelve months (for residential buildings) or three years (for personal use), the evicted tenant may apply to the Controller to have possession restored.</p><br>
    
    <h2><b>Q: What compensation can a tenant receive if a landlord's eviction application is deemed frivolous or vexatious?</b></h2><br>
    <p class="answer">A: The Controller may direct that compensation not exceeding five hundred rupees be paid by the landlord to the tenant if the eviction application is found to be frivolous or vexatious.</p>

<h2><b>Q: What is the purpose of Section 113-A?</h2><br></b>
    <div class="answer">A: Section 113-A outlines the special procedure for dealing with eviction applications made by landlords who are or were members of the Armed Forces of India or employees of the Government of India, Government of Haryana, or any state-owned board or corporation. It sets out the process for these landlords to recover possession of residential buildings under specific conditions.</div><br>

   <h2><b>Q: Who can apply under Section 113-A?</h2><br></b>
    <div class="answer">A: Landlords who are or were:
        <ul>
            <li>1. Members of the Armed Forces of the Union of India, within one year before or after their retirement/discharge, or within one year from the commencement of the Haryana Urban (Control of Rent and Eviction) Amendment Act, 1986.</li>
            <li>2. Employees of the Government of India, Government of Haryana, or any state-owned board or corporation, within one year prior to or after their retirement or within one year from the commencement of the Haryana Urban (Control of Rent and Eviction) Amendment Act, 1990.</li>
        </ul>
    </div>

   <h2><b>Q: What happens if the landlord dies?</h2><br></b>
    <div class="answer">A: If a landlord who is eligible under this section dies:
        <ul>
            <li>1. The landlord's widow, or in the absence of the widow, the landlord's child, grandchild, or widowed daughter-in-law who was dependent on him, can make an application.</li>
            <li>2. They must apply within one year from the commencement of the Haryana Urban (Control of Rent and Eviction) Amendment Act, 1988, if the landlord died before the Act's commencement.</li>
            <li>3. If the landlord died after the Act's commencement but before retirement/discharge, the application must be made within one year of the landlord's death.</li>
            <li>. If the landlord died after the commencement of the Act and after retirement/discharge, the application must be made within one year of retirement/discharge.</li>
        </ul>
    </div>

   <h2><b>Q: What is the procedure for issuing summons?</h2><br></b>
    <div class="answer">A: 
        <ul>
            <li>1. The Controller must issue summons in the prescribed form.</li>
            <li>2. Summons are to be served by registered post with acknowledgment due, or by publication in a local newspaper if necessary.</li>
            <li>3. If an acknowledgment or the registered mail is refused, the Controller may declare the summons validly served.</li>
        </ul>
    </div><br>

   <h2><b>Q: Can a tenant contest the eviction application?</h2><br></b>
    <div class="answer">A: Yes, but only if:
        <ul>
            <li>1. The tenant files an affidavit stating the grounds for contesting the application and obtains leave from the Controller.</li>
            <li>2. If the tenant does not file such an affidavit or appear as required, the landlord's claims will be deemed admitted, and eviction may be granted.</li>
        </ul>
    </div><br>

   <h2><b>Q: What happens if leave to contest is granted?</h2><br></b>
    <div class="answer">A: If leave is granted, the Controller will commence the hearing of the application as soon as practicable.</div><br>

   <h2><b>Q: What procedures must the Controller follow during the inquiry?</h2><br></b>
    <div class="answer">A: The Controller must follow the practice and procedure of a Court of Small Causes, including recording evidence.</div><br>

   <h2><b>Q: Can there be an appeal against the Controller's decision?</h2><br></b>
    <div class="answer">A: No appeal or second appeal lies against an order for eviction. However, the High Court may call for records to ensure that the order is according to law.</div><br>

   <h2><b>Q: Can the Controller review a decision?</h2><br></b>
    <div class="answer">A: Yes, the Controller can review decisions that have become final, in accordance with Order XLVII of the First Schedule to the Code of Civil Procedure, 1908.</div><br>

   <h2><b>Q: How does Section 113-A affect other provisions of the Act?</h2><br></b>
    <div class="answer">A: The provisions of Section 113-A or any rule made under it will have effect notwithstanding any inconsistencies with other provisions in the Act or other laws in force.</div><br>

<h2><b>Q: How are decisions that have become final treated under this Act?</h2><br></b>
    <div class="answer">A: Decisions that have become final are not subject to reopening. They are considered conclusive and are not to be revisited or reexamined in subsequent proceedings.</div><br>

   <h2><b>Q: What is the procedure for appealing an order made by the Controller?</h2><br></b>
    <div class="answer">A:
        <ul>
            <p><b>1. Appeal Period:</b> A person aggrieved by an order from the Controller can appeal within thirty days from the date of the order. This period can be extended if the appellate authority allows it for valid reasons.</p>
            <p><b>2. Exclusion of Time:</b> When calculating the thirty-day period, the time taken to obtain a certified copy of the order is excluded.</p>
            <p><b>3. Stay of Proceedings:</b> The appellate authority may grant a stay on further proceedings pending the decision on the appeal.</p>
            <p><b>4. Decision Making:</b> The appellate authority reviews the case records, hears the parties involved, and may conduct further inquiries as necessary. Its decision is final, subject to review by the High Court.</p>
        </ul>
    </div><br>

   <h2><b>Q: Can the appellate authority's decision be challenged in court?</h2><br></b>
    <div class="answer">A: The decision of the appellate authority is final and cannot be challenged in any court of law, except as provided under the High Court's revisional authority.</div><br>

   <h2><b>Q: What is the role of the High Court as a revisional authority?</h2><br></b>
    <div class="answer">A:
        <ul>
            <p><b>1. Revisional Authority:</b> The High Court can, on its own motion or on an application by an aggrieved party, examine the records of any order or proceedings under this Act to ensure legality and propriety.</p>
            <p><b>2. Time Limit:</b> The High Court may do so within ninety days from the date of the order, with the period for obtaining a certified copy of the order excluded.</p>
            <p><b>3. Action:</b> After reviewing, the High Court may pass any order it deems fit regarding the matter.</p>
        </ul>
    </div><br>

   <h2><b>Q: What happens if the appellate authority or High Court's review process finds issues with the Controller’s order?</h2><br></b>
    <div class="answer">A: If issues are found, the High Court may pass an appropriate order to address these issues, ensuring the order or proceedings are lawful and proper.</div><br>

   <h2><b>Q: Are there any specific provisions that override other parts of the Act or existing laws?</h2><br></b>
    <div class="answer">A: Yes, the provisions of Section 113-A and related sections or rules made under it take precedence over any inconsistent provisions in the Act or other laws in force. This means that the special procedures outlined in these sections apply regardless of conflicting regulations elsewhere.</div><br>

 <h2><b>Q: What powers does an authority exercising functions under this Act have regarding witnesses and evidence?</h2><br></b>
    <div class="answer">A: An authority exercising powers under this Act has the same powers as a court under the Code of Civil Procedure, 1908. This includes:
        <ul>
            <li>1. Summoning witnesses</li>
            <li>2. Enforcing the attendance of witnesses</li>
            <li>3. Compelling the production of evidence</li>
        </ul>
    </div><br>

   <h2><b>Q: Who determines the compensation and costs associated with proceedings before the Controller, appellate authority, or revisional authority?</h2><br></b>
    <div class="answer">A: The compensation and costs of proceedings are determined at the discretion of the Controller, appellate authority, or revisional authority, as applicable. They decide:
        <ul>
            <li>1. Who should bear the costs</li>
            <li>2. Out of which property the costs should be paid</li>
            <li>3. The extent of such costs</li>
        </ul>
        They also issue necessary directions for the payment of these costs.
    </h2><br>

   <h2><b>Q: Can the lack of jurisdiction affect the authority's ability to decide on costs?</h2><br></b>
    <div class="answer">A: No, the lack of jurisdiction to try the proceedings does not prevent the authority from exercising powers to determine costs.</div><br>

   <h2><b>Q: When the authority decides that costs should not follow the event, what is required?</h2><br></b>
    <div class="answer">A: If the authority decides that costs should not follow the event (i.e., one party does not automatically bear the costs of the other party), it must provide written reasons for this decision.</div><br>

<h2><b>Q: What should be done if there is more than one Controller at the same place?</h2><br></b>
    <div class="answer">A: Applications should be made to the Controller who is authorized by the appellate authority of the area to entertain such applications.</div><br>

   <h2><b>Q: What happens to an application if it is made to a Controller who is not authorized?</h2><br></b>
    <div class="answer">A: The Controller who receives the application but is not authorized to dispose of it has two options:
        <ul>
            <li>1. Keep the application on their file.</li>
            <li>2. Transfer the application to another authorized Controller at the same place for disposal.</li>
        </ul>
    </div><br>
    <h2><b>Q: Can the High Court transfer proceedings between appellate authorities?</h2><br></b>
    <div class="answer">A: Yes, the High Court may, upon an application or otherwise, order the transfer of any proceedings pending before an appellate authority to another appellate authority. The new appellate authority will dispose of the proceedings according to the order of transfer, subject to any special directions provided.</div><br>

   <h2><b>Q: Can an appellate authority transfer proceedings between Controllers?</h2><br></b>
    <div class="answer">A: Yes, an appellate authority may, on an application or otherwise, order the transfer of any proceedings pending before a Controller to another Controller within its jurisdiction. The new Controller will handle the proceedings according to the order of transfer, subject to any special directions given.</div><br>

<h2><b>Q: What are the obligations of landlords and tenants under this Act?</h2><br></b>
    <div class="answer">A: Every landlord and tenant of a building or rented land is required to provide the Controller or any authorized person with such particulars regarding the building or rented land as may be prescribed.</div><br>

   <h2><b>Q: What are the penalties for contravening specific provisions of the Act?</h2><br></b>
    <div class="answer">
        A:
        <ol>
            <li><strong> Contravention of Sub-sections:</strong> If a person violates any provisions of:
                <ul>
                    <li>1. Sub-section (2) of Section 8</li>
                    <li>2. Sub-section (1) of Section 10</li>
                    <li>3. Section 11</li>
                    <li>4. Section 21</li>
                </ul>
                They are punishable with a fine of up to one thousand rupees.
            </li>
            <li><strong> Contravention of Clause (a) of Section 6:</strong> If a person contravenes this clause, they are punishable with imprisonment for up to two years, or with a fine, or with both.</li>
        </ol>
    </div><br>

   <h2><b>Q: What is required for a court to take cognizance of an offence under this Act?</h2><br></b>
    <div class="answer">A: No court shall take cognizance of an offence under this section except upon:
        <ul>
            <li>1. A written complaint filed with the sanction of the Controller, detailing the facts constituting the offence, or</li>
            <li>2. A written report of such facts made by the Controller.</li>
        </ul>
    </div><br>
 <h2><b>Q: Can the State Government create additional rules under this Act?</h2><br></b>
    <div class="answer">A: Yes, the State Government may, by notification, make rules to carry out all or any of the purposes of this Act.</div><br>

   <h2><b>Q: What is the status of the East Punjab Urban Rent Restriction Act, 1949 after the enactment of this Act?</h2><br></b>
    <div class="answer">
        A:
        <ol>
            <li><strong> Repeal of the Act:</strong> The East Punjab Urban Rent Restriction Act, 1949 (East Punjab Act No. 3 of 1949) has been repealed.</li>
            <li><strong> Effect on Pending Proceedings:</strong> The repeal does not affect any proceedings pending or orders passed immediately before the commencement of this Act. Such proceedings or orders shall continue and be disposed of or enforced as if the repealed Act had not been repealed.</li>
            <li><strong> Continuance of Actions:</strong> Actions taken or things done under the repealed Act, including any rules, notifications, or orders that are not inconsistent with this Act, are deemed to have been done under the corresponding provisions of this Act and shall remain in force until superseded by actions under this Act.</li>
        </ol>
    </div>




