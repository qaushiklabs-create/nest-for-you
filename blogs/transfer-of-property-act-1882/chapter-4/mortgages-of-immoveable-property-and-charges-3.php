<h2><b>Q1: What Responsibilities Does a Mortgagee Have When in Possession of the Mortgaged Property?</b></h2><br>
<p>A1: When in possession, a mortgagee must:</p><br>
<ul>
  <li>Manage the property prudently as if it were their own.</li>
  <li>Make efforts to collect rents and profits.</li>
  <li>Pay government revenue, public charges, and rent accruing during possession.</li>
  <li>Make necessary repairs, funded from income after deducting payments for taxes and interest.</li>
  <li>Avoid any acts that could permanently injure the property.</li>
  <li>Apply insurance proceeds for reinstating the property or reducing the mortgage debt.</li>
  <li>Maintain accurate accounts of all transactions and provide copies to the mortgagor upon request.</li>
  <li>Deduct expenses properly incurred and account for receipts against the mortgage amount due.</li>
  <li>Upon a tender or deposit of the mortgage amount, account for receipts from that date without deducting further expenses.</li>
</ul><br>

<h2><b>Q2: What Happens if the Mortgagee Fails to Fulfill Their Duties?</b></h2><br>
<p>A2: If the mortgagee fails to perform their duties, they may be held liable for any loss that results from such failure when accounts are taken under a decree.</p><br>

<h2><b>Q3: Are There Exceptions to the Rules Regarding the Mortgagee's Receipts in Lieu of Interest?</b></h2><br>
<p>A3: Yes, if there is a contract stating that receipts from the mortgaged property will serve as interest while the mortgagee is in possession, the provisions about receipts do not apply.</p><br>

<h2><b>Q4: Under What Circumstances Can a Prior Mortgagee Be Postponed to a Subsequent Mortgagee?</b></h2><br>
<p>A4: A prior mortgagee can be postponed if, through fraud, misrepresentation, or gross neglect, they induced another person to advance money on the security of the mortgaged property.</p><br>

<h2><b>Q5: How Does the Express Maximum in a Mortgage for Future Advances Affect Subsequent Mortgages?</b></h2><br>
<p>A5: <a href="https://www.indiacode.nic.in/bitstream/123456789/2338/1/A1882-04.pdf" target="_blank" rel="nofollow"> <b>Transfer of Property Act, 1882 :</b></a> If a mortgage secures future advances and expresses a maximum amount, any subsequent mortgage made with notice of the prior mortgage will be postponed to the prior mortgage for all advances or debits not exceeding that maximum, even if those advances were made with notice of the subsequent mortgage.</p><br>

<h2><b>Q6: What Is the Principle of Marshalling Securities in the Context of Mortgages?</b></h2><br>
<p>A6: Marshalling securities allows a subsequent mortgagee to have the prior mortgaged debt satisfied from properties not mortgaged to them, provided it does not prejudice the rights of the prior mortgagee or any other person with a legitimate interest in those properties.</p><br>

<h2><b>Q7: How Does Contribution to Mortgage Debt Work When Multiple Owners Are Involved?</b></h2><br>
<p>A7: If a property subject to a mortgage has multiple owners, each share or part of the property is, in the absence of a contract to the contrary, liable to contribute rateably to the mortgage debt. The contribution is determined based on the value of each share at the time of the mortgage, minus any other existing mortgage or charge.</p><br>

<h2><b>Q8: What Happens if One of Two Properties Belonging to the Same Owner Is Mortgaged to Secure One Debt and Then Both Are Mortgaged for Another Debt?</b></h2><br>
<p>A8: If the former debt is paid off using the property mortgaged for that debt, both properties are, unless stated otherwise in a contract, liable to contribute rateably to the latter debt after deducting the amount of the former debt from the value of the property that secured it.</p><br>

<h2><b>Q9: What Is the Process for a Mortgagor to Deposit Money Due on a Mortgage in Court?</b></h2><br>
<p>A9: The mortgagor or a person entitled to sue may deposit the amount due on the mortgage in any court where a redemption suit could be instituted. After the deposit, the court will notify the mortgagee. The mortgagee can then petition the court to accept the deposited amount in full discharge of the mortgage by stating the amount due and submitting the mortgage deed and related documents.</p><br>

<h2><b>Q10: What Happens if the Mortgagee Is in Possession of the Mortgaged Property When Money Is Deposited in Court?</b></h2><br>
<p>A10: If the mortgagee is in possession, the court will require them to deliver possession of the property back to the mortgagor before paying out the deposited amount. The mortgagee must either re-transfer the property to the mortgagor or execute an acknowledgment that their rights have been extinguished.</p><br>

<h2><b>Q11: What Happens to the Interest on the Principal Money When a Mortgagor Tenders or Deposits the Amount Due in Court?</b></h2><br>
<p>A11: Interest on the principal money shall cease from the date of the tender or, in the case of a deposit where no previous tender has been made, as soon as the mortgagor has done everything necessary for the mortgagee to withdraw the amount from court.</p><br>

<h2><b>Q12: Under What Condition Does Interest Continue to Be Payable if a Mortgagor Deposits the Amount Without a Previous Tender?</b></h2><br>
<p>A12: If the mortgagor deposits the amount without a previous tender and then withdraws all or part of it, interest on the principal money shall be payable from the date of such withdrawal.</p><br>

<h2><b>Q13: Does the Mortgagee Lose the Right to Interest if They Have a Contract That Requires Reasonable Notice Before Payment?</b></h2><br>
<p>A13: No, the mortgagee retains the right to interest if they have not been given the required notice before the tender or deposit is made.</p><br>

<h2><b>Q14: Who Can Sue for Redemption of the Mortgaged Property?</b></h2><br>
<p>A14: Besides the mortgagor, any person with an interest in the property, any surety for the mortgage debt, or any creditor of the mortgagor with a decree for sale of the mortgaged property can sue for redemption.</p><br>

<h2><b>Q15: What Rights Does a Person Who Redeems a Mortgage Have Regarding Subrogation?</b></h2><br>
<p>A15: A person who redeems a mortgage (other than the mortgagor) has the same rights against the mortgagor or other mortgagees as the mortgagee whose mortgage they redeem.</p><br>

<h2><b>Q16: What Is Required for a Person Who Has Advanced Money to a Mortgagor to Be Subrogated to the Rights of the Mortgagee?</b></h2><br>
<p>A16: The mortgagor must agree by a registered instrument that the person advancing the money shall be subrogated to the rights of the mortgagee whose mortgage has been redeemed.</p><br>

<h2><b>Q17: What Is the Prohibition of Tacking in Mortgage Law?</b></h2><br>
<p>A17: No mortgagee paying off a prior mortgage shall acquire priority in respect of their original security, and no mortgagee making a subsequent advance shall acquire any priority regarding their security for that advance.</p><br>

<h2><b>Q18: What Rights Does a Mesne Mortgagee Have?</b></h2><br>
<p>A18: A mesne mortgagee has the same rights against mortgagees posterior to themselves as they have against the mortgagor.</p><br>

<h2><b>Q19: When a Co-Mortgagor Redeems the Mortgaged Property, What Can They Add to the Mortgage Money Recoverable From Their Co-Mortgagors?</b></h2><br>
<p>A19: They can add the proportion of the expenses properly incurred in the redemption that is attributable to the share of the co-mortgagors in the property.</p><br>

<h2><b>Q20: How Are the Rights and Liabilities of Parties to an Anomalous Mortgage Determined?</b></h2><br>
<p>A20: The rights and liabilities of the parties to an anomalous mortgage are determined by their contract as evidenced in the mortgage deed, and, where the contract does not extend, by local usage.</p><br>

<h2><b>Q21: What Is a Charge in the Context of Property Law?</b></h2><br>
<p>A21: A charge occurs when immovable property of one person is made security for the payment of money to another, and the transaction does not amount to a mortgage. The provisions that apply to a simple mortgage also apply to such a charge.</p><br>

<h2><b>Q22: Are There Any Exceptions to the Enforcement of a Charge Against Property?</b></h2><br>
<p>A22: Yes, a charge of a trustee on the trust property for expenses incurred in executing the trust is an exception, and no charge can be enforced against property transferred for consideration and without notice of the charge.</p><br>

<h2><b>Q23: Can a Mortgagee Purchase Rights in the Mortgaged Property Without Causing a Merger?</b></h2><br>
<p>A23: Yes, a mortgagee or charge-holder can purchase or acquire rights in the property without causing the mortgage or charge to merge with any subsequent mortgage or charge.</p><br>

<h2><b>Q24: What Happens if a Notice or Tender Needs to Be Served to Someone Not Residing in the District of the Mortgaged Property?</b></h2><br>
<p>A24: Service or tender can be made to an agent holding a general power-of-attorney or otherwise duly authorized to accept such service. If no person or agent can be found, an application can be made to the court for directions on serving the notice.</p><br>

<h2><b>Q25: What Should Be Done if a Person Desiring to Make a Tender Cannot Find the Appropriate Person to Tender To?</b></h2><br>
<p>A25: The person may deposit the amount sought to be tendered in any court where a suit might be brought for redemption of the mortgaged property, and such deposit will have the effect of a tender.</p><br>

<h2><b>Q26: How Can Notices or Tenders Be Served or Accepted on Behalf of a Person Incompetent to Contract?</b></h2><br>
<p>A26: Such notices can be served or tenders made by the legal curator of the property of the incompetent person. If no curator exists, an application can be made to the court to appoint a guardian ad litem for these purposes.</p><br>

<h2><b>Q27: What Authority Does the High Court Have Regarding the Rules in This Chapter?</b></h2><br>
<p>A27: The High Court may make rules consistent with the Act for carrying out its provisions and those in the Courts of Civil Judicature subject to its superintendence.</p><br>


