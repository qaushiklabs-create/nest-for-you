<h2><b>Q1: What Are the Obligations of a Mortgagor in Possession of the Mortgaged Property?</b></h2><br>
<p>A1: A mortgagor in possession is not liable for the general deterioration of the property but must not commit acts that are destructive or permanently injurious, especially if the property’s value is insufficient to cover the mortgage debt.</p><br>

<h2><b>Q2: Under What Conditions Can a Mortgagee Seek Foreclosure or Sale of the Mortgaged Property?</b></h2><br>
<p>A2: A mortgagee can seek foreclosure or sale after the mortgage-money has become due, provided no decree for redemption has been made, and the mortgage-money has not been paid or deposited.</p><br>

<h2><b>Q3: What Is a "Suit for Foreclosure"?</b></h2><br>
<p>A3: A suit for foreclosure is a legal action taken by the mortgagee to debar the mortgagor from redeeming the mortgaged property, allowing the mortgagee to retain the property outright.</p><br>

<h2><b>Q4: What Is the Mortgagee's Obligation When Holding Multiple Mortgages From the Same Mortgagor?</b></h2><br>
<p>A4: If a mortgagee holds multiple mortgages and sues on one, they are bound to sue on all mortgages concerning which the mortgage-money has become due, unless a contrary contract exists.</p><br>

<h2><b>Q5: In What Scenarios Can a Mortgagee Sue for Mortgage-Money?</b></h2><br>
<p>A5: A mortgagee can sue for mortgage-money in the following cases:</p><br>
<ul>
  <li>When the mortgagor has agreed to repay.</li>
  <li>If the property is damaged or insufficient security exists (not due to the mortgagee's fault) and the mortgagor fails to provide additional security.</li>
  <li>If the mortgagee loses part or all of the security due to the mortgagor's wrongful act or default.</li>
  <li>If the mortgagor fails to deliver possession of the property when the mortgagee is entitled to it.</li>
</ul>

<h2><b>Q6: What Discretion Does the Court Have When a Suit Is Brought for Mortgage-Money?</b></h2><br>
<p>A6: The court can stay the suit and all proceedings if the mortgagee has not exhausted all remedies against the mortgaged property, unless the mortgagee decides to abandon their security and re-transfer the property if necessary.</p><br>

<h2><b>Q7: Under What Conditions Does a Mortgagee Have the Power to Sell the Mortgaged Property Without Court Intervention?</b></h2><br>
<p>A7: A mortgagee can sell the mortgaged property without court intervention in the following cases:</p><br>
<ul>
  <li>When the mortgage is an English mortgage and neither party is a Hindu, Muhammadan, Buddhist, or a member of any specified class.</li>
  <li>When a power of sale is expressly conferred by the mortgage-deed and the mortgagee is the Government.</li>
  <li>When a power of sale is conferred by the mortgage-deed and the mortgaged property is located in specified towns or areas.</li>
</ul>

<h2><b>Q8: What Must Occur Before a Mortgagee Can Exercise the Power of Sale?</b></h2><br>
<p>A8: Before exercising the power of sale, the mortgagee must serve a written notice requiring payment to the mortgagor. If the mortgagor defaults on the principal amount for three months after the notice, or if interest amounting to at least five hundred rupees is in arrears for three months, the power of sale can be exercised.</p><br>

<h2><b>Q9: What Protections Do Purchasers Have When Buying Property Sold Under a Mortgagee's Power of Sale?</b></h2><br>
<p>A9: The title of the purchaser is not impeachable on the grounds that no case existed to authorize the sale, that due notice was not given, or that the power was improperly exercised. However, anyone adversely affected by an unauthorized or improper exercise of the power can seek damages against the person exercising the power.</p><br>

<h2><b>Q10: How Must the Proceeds From the Sale of Mortgaged Property Be Handled by the Mortgagee?</b></h2><br>
<p>A10: According to <a href="https://www.indiacode.nic.in/bitstream/123456789/2338/1/A1882-04.pdf" target="_blank" rel="nofollow"> <b>"Transfer of Property Act, 1882."</b></a> The proceeds from the sale must first be used to cover all costs and expenses incurred by the mortgagee in relation to the sale. Then, the mortgage-money and any other due amounts under the mortgage should be paid off. Any remaining funds are to be paid to the person entitled to the mortgaged property or authorized to receive the sale proceeds.</p><br>

<h2><b>Q11: Does the Power of Sale Apply to Mortgages Created Before July 1, 1882?</b></h2><br>
<p>A11: No, the provisions regarding the power of sale do not apply to powers conferred before July 1, 1882.</p><br>

<h2><b>Q12: What Rights Does a Mortgagee Have Regarding the Appointment of a Receiver?</b></h2><br>
<p>A12: A mortgagee has the right to appoint a receiver to manage the income of the mortgaged property if they have the power to sell under section 69. This appointment must be made in writing. If a specific person is named in the mortgage-deed and is willing to act, they can be appointed. If not, the mortgagee may appoint someone with the mortgagor's consent or apply to the Court for a receiver.</p><br>

<h2><b>Q13: What Is the Legal Status of a Receiver Appointed Under These Provisions?</b></h2><br>
<p>A13: A receiver is considered the agent of the mortgagor and the mortgagor is responsible for the receiver's actions unless the mortgage-deed states otherwise or the actions are due to the mortgagee's improper intervention.</p><br>

<h2><b>Q14: What Powers Does a Receiver Have Regarding Income Collection?</b></h2><br>
<p>A14: A receiver can demand and recover the income of the mortgaged property and issue valid receipts for the same. They can act in the name of either the mortgagor or the mortgagee and may exercise any powers delegated to them by the mortgagee.</p><br>

<h2><b>Q15: How Is the Remuneration for the Receiver Determined?</b></h2><br>
<p>A15: The receiver is entitled to retain a commission not exceeding five percent of the gross amount of money received. If no rate is specified in their appointment, the default rate of five percent applies, or the Court may allow a different rate upon application.</p><br>

<h2><b>Q16: What Responsibilities Does the Receiver Have Regarding the Property?</b></h2><br>
<p>A16: The receiver must apply the money received for various expenses including:</p><br>
<ul>
  <li>Discharging rents, taxes, and other outgoings.</li>
  <li>Paying interest due under the mortgage.</li>
  <li>Covering the costs of necessary repairs directed by the mortgagee. They may also be directed to insure the property against loss or damage.</li>
</ul>

<h2><b>Q17: Can the Mortgagee or Mortgagor Remove the Receiver?</b></h2><br>
<p>A17: Yes, the receiver can be removed by a written notice from the mortgagee or mortgagor, or by the Court upon application from either party, provided there is due cause shown.</p><br>

<h2><b>Q18: What Happens to Any Money Received by the Receiver After Their Obligations Are Met?</b></h2><br>
<p>A18: After fulfilling their obligations, any remaining money received by the receiver should be paid to the person entitled to the income of the property or to the individual entitled to the mortgaged property.</p><br>

<h2><b>Q19: Can the Provisions Regarding the Receiver Be Altered?</b></h2><br>
<p>A19: Yes, the provisions regarding the appointment and duties of the receiver can be varied or extended by the mortgage-deed, operating in the same manner as stated in the relevant sections.</p><br>


