<h2><b>Q1: What Is the Definition of "Sale" According to the Provided Text?</b></h2><br>
<p>A1: A "sale" is defined as a transfer of ownership in exchange for a price that is paid, promised, part-paid, or part-promised.</p><br>

<h2><b>Q2: How Is a Sale of Tangible Immovable Property Made if the Property Is Valued at One Hundred Rupees or More?</b></h2><br>
<p>A2: For tangible immovable property valued at one hundred rupees or more, the sale must be made through a registered instrument.</p><br>

<h2><b>Q3: What About the Sale of Tangible Immovable Property Valued at Less Than One Hundred Rupees?</b></h2><br>
<p>A3: For tangible immovable property valued at less than one hundred rupees, the sale can be made either by a registered instrument or by delivery of the property.</p><br>

<h2><b>Q4: How Is Delivery of Tangible Immovable Property Defined?</b></h2><br>
<p>A4: Delivery of tangible immovable property occurs when the seller places the buyer, or someone directed by the buyer, in possession of the property.</p><br>

<h2><b>Q5: What Is a "Contract for Sale" in the Context of Immovable Property?</b></h2><br>
<p>A5: A contract for sale is an agreement that a sale of immovable property will take place based on terms settled between the parties. However, it does not create any interest in or charge on the property itself.</p><br>

<h2><b>Q6: What Is the Specific Amendment Mentioned for Assam Regarding the Registration of Sale?</b></h2><br>
<p>A6: According to <a href="https://www.indiacode.nic.in/bitstream/123456789/2338/1/A1882-04.pdf" target="_blank" rel="nofollow"> <b>"Transfer of Property Act, 1882."</b></a> In Assam, the amendment states that the expression “by a registered instrument” is replaced with “by an instrument registered in the State of Assam,” regardless of the provisions in the Indian Registration Act, 1908.</p><br>

<h2><b>Q7: What Is the Seller Required to Disclose to the Buyer?</b></h2><br>
<p>A7: The seller must disclose any material defects in the property or in the seller’s title that the seller is aware of but the buyer is not, and which the buyer could not discover with ordinary care.</p><br>

<h2><b>Q8: What Documents Must the Seller Provide to the Buyer Upon Request?</b></h2><br>
<p>A8: The seller is required to produce all documents of title relating to the property that are in the seller's possession or power for examination by the buyer.</p><br>

<h2><b>Q9: What Obligations Does the Seller Have Regarding the Property From the Date of the Sale Contract Until Delivery?</b></h2><br>
<p>A9: The seller must take care of the property and all related documents as a prudent owner would and must pay all public charges and rent due up to the date of the sale.</p><br>

<h2><b>Q10: What Rights Does the Seller Retain Until the Ownership of the Property Is Transferred to the Buyer?</b></h2><br>
<p>A10: The seller is entitled to the rents and profits from the property until ownership passes to the buyer.</p><br>

<h2><b>Q11: What Must the Buyer Disclose to the Seller?</b></h2><br>
<p>A11: The buyer must disclose any facts about the nature or extent of the seller’s interest in the property that the buyer is aware of but believes the seller is not, especially if this fact materially increases the value of the seller’s interest.</p><br>

<h2><b>Q12: What Happens if the Ownership of the Property Has Passed to the Buyer?</b></h2><br>
<p>A12: Once ownership has passed, the buyer bears any loss from destruction, injury, or decrease in value of the property that is not caused by the seller, and is responsible for all public charges and rents payable in respect of the property.</p><br>

<h2><b>Q13: What Rights Does the Buyer Have Once They Own the Property?</b></h2><br>
<p>A13: The buyer is entitled to any benefits from improvements or increases in the property’s value and to the rents and profits thereof. The buyer also has a charge on the property for any purchase-money properly paid in anticipation of delivery.</p><br>

<h2><b>Q14: What Can the Court Do When Immovable Property With an Incumbrance Is Sold?</b></h2><br>
<p>A14: The court may direct or allow payment into court to manage the incumbrance, either by investing an amount sufficient to cover ongoing charges or by paying the amount needed to clear the incumbrance and any due interest.</p><br>

<h2><b>Q15: What Is the Condition for Payment Into Court When Dealing With an Annual or Monthly Charge?</b></h2><br>
<p>A15: For annual or monthly charges, the court may require an amount that, when invested in Central Government securities, will generate sufficient interest to cover the charge.</p><br>

<h2><b>Q16: What Additional Payment Is Required Besides the Amount for the Incumbrance?</b></h2><br>
<p>A16: The court may require an additional amount to cover potential future costs, expenses, and interest, which should not exceed one-tenth of the original amount unless the court specifies otherwise for special reasons.</p><br>

<h2><b>Q17: What Happens After the Payment Into Court Is Made?</b></h2><br>
<p>A17: The court may declare the property freed from the incumbrance, issue a conveyance order, and direct the investment of the money in court, unless it decides to waive notice to the incumbrancer for specific reasons.</p><br>

<h2><b>Q18: How Does the Court Manage the Distribution of the Funds After They Are Paid In?</b></h2><br>
<p>A18: After notifying the interested parties, the court can direct payment or transfer of the funds to those entitled and provide instructions regarding the application or distribution of the capital or income.</p><br>

<h2><b>Q19: Can Parties Appeal Decisions Made Under This Section?</b></h2><br>
<p>A19: Yes, an appeal can be made from any declaration, order, or direction made under this section as if it were a decree.</p><br>

<h2><b>Q20: What Is Meant by "Court" in This Context?</b></h2><br>
<p>A20: "Court" refers to a High Court exercising original civil jurisdiction, a District Judge's Court within the relevant local jurisdiction, or any other court designated by the State Government through an official notification.</p><br>

<h2><b>Q21: What Happens When an Owner Mortgages Multiple Properties and Then Sells One or More of Them?</b></h2><br>
<p>A21: If the owner mortgages two or more properties to one person and subsequently sells one or more properties to another person, the buyer is entitled to have the mortgage debt satisfied from the properties not sold to him, provided there is no contract stating otherwise.</p><br>

<h2><b>Q22: What Condition Must Be Met for the Buyer to Have the Mortgage Debt Satisfied From Unsold Properties?</b></h2><br>
<p>A22: The buyer's right to have the mortgage debt satisfied from the unsold properties does not prejudice the rights of the mortgagee or anyone else who has acquired an interest in the properties for consideration.</p><br>

<h2><b>Q23: Can the Buyer of the Sold Property Affect the Rights of the Mortgagee?</b></h2><br>
<p>A23: No, the buyer cannot affect the rights of the mortgagee or any other parties who have acquired interests in the properties. Their rights must be preserved.</p><br>

<h2><b>Q24: What Does "Marshalling" Refer to in This Context?</b></h2><br>
<p>A24: Marshalling refers to the principle that allows a buyer, in certain circumstances, to ensure that the mortgage debt is satisfied from properties that were not sold, thereby protecting their own interests.</p><br>

<h2><b>Q25: Is There Any Possibility for a Contract to Override the Buyer's Entitlement?</b></h2><br>
<p>A25: Yes, if there is a contract to the contrary, the terms of that contract will take precedence over the buyer's entitlement to have the mortgage debt satisfied from the unsold properties.</p><br>


