<h2><b>Q1: What Is Defined as an "Exchange"?</b></h2><br>
<p>A1: An <a href="https://www.indiacode.nic.in/bitstream/123456789/2338/1/A1882-04.pdf" target="_blank" rel="nofollow"> <b>"Exchange"</b></a> is when two persons mutually transfer the ownership of one thing for the ownership of another, with neither thing or both things being money only.</p><br>

<h2><b>Q2: How Is the Transfer of Property Completed in an Exchange?</b></h2><br>
<p>A2: The transfer of property in completion of an exchange can only be made in the manner provided for the transfer of such property by sale.</p><br>

<h2><b>Q3: What Happens if a Party to an Exchange Is Deprived of the Thing Received Due to a Defect in Title?</b></h2><br>
<p>A3: If a party is deprived of the thing received in exchange due to a defect in the title of the other party, the other party is liable for the loss caused, or at the option of the deprived party, for the return of the thing transferred if it is still in possession of the other party or their legal representative.</p><br>

<h2><b>Q4: Is the Other Party Liable if the Terms of the Exchange Indicate Otherwise?</b></h2><br>
<p>A4: No, the other party is not liable if a contrary intention appears from the terms of the exchange.</p><br>

<h2><b>Q5: What Are the Rights and Liabilities of the Parties in an Exchange?</b></h2><br>
<p>A5: Each party in an exchange has the rights and is subject to the liabilities of a seller regarding what they give, and has the rights and is subject to the liabilities of a buyer regarding what they take.</p><br>

<h2><b>Q6: What Warranty Is Provided When Money Is Exchanged?</b></h2><br>
<p>A6: When money is exchanged, each party warrants the genuineness of the money given by them.</p><br>


