<h2><b>Q1: What Is Defined as a "Gift"?</b></h2><br>
<p>A1: A <a href="https://www.indiacode.nic.in/bitstream/123456789/2338/1/A1882-04.pdf" target="_blank" rel="nofollow"> <b>"Gift"</b></a> is the voluntary transfer of existing moveable or immoveable property made without consideration by a donor to a donee, which must be accepted by or on behalf of the donee.</p><br>

<h2><b>Q2: When Must Acceptance of a Gift Be Made?</b></h2><br>
<p>A2: Acceptance of a gift must be made during the donor's lifetime and while the donor is capable of giving. If the donee dies before acceptance, the gift is void.</p><br>

<h2><b>Q3: How Is a Gift of Immoveable Property Effected?</b></h2><br>
<p>A3: A gift of immoveable property must be effected by a registered instrument signed by the donor and attested by at least two witnesses.</p><br>

<h2><b>Q4: How Can a Gift of Moveable Property Be Made?</b></h2><br>
<p>A4: A gift of moveable property can be made by a registered instrument signed by the donor or by delivery, which can be done in the same manner as goods sold.</p><br>

<h2><b>Q5: What Happens if a Gift Includes Future Property?</b></h2><br>
<p>A5: A gift that includes both existing and future property is void concerning the future property.</p><br>

<h2><b>Q6: What Occurs if a Gift Is Made to Multiple Donees, but One Does Not Accept?</b></h2><br>
<p>A6: If a gift is made to two or more donees and one does not accept, the gift is void concerning the interest that the non-accepting donee would have taken had they accepted.</p><br>

<h2><b>Q7: Under What Conditions Can a Gift Be Suspended or Revoked?</b></h2><br>
<p>A7: A gift can be suspended or revoked if the donor and donee agree on a specified event that is not dependent on the donor's will. However, a gift that is revocable at the mere will of the donor is void. A gift may also be revoked in cases where a contract could be rescinded, except for reasons related to the lack or failure of consideration.</p><br>

<h2><b>Q8: Can a Gift Be Revoked Without Affecting the Rights of Certain Parties?</b></h2><br>
<p>A8: Yes, the rights of transferees for consideration without notice are not affected by the revocation of a gift.</p><br>

<h2><b>Q9: What Is an Onerous Gift?</b></h2><br>
<p>A9: An onerous gift involves a single transfer to the same person of several things, where one item is burdened by an obligation. The donee must accept the entire gift; if they refuse one item, they cannot take any of the gifts.</p><br>

<h2><b>Q10: How Does Acceptance Work With Separate and Independent Transfers?</b></h2><br>
<p>A10: If a gift consists of two or more separate transfers, the donee can accept one item and refuse others, even if the accepted item is beneficial and the refused ones are onerous.</p><br>

<h2><b>Q11: What Happens if a Donee Not Competent to Contract Accepts an Onerous Gift?</b></h2><br>
<p>A11: A donee who is not competent to contract and accepts property burdened by an obligation is not bound by the acceptance. However, if they become competent to contract, become aware of the obligation, and retain the property, they then become bound by that obligation.</p><br>

<h2><b>Q12: Provide an Example of an Onerous Gift Scenario.</b></h2><br>
<p>A12: If A has shares in a profitable company X and shares in a struggling company Y, and gives all his shares to B, who refuses the shares in Y, then B cannot accept the shares in X either.</p><br>

<h2><b>Q13: What Is the Liability of a Universal Donee?</b></h2><br>
<p>A13: A universal donee, who receives the entire property of the donor, is personally liable for all debts and liabilities of the donor at the time of the gift, to the extent of the property received.</p><br>

<h2><b>Q14: Are There Any Exceptions for Gifts Made in Contemplation of Death?</b></h2><br>
<p>A14: Yes, the provisions regarding gifts do not apply to gifts of moveable property made in contemplation of death, nor do they affect any rules of Muhammadan law.</p><br>

