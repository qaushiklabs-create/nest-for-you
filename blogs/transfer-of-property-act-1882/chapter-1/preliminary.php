<h2><b>Q1: What Is the Short Title of the Act Discussed?</b></h2><br>
<p>A1: The Act may be called the <a href="https://www.indiacode.nic.in/bitstream/123456789/2338/1/A1882-04.pdf" target="_blank" rel="nofollow"> <b>"Transfer of Property Act, 1882."</b></a></p><br>

<h2><b>Q2: When Did the Transfer of Property Act, 1882, Come Into Force?</b></h2><br>
<p>A2: It came into force on the first day of <b>July, 1882</b>.</p><br>

<h2><b>Q3: To What Geographical Area Does the Act Initially Extend?</b></h2><br>
<p>A3: It initially extends to the whole of <b>India</b>, except certain territories that were part of Part B States or the States of Bombay, Punjab, and Delhi before November 1, 1956.</p><br>

<h2><b>Q4: Can the Act Be Extended to Other Territories?</b></h2><br>
<p>A4: Yes, the Act may be extended to other territories by notification in the <b>Official Gazette</b> by the concerned State Government.</p><br>

<h2><b>Q5: What Provisions Can a State Government Exempt From the Act?</b></h2><br>
<p>A5: A State Government may exempt any part of the territories from Sections 54 (paragraphs 2 and 3), 59, 107, and 123 of the Act.</p><br>

<h2><b>Q6: Are There Limitations on the Extension of Certain Sections of the Act?</b></h2><br>
<p>A6: Yes, Sections 54 (paragraphs 2 and 3), 59, 107, and 123 shall not extend to any district or tract excluded from the operation of the Indian Registration Act, 1908.</p><br>

<h2><b>Q7: What Is the Effect of the Act on Existing Enactments?</b></h2><br>
<p>A7: The enactments specified in the Schedule of the Act are repealed, but this does not affect provisions of other enactments or contracts arising before the Act.</p><br>

<h2><b>Q8: What Types of Property Are Excluded From the Definition of "Immoveable Property"?</b></h2><br>
<p>A8: "Immoveable property" does not include <b>standing timber, growing crops, or grass</b>.</p><br>

<h2><b>Q9: How Is the Term “Instrument” Defined?</b></h2><br>
<p>A9: “Instrument” means a <b>non-testamentary instrument</b>.</p><br>

<h2><b>Q10: What Does “Attested” Mean in Relation to an Instrument?</b></h2><br>
<p>A10: “Attested” means the instrument is attested by two or more witnesses who have seen the executant sign or acknowledge the instrument, and they must sign in the presence of the executant.</p><br>

<h2><b>Q11: What Does “Attached to the Earth” Refer To?</b></h2><br>
<p>A11: It refers to things rooted or imbedded in the earth, like <b>trees or walls</b>.</p><br>

<h2><b>Q12: How Is "Actionable Claim" Defined?</b></h2><br>
<p>A12: "Actionable claim" refers to a claim to any debt (not secured by mortgage of immoveable property) or any beneficial interest in moveable property.</p><br>

<h2><b>Q13: When Is a Person Considered to Have Notice of a Fact?</b></h2><br>
<p>A13: A person has notice of a fact when they actually know it, or through willful abstention or gross negligence.</p><br>

<h2><b>Q14: What Is the Implication of a Registered Instrument Concerning Immoveable Property?</b></h2><br>
<p>A14: Any person acquiring property through a registered instrument is deemed to have notice of that instrument from the date of registration.</p><br>

<h2><b>Q15: How Does the Act Address the Notice of Title in Relation to Actual Possession?</b></h2><br>
<p>A15: A person acquiring immoveable property is deemed to have notice of any title of a person in actual possession of the property.</p><br>

<h2><b>Q16: What Happens If an Agent Acquires Notice of a Fact on Behalf of a Principal?</b></h2><br>
<p>A16: The principal is deemed to have notice of that fact unless the agent fraudulently conceals it.</p><br>

<h2><b>Q17: How Are the Chapters and Sections of the Act Related to the Indian Contract Act?</b></h2><br>
<p>A17: The chapters and sections related to contracts shall be part of the <b>Indian Contract Act, 1872</b>.</p><br>

<h2><b>Q18: Which Sections of the Act Are Supplemental to the Indian Registration Act?</b></h2><br>
<p>A18: Sections 54 (paragraphs 2 and 3), 59, 107, and 123 are supplemental to the <b>Indian Registration Act, 1908</b>.</p><br>


