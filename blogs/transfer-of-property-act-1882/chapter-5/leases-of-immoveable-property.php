<h2><b>Q1: What Is a Lease of Immoveable Property?</b></h2><br>
<p>A1: A lease of immoveable property is a transfer of the right to enjoy such property for a certain time, either express or implied, or in perpetuity, in consideration of a price paid or promised, or other forms of value rendered periodically or on specified occasions.</p><br>

<h2><b>Q2: What Is the Role of the Transferor and Transferee in a Lease?</b></h2><br>
<p>A2: The transferor is called the lessor, and the transferee is called the lessee.</p><br>

<h2><b>Q3: What Terms Are Used to Describe the Financial Aspects of a Lease?</b></h2><br>
<p>A3: The price paid or promised for the lease is called the premium, and the money, share, service, or other thing rendered is referred to as the rent.</p><br>

<h2><b>Q4: What Is the Default Duration of a Lease for Agricultural or Manufacturing Purposes in the Absence of a Written Contract or Local Usage?</b></h2><br>
<p>A4: In the absence of a contract or local law, a lease for agricultural or manufacturing purposes is deemed to be a lease from year to year, terminable by either party with six months' notice.</p><br>

<h2><b>Q5: What Is the Default Duration of a Lease for Purposes Other Than Agricultural or Manufacturing?</b></h2><br>
<p>A5: A lease for any other purpose is deemed to be a lease from month to month, terminable by either party with fifteen days' notice.</p><br>

<h2><b>Q6: When Does the Notice Period for Terminating a Lease Commence?</b></h2><br>
<p>A6: The notice period commences from the date of receipt of the notice.</p><br>

<h2><b>Q7: Is a Notice Invalid if It Falls Short of the Specified Period Mentioned in the Lease Terms?</b></h2><br>
<p>A7: No, a notice is not deemed invalid merely because the period falls short, as long as a suit or proceeding is filed after the expiry of the specified period.</p><br>

<h2><b>Q8: What Are the Requirements for a Notice to Terminate a Lease?</b></h2><br>
<p>A8: Every notice must be in writing, signed by or on behalf of the person giving it, and can be sent by post, delivered personally, or affixed to a conspicuous part of the property if personal delivery is impracticable.</p><br>

<h2><b>Q9: How Must a Lease of Immoveable Property from Year to Year, or for a Term Exceeding One Year, Be Made?</b></h2><br>
<p>A9: Such a lease can only be made by a registered instrument.</p><br>

<h2><b>Q10: How Can Other Leases of Immoveable Property Be Made?</b></h2><br>
<p>A10: Other leases can be made either by a registered instrument or by oral agreement accompanied by delivery of possession.</p><br>

<h2><b>Q11: What Is Required for a Registered Lease Instrument to Be Valid?</b></h2><br>
<p>A11: The registered instrument must be executed by both the lessor and the lessee.</p><br>

<h2><b>Q12: Can the State Government Modify the Requirements for Making Leases?</b></h2><br>
<p>A12: Yes, the State Government can direct, through notifications in the Official Gazette, that certain leases may be made by unregistered instruments or oral agreements without delivery of possession.</p><br>

<h2><b>Q13: What Rights Does the Lessor Have Regarding the Condition of the Property?</b></h2><br>
<p>A13: The lessor is bound to disclose any material defect in the property that affects its intended use and of which the lessee is unaware and could not discover with ordinary care.</p><br>

<h2><b>Q14: What Is the Lessor Obligated to Do Upon the Lessee's Request?</b></h2><br>
<p>A14: The lessor is obligated to put the lessee in possession of the property upon request.</p><br>

<h2><b>Q15: What Assurance Does the Lessor Provide to the Lessee Regarding the Lease?</b></h2><br>
<p>A15: The lessor assures that if the lessee pays the reserved rent and fulfills binding contracts, the lessee may hold the property without interruption during the lease term.</p><br>

<h2><b>Q16: What Happens if Any Accession Is Made to the Property During the Lease?</b></h2><br>
<p>A16: Such accession shall be deemed to be comprised in the lease, subject to the law relating to alluvion.</p><br>

<h2><b>Q17: What Options Does the Lessee Have if a Material Part of the Property Is Destroyed?</b></h2><br>
<p>A17: If a material part of the property is destroyed by external forces, the lease shall be void at the lessee's option, unless the destruction is due to the lessee's wrongful act.</p><br>

<h2><b>Q18: What Rights Does the Lessee Have if the Lessor Neglects Necessary Repairs?</b></h2><br>
<p>A18: If the lessor neglects to make repairs within a reasonable time after notice, the lessee may make the repairs themselves and deduct the costs from the rent or recover it from the lessor.</p><br>

<h2><b>Q19: Can the Lessee Remove Attachments Made to the Property After the Lease Ends?</b></h2><br>
<p>A19: Yes, the lessee can remove attachments while in possession but must leave the property in the condition it was received.</p><br>

<h2><b>Q20: What Rights Does the Lessee Have Concerning Crops Planted on the Property?</b></h2><br>
<p>A20: Upon termination of a lease of uncertain duration, the lessee is entitled to the crops planted and growing on the property and may access the property to gather them.</p><br>

<h2><b>Q21: What Can the Lessee Do With Their Interest in the Property?</b></h2><br>
<p>A21: The lessee may transfer their interest absolutely, by way of mortgage, or sub-lease, but remains subject to all liabilities under the lease.</p><br>

<h2><b>Q22: What Must the Lessee Disclose to the Lessor Regarding Their Interest?</b></h2><br>
<p>A22: The lessee must disclose any facts about the nature or extent of their interest that materially increase its value, of which the lessor is unaware.</p><br>

<h2><b>Q23: What Obligations Does the Lessee Have Regarding Payment of Rent?</b></h2><br>
<p>A23: The lessee is bound to pay or tender the premium or rent at the proper time and place to the lessor or their agent.</p><br>

<h2><b>Q24: What Is the Lessee's Responsibility for the Condition of the Property at Lease Termination?</b></h2><br>
<p>A24: The lessee must restore the <a href="https://www.indiacode.nic.in/bitstream/123456789/2338/1/A1882-04.pdf" target="_blank" rel="nofollow"> <b>"Transfer of Property"</b></a> in as good condition as it was received, subject to reasonable wear and tear.</p><br>

<h2><b>Q25: What Should the Lessee Do if They Become Aware of Any Proceedings Concerning the Property?</b></h2><br>
<p>A25: The lessee must promptly notify the lessor of any proceedings to recover the property or any interference with the lessor's rights.</p><br>

<h2><b>Q26: How Can the Lessee Use the Property?</b></h2><br>
<p>A26: The lessee may use the property as a prudent person would but must not use it for purposes other than intended or damage the property in any way.</p><br>

<h2><b>Q27: What Must the Lessee Do With Permanent Structures on the Property?</b></h2><br>
<p>A27: The lessee must not erect any permanent structure without the lessor's consent, except for agricultural purposes.</p><br>

<h2><b>Q28: What Is the Lessee's Obligation Upon Termination of the Lease?</b></h2><br>
<p>A28: Upon termination of the lease, the lessee must put the lessor back into possession of the property.</p><br>

<h2><b>Q29: What Happens if the Lessor Transfers the Leased Property?</b></h2><br>
<p>A29: If the lessor transfers the property or any part of it, the transferee possesses all the rights and, if the lessee elects, is subject to all the liabilities of the lessor, but the lessor remains liable unless the lessee chooses to treat the transferee as the liable party.</p><br>

<h2><b>Q30: Are There Any Limitations on the Transferee Regarding Arrears of Rent?</b></h2><br>
<p>A30: Yes, the transferee is not entitled to arrears of rent that were due before the transfer. If the lessee pays rent to the lessor without knowing of the transfer, the lessee is not liable to pay again to the transferee.</p><br>

<h2><b>Q31: How Is the Premium or Rent Determined if Part of the Property Is Transferred?</b></h2><br>
<p>A31: The lessor, transferee, and lessee can determine the portion of the premium or rent payable for the part transferred. If they cannot agree, a court may make the determination.</p><br>

<h2><b>Q32: How Is the Duration of a Lease Calculated When a Specific Start Date Is Given?</b></h2><br>
<p>A32: The day from which the lease commences is excluded in calculating the duration of the lease. If no start date is mentioned, it begins from the making of the lease.</p><br>

<h2><b>Q33: What Is the Default Duration of a Lease if It Is for a Year or More?</b></h2><br>
<p>A33: In the absence of an express agreement to the contrary, a lease lasting a year or more lasts for the whole anniversary of the commencement day.</p><br>

<h2><b>Q34: Who Has the Option to Determine a Lease if It Is Expressed to Be Terminable?</b></h2><br>
<p>A34: If the lease does not specify who has the option to terminate, the lessee has the option to determine the lease.</p><br>

<h2><b>Q35: How Can a Lease of Immoveable Property Be Determined?</b></h2><br>
<p>A35: A lease can be determined in several ways:<br>
<ul>
  <li>By the expiry of the limited time.</li>
  <li>By the occurrence of a specified event if the lease is conditional.</li>
  <li>By the lessor’s interest terminating due to an event.</li>
  <li>If both lessor and lessee's interests become vested in the same person.</li>
  <li>Through express surrender by mutual agreement.</li>
  <li>Through implied surrender.</li>
  <li>By forfeiture, such as breach of express conditions or insolvency.</li>
  <li>Upon expiration of a notice to determine or quit the lease.</li>
</ul></p><br>

<h2><b>Q36: What Is an Example of Implied Surrender of a Lease?</b></h2><br>
<p>A36: If a lessee accepts a new lease from the lessor that takes effect during the existing lease, it constitutes an implied surrender of the former lease, resulting in its termination.</p><br>

<h2><b>Q37: What Happens if a Lessee Remains in Possession After the Lease Ends?</b></h2><br>
<p>A37: If a lessee or under-lessee remains in possession after the lease ends and the lessor or their legal representative accepts rent or assents to the continued possession, the lease is renewed from year to year or month to month, depending on the purpose of the lease, unless there is an agreement to the contrary.</p><br>

<h2><b>Q38: Can You Provide an Example of Holding Over?</b></h2><br>
<p>A38: Yes. If A lets a house to B for five years and B underlets it to C at a monthly rent of Rs. 100, when the five years expire but C continues to pay rent to A, C’s lease is renewed from month to month.</p><br>

<h2><b>Q39: How Does Holding Over Work in a Lease for a Life?</b></h2><br>
<p>A39: For example, if A lets a farm to B for the life of C and C dies, but B continues to possess the farm with A's assent, B's lease is renewed from year to year.</p><br>

<h2><b>Q40: Do the Provisions of This Chapter Apply to Leases for Agricultural Purposes?</b></h2><br>
<p>A40: No, the provisions do not apply to leases for agricultural purposes unless the State Government publishes a notification in the Official Gazette declaring certain provisions applicable.</p><br>


