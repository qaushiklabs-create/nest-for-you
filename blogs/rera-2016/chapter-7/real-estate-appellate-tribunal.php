<h2><b>Establishment of Real Estate Appellate Tribunal.</b></h2><br>
<p>(1) The appropriate Government shall, within a period of one year from the date of coming into force of this Act, by notification, establish an Appellate Tribunal to be known as the — (name of the State/Union territory) Real Estate Appellate Tribunal.</p>

<p>(2) The appropriate Government may, if it deems necessary, establish one or more benches of the Appellate Tribunal, for various jurisdictions, in the State or Union territory, as the case may be.</p>

<p>(3) Every bench of the Appellate Tribunal shall consist of at least one Judicial Member and one Administrative or Technical Member.</p>

<p>(4) The appropriate Government of two or more States or Union territories may, if it deems fit, establish one single Appellate Tribunal:
Provided that, until the establishment of an Appellate Tribunal under this section, the appropriate Government shall designate, by order, any Appellate Tribunal functioning under any law for the time being in force, to be the Appellate Tribunal to hear appeals under the Act:
Provided further that after the Appellate Tribunal under this section is established, all matters pending with the Appellate Tribunal designated to hear appeals, shall stand transferred to the Appellate Tribunal so established and shall be heard from the stage such appeal is transferred.</p>

<p>(5) Any person aggrieved by any direction or decision or order made by the Authority or by an adjudicating officer under this Act may prefer an appeal before the Appellate Tribunal having jurisdiction over the matter:
Provided that where a promoter files an appeal with the Appellate Tribunal, it shall not be entertained, without the promoter first having deposited with the Appellate Tribunal at least thirty per cent. of the penalty, or such higher percentage as may be determined by the Appellate Tribunal, or the total amount to be paid to the allottee including interest and compensation imposed on him, if any, or with both, as the case may be, before the said appeal is heard.</p>

<p><b>Explanation.—</b>For the purpose of this sub-section "person" shall include the association of allottees or any voluntary consumer association registered under any law for the time being in force.</p>

<h2><b>Application for settlement of disputes and appeals to Appellate Tribunal.</b></h2><br>
<p>(1) The appropriate Government or the competent authority or any person aggrieved by any direction or order or decision of the Authority or the adjudicating officer may prefer an appeal to the Appellate Tribunal.</p>

<p>(2) Every appeal made under sub-section (1) shall be preferred within a period of sixty days from the date on which a copy of the direction or order or decision made by the Authority or the adjudicating officer is received by the appropriate Government or the competent authority or the aggrieved person and it shall be in such form and accompanied by such fee, as may be prescribed:
Provided that the Appellate Tribunal may entertain any appeal after the expiry of sixt days if it is satisfied that there was sufficient cause for not filing it within that period.</p>

<p>(3) On receipt of an appeal under sub-section (1), the Appellate Tribunal may after giving the parties an opportunity of being heard, pass such orders, including interim orders, as it thinks fit.</p>

<p>(4) The Appellate Tribunal shall send a copy of every order made by it to the parties and to the Authority or the adjudicating officer, as the case may be.</p>

<p>(5) The appeal preferred under sub-section (1) shall be dealt with by it as expeditiously as possible and an endeavor shall be made by it to dispose of the appeal within a period of sixty days from the date of receipt of the appeal:
Provided that where any such appeal could not be disposed of within the said period of sixty days, the Appellate Tribunal shall record its reasons in writing for not disposing of the appeal within that period.</p>

<p>(6) The Appellate Tribunal may, for the purpose of examining the legality or propriety or correctness of any order or decision of the Authority or the adjudicating officer, on its own motion or otherwise, call for the records relevant to disposing of such appeal and make such orders as it thinks fit.</p>

<h2><b>Qualifications for appointment of Chairperson and Members</b></h2><br>
<p>(1) A person shall not be qualified for appointment as the Chairperson or a Member
of the Appellate Tribunal unless he,—
(a) in the case of Chairperson, is or has been a Judge of a High Court; and
(b) in the case of a Judicial Member, he has held a judicial office in the territory of India for at least fifteen years or has been a member of the Indian Legal Service and has held the post of Additional Secretary of that service or any equivalent post, or has been an advocate for at least twenty years with experience in dealing with real estate matters; and
(c) in the case of a Technical or Administrative Member, he is a person who is
well-versed in the field of urban development, housing, real estate development,
infrastructure, economics, planning, law, commerce, accountancy, industry,
management, public affairs, or administration and possesses experience of at least twenty years in the field or who has held the post in the Central Government, or a State Government equivalent to the post of Additional Secretary to the Government of India or an equivalent post in the Central Government or an equivalent post in the State Government.</p>

<p>(2) The Chairperson of the Appellate Tribunal shall be appointed by the appropriate Government in consultation with the Chief Justice of the High Court or his nominee.</p>

<p>(3) The judicial Members and Technical or Administrative Members of the Appellate Tribunal shall be appointed by the appropriate Government on the recommendations of a Selection Committee consisting of the Chief Justice of the High Court or his nominee, the Secretary of the Department handling Housing, and the Law Secretary and in such manner as may be prescribed.</p>

<h2><b>Term of office of Chairperson and Members.</b></h2><br>
<p>(1) The Chairperson of the Appellate Tribunal or a Member of the Appellate Tribunal shall hold office, as such for a term not exceeding five years from the date on which he enters upon his office, but shall not be eligible for re-appointment:
Provided that in case a person, who is or has been a Judge of a High Court, has been appointed as Chairperson of the Tribunal, he shall not hold office after he has attained the age of sixty-seven years:
Provided further that no Judicial Member or Technical or Administrative Member shall hold office after he has attained the age of sixty-five years.</p>

<p>(2) Before appointing any person as Chairperson or Member, the appropriate Government shall satisfy itself that the person does not have any such financial or other interest, as is likely to affect prejudicially his functions as such member.</p>

<h2><b>Removal of Chairperson and Member from office in certain circumstances.</b></h2><br>
<p>(1) The appropriate Government may, in consultation with the Chief Justice of the High Court, remove from office of the Chairperson or any judicial Member or Technical or Administrative Member of the Appellate Tribunal, who—
(a) has been adjudged as an insolvent; or
(b) has been convicted of an offence which, in the opinion of the appropriate Government involves moral turpitude; or
(c) has become physically or mentally incapable; or
(d) has acquired such financial or other interest as is likely to affect prejudicially his functions; or
(e) has so abused his position as to render his continuance in office prejudicial to the public interest.</p>

<p>(2) The Chairperson or Judicial member or Technical or Administrative Member shall not be removed from his office except by an order made by the appropriate Government after an inquiry made by the Judge of the High Court in which such Chairperson or Judicial member or Technical or Administrative Member has been informed of the charges against him and given a reasonable opportunity of being heard in respect of those charges.</p>

<p>(3) The appropriate Government may suspend from the office of the Chairperson or Judicial member or Technical or Administrative Member in respect of whom a reference of conducting an inquiry has been made to the Judge of the High Court under sub-section (2), until the appropriate Government passes an order on receipt of the report of inquiry made by the Judge of the High Court on such reference.</p>

<p>(4) The appropriate Government may, by rules, regulate the procedure for inquiry referred to in sub-section (2).</p>

<h2><b>Restrictions on Chairperson or Judicial Member or Technical or Administrative Member on employment after cessation of office</b></h2><br>
<p>(1) The Chairperson or Judicial Member or Technical or Administrative Member,
ceasing to hold office as such shall not:—
(a) Accept any employment in, or connected with, the management or
administration of, any person or organisation which has been associated with any
work under this Act, from the date on which he ceases to hold office:
Provided that nothing contained in this clause shall apply to any employment
under the appropriate Government or a local authority or in any statutory authority or any corporation established by or under any Central, State or provincial Act or a Government Company as defined under clause (45) of section 2 of the Companies
Act, 2013, which is not a promoter as per the provisions of this Act;
(b) act, for or on behalf of any person or organisation in connection with any
specific proceeding or transaction or negotiation or a case to which the Authority is a party and with respect to which the Chairperson or Judicial Member or Technical or Administrative Member had, before cessation of office, acted for or provided advice to, the Authority;
(c) give advice to any person using information which was obtained in his capacity as the Chairperson or Judicial Member or Technical or Administrative Member and
being unavailable to or not being able to be made available to the public;
(d) enter into a contract of service with, or accept an appointment to a board of directors of, or accept an offer of employment with, an entity with which he had direct and significant official dealings during his term of office as such.</p>

<p>(2) The Chairperson or Judicial Member or Technical or Administrative Member shall not communicate or reveal to any person any matter which has been brought under his consideration or known to him while acting as such.</p>

<h2><b>Officers and other employees of Appellate Tribunal</b></h2><br>
<p>(1) The appropriate Government shall provide the Appellate Tribunal with such
officers and employees as it may deem fit.</p>

<p>(2) The officers and employees of the Appellate Tribunal shall discharge their functions under the general superintendence of its Chairperson.</p>

<p>(3) The salary and allowances payable to, and the other terms and conditions of service of, the officers and employees of the Appellate Tribunal shall be such as may be prescribed.</p>

<h2><b>Vacancies</b></h2><br>
<p>52. If, for reason other than temporary absence, any vacancy occurs in the office of the Chairperson or a Member of the Appellate Tribunal, the appropriate Government shall appoint another person in accordance with the provisions of this Act to fill the vacancy and the proceedings may be continued before the Appellae Tribunal from the stage at which the vacancy is filled</p>
<h2><b>Powers of Tribunal.</b></h2><br>
<p>(1) The Appellate Tribunal shall not be bound by the procedure laid down by the Code of Civil Procedure, 1908 but shall be guided by the principles of natural justice.</p>

<p>(2) Subject to the provisions of this Act, the Appellate Tribunal shall have power to regulate its own procedure.</p>

<p>(3) The Appellate Tribunal shall also not be bound by the rules of evidence contained in the Indian Evidence Act, 1872.</p>

<p>(4) The Appellate Tribunal shall have, for the purpose of discharging its functions under this Act, the same powers as are vested in a civil court under the Code of Civil Procedure, 1908 in respect of the following matters, namely:—
(a) summoning and enforcing the attendance of any person and examining him
on oath;
(b) requiring the discovery and production of documents;
(c) receiving evidence on affidavits;
(d) issuing commissions for the examinations of witnesses or documents;
(e) reviewing its decisions;
(f) dismissing an application for default or directing it ex parte; and
(g) any other matter which may be prescribed.</p>

<p>(5) All proceedings before the Appellate Tribunal shall be deemed to be judicial proceedings within the meaning of sections 193, 219 and 228 for the purposes of section 196 of the Indian Penal Code, and the Appellate Tribunal shall be deemed to be civil court for the purposes of section 195 and Chapter XXVI of the Code of Criminal Procedure, 1973</p>

<h2><b>Administrative powers of Chairperson of Appellate Tribunal.</b></h2><br>
<p>54. The Chairperson shall have powers of general superintendence and direction in the conduct of the affairs of Appellate Tribunal and he shall, in addition to presiding over the meetings of the Appellate Tribunal exercise and discharge such administrative powers and functions of the Appellate Tribunal as may be prescribed</p>

<h2><b>Right to legal representation</b></h2><br>
<p>The applicant or appellant may either appear in person or authorise one or more chartered accountants or company secretaries or cost accountants or legal practitioners or any of its officers to present his or its case before the Appellate Tribunal or the Regulatory Authority or the adjudicating officer, as the case may be.</p>

<p><b>Explanation.—</b>For the purposes of this section,—
(a) "chartered accountant" means a chartered accountant as defined in clause (b) of sub-section (1) of section 2 of the Chartered Accountants Act, 1949 or any other law for the time being in force and who has obtained a certificate of practice under sub-section (1) of section 6 of that Act;
(b) "company secretary" means a company secretary as defined in clause (c) of sub-section (1) of section 2 of the Company Secretaries Act, 1980 or any other law for the time being in force and who has obtained a certificate of practice under sub-section (1) of section 6 of that Act;
(c) "cost accountant" means a cost accountant as defined in clause (b) of sub-section (1) of section 2 of the Cost and Works Accountants Act, 1959 or any other law for the time being in force and who has obtained a certificate of practice under sub-section (1) of section 6 of that Act;
(d) "legal practitioner" means an advocate, vakil or an attorney of any High Court, and includes a pleader in practice.</p>

<h2><b>Orders passed by Appellate Tribunal to be executable as a decree</b></h2><br>
<p>(1) Every order made by the Appellate Tribunal under this Act shall be executable by the Appellate Tribunal as a decree of civil court, and for this purpose, the Appellate Tribunal shall have all the powers of a civil court.</p>

<p>(2) Notwithstanding anything contained in sub-section (1), the Appellate Tribunal may transmit any order made by it to a civil court having local jurisdiction and such civil court shall execute the order as if it were a decree made by the court.</p>

<h2><b>Appeal to High Court.</b></h2><br>
<p>(1) Any person aggrieved by any decision or order of the Appellate Tribunal, may, file an appeal to the High Court, within a period of sixty days from the date of communication of the decision or order of the Appellate Tribunal, to him, on any one or more of the grounds specified in section 100 of the Code of Civil Procedure, 1908:
Provided that the High Court may entertain the appeal after the expiry of the said period of sixty days, if it is satisfied that the appellant was prevented by sufficient cause from preferring the appeal in time.
<b>Explanation.—</b>The expression "High Court" means the High Court of a State or Union territory where the real estate project is situated.</p>

<p>(2) No appeal shall lie against any decision or order made by the Appellate Tribunal with the consent of the parties.</p><br>

