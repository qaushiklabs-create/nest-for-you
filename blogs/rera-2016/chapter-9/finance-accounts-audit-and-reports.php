<h2><b>Grants and loans by Central Government</b></h2><br>
<p>73. The Central Government may, after due appropriation made by Parliament in this behalf, make to the Authority grants and loans of such sums of money as that Government may consider necessary.</p>

<h2><b>Grants and loans by State Government</b></h2><br>
<p>74. The State Government may, after due appropriation made by State Legislature by law in this behalf, make to the Authority, grants and loans of such sums of money as the State Government may think fit for being utilised for the purposes of this Act.</p>
<h2><b>Constitution of Fund.</b></h2><br>
<p>(1) The appropriate Government shall constitute a fund to be called the 'Real Estate Regulatory Fund' and there shall be credited thereto,—
(a) all Government grants received by the Authority;
(b) the fees received under this Act;
(c) the interest accrued on the amounts referred to in clauses (a) to (b).</p>

<p>(2) The Fund shall be applied for meeting—
(a) the salaries and allowances payable to the Chairperson and other Members, the adjudicating officer and the administrative expenses including the salaries and allowances payable to the officers and other employees of the Authority and the Appellate Tribunal;
(b) the other expenses of the Authority in connection with the discharge of its functions and for the purposes of this Act.</p>

<p>(3) The Fund shall be administered by a committee of such Members of the Authority as may be determined by the Chairperson.</p>

<p>(4) The committee appointed under sub-section (3) shall spend monies out of the Fund for carrying out the objects for which the Fund has been constituted.</p>

<h2><b>Crediting sums realised by way of penalties to Consolidated Fund of India or State account.</b></h2><br>
<p>(1) All sums realised, by way of penalties, imposed by the Appellate Tribunal or the Authority, in the Union territories, shall be credited to the Consolidated Fund of India.</p>

<p>(2) All sums realised, by way of penalties, imposed by the Appellate Tribunal or the Authority, in a State, shall be credited to such account as the State Government may specify.</p>

<h2><b>Budget, accounts and audit</b></h2><br>
<p>(1) The Authority shall prepare a budget, maintain proper accounts and other relevant records and prepare an annual statement of accounts in such form as may be prescribed by the appropriate Government in consultation with the Comptroller and Auditor-General of India.</p>

<p>(2) The accounts of the Authority shall be audited by the Comptroller and Auditor-General of India at such intervals as may be specified by him and any expenditure incurred in connection with such audit shall be payable by the Authority to the Comptroller and Auditor-General of India.</p>

<p>(3) The Comptroller and Auditor-General and any person appointed by him in connection with the audit of the accounts of the Authority under this Act shall have the same rights and privileges and authority in connection with such audit as the Comptroller and Auditor-General generally has in connection with the audit of Government accounts and, in particular shall have the right to demand and production of books, accounts, connected vouchers and other documents and papers, and to inspect any of the offices of the Authority.</p>

<p>(4) The accounts of the Authority, as certified by the Comptroller and Auditor-General of India or any other person appointed by him in this behalf, together with the audit report thereon shall be forwarded annually to the appropriate Government by the Authority and the appropriate Government shall cause the audit report to be laid, as soon as may be after it is received, before each House of Parliament or, as the case may be, before the State Legislature or the Union territory Legislature, where it consists of two Houses, or where such legislature consists of one House, before the House.</p>

<h2><b>Annual report.</b></h2><br>
<p>(1) The Authority shall prepare once in every year, in such form and at such time as
may be prescribed by the appropriate Government,—
(a) a description of all the activities of the Authority for the previous year;
(b) the annual accounts for the previous year; and
(c) the programmes of work for the coming year.
(2) A copy of the report received under sub-section (1) shall be laid, as soon as may be
after it is received, before each House of Parliament or, as the case may be, before the State
Legislature or the Union Territory Legislature, where it consists of two Houses, or where
such legislature consists of one House, before that House.</p><br>

