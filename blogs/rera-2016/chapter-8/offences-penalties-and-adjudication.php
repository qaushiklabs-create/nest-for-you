<h2><b>Punishment for no-registration under section 3</b></h2><br>
<p>59. (1) If any promoter contravenes the provisions of section 3, he shall be liable to a penalty which may extend up to ten per cent. of the estimated cost of the real estate project as determined by the Authority</p>
<p>(2) If any promoter does not comply with the orders, decisions or directions issued
under sub-section (1) or continues to violate the provisions of section 3, he shall be punishable with imprisonment for a term which may extend up to three years or with fine which may extend up to a further ten per cent. of the estimated cost of the real estate project, or with both.</p>
<h2><b>Penalty for contravention of section 4.</b></h2><br>

<p>60. If any promoter provides false information or contravenes the provisions of section 4, he shall be liable to a penalty which may extend up to five per cent. of the estimated cost of the real estate project, as determined by the Authorit</p>

<h2><b>Penalty for contravention of other provisions of this Act.</b></h2><br>

<p>61. If any promoter contravenes any other provisions of this Act, other than that provided under section 3 or section 4, or the rules or regulations made thereunder, he shall be liable to a penalty which may extend up to five per cent. of the estimated cost of the real estate project as determined by the Authority</p>

<h2><b>Penalty for non-registration and contravention under sections 9 and 10.</b></h2><br>

<p>62. If any real estate agent fails to comply with or contravenes the provisions of section 9 or section 10, he shall be liable to a penalty of ten thousand rupees for every day during which such default continues, which may cumulatively extend up to five per cent. of the cost of plot, apartment or buildings, as the case may be, of the real estate project, for which the sale or purchase has been facilitated as determined by the Authority.</p>

<h2><b>Penalty for failure to comply with orders of Authority by promoter.</b></h2><br>

<p>63. If any promoter, who fails to comply with, or contravenes any of the orders or directions of the Authority, he shall be liable to a penalty for every day during which such default continues, which may cumulatively extend up to five per cent., of the estimated cost of the real estate project as determined by the Authority.</p>

<h2><b>Penalty for failure to comply with orders of Appellate Tribunal by promoter</b></h2><br>

<p>64. If any promoter, who fails to comply with, or contravenes any of the orders, decisions or directions of the Applellate Trinbunal, he shall be punishable with imprisonment for a term which may extend up to three years or with fine for every day during which such default continues, which may cumulatively extend up to ten per cent. of the estimated cost of the real estate project, or with both</p>

<h2><b>Penalty for failure to comply with orders of Authority by real estate agent.</b></h2><br>

<p>65. If any real estate agent, who fails to comply with, or contravenes any of the orders or directions of the Authority, he shall be liable to a penalty for every day during which such default continues, which may cumulatively extend up to five per cent., of the estimated cost of plot, apartment or building, as the case may be, of the real estate project, for which the sale or purchase has been facilitated and as determined by the Authority.</p>

<h2><b>Penalty for failure to comply with orders of Appellate Tribunal by real estate agent</b></h2><br>
    <p>66. If any real estate agent, who fails to comply with, or contravenes any of the orders, decisions or directions of the Appellate Tribunal, he shall be punishable with imprisonment for a term which may extend up to one year or with fine for every day during which such default continues, which may cumulatively extend up to ten per cent. of the estimated cost of plot, apartment or building, as the case may be, of the real estate project, for which the sale or purchase has been facilitated, or with both</p>

<h2><b>Penalty for failure to comply with orders of Authority by allottee.</b></h2><br>
<p>67. If any allottee, who fails to comply with, or contravenes any of the orders, decisions or directions of the Authority he shall be liable to a penalty for the period during which such default continues, which may cumulatively extend up to five per cent. of the plot, apartment or building cost, as the case may be, as determined by the Authority.</p>

<h2><b>Penalty for failure to comply with orders of Appellate Tribunal by allottee.</b></h2><br>
<p>68. If any allottee, who fails to comply with, or contravenes any of the orders or directions of the Applellate Tribunal, as the case may be, he shall be punishable with imprisonment for a term which may extend up to one year or with fine for every day during which such default continues, which may cumulatively extend up to ten per cent. of the plot, apartment or building cost, as the case may be, or with both.</p>

<h2><b>Offences by companies.</b></h2><br>

<p><p>(1) Where an offence under this Act has been committed by a company, every
person who, at the time, the offence was committed was in charge of, or was responsible to the company for the conduct of, the business of the company, as well as the company, shall be deemed to be guilty of the offence and shall be liable to be proceeded against and punished accordingly:
Provided that nothing contained in this sub-section, shall render any such person liable to any punishment under this Act if he proves that the offence was committed without his knowledge or that he had exercised all due diligence to prevent the commission of such offence.</p>

<p>(2) Notwithstanding anything contained in sub-section (1), where an offence under this Act has been committed by a company, and it is proved that the offence has been committed with the consent or connivance of, or is attributable to, any neglect on the part of any director, manager, secretary or other officer of the company, such director, manager, secretary or other officer shall also be deemed to be guilty of that offence and shall be liable to be proceeded against and punished accordingly.</p>

<p><b></b>Explanation.—</b>For the purpose of this section,—
(a) ''company'' means any body corporate and includes a firm, or other association of individuals; and
(b) ''director'' in relation to a firm, means a partner in the firm.</p>
