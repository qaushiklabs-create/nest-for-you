<h2><b>Power to adjudicate.</b></h2><br>
<p>(1) For the purpose of adjudging compensation under sections 12, 14, 18 and
section 19, the Authority shall appoint in consultation with the appropriate Government one or more judicial officers as deemed necessary, who is or has been a District Judge to be an adjudicating officer for holding an inquiry in the prescribed manner, after giving any person concerned a reasonable opportunity of being heard:
Provided that any person whose complaint in respect of matters covered under sections
12, 14, 18 and section 19 is pending before the Consumer Disputes Redressal Forum or the Consumer Disputes Redressal Commission or the National Consumer Redressal Commission, established under section 9 of the Consumer Protection Act, 1986, on or before the commencement of this Act, he may, with the permission of such Forum or Commission, as the case may be, withdraw the complaint pending before it and file an application before the adjudicating officer under this Act.</p>

<p>(2) The application for adjudging compensation under sub-section (1), shall be dealt with by the adjudicating officer as expeditiously as possible and dispose of the same within a period of sixty days from the date of receipt of the application:
Provided that where any such application could not be disposed of within the said period of sixty days, the adjudicating officer shall record his reasons in writing for not disposing of the application within that period.</p>

<p>(3) While holding an inquiry the adjudicating officer shall have power to summon and enforce the attendance of any person acquainted with the facts and circumstances of the case to give evidence or to produce any document which in the opinion of the adjudicating officer, may be useful for or relevant to the subject matter of the inquiry and if, on such inquiry, he is satisfied that the person has failed to comply with the provisions of any of the sections specified in sub-section (1), he may direct to pay such compensation or interest, as the case may be, as he thinks fit in accordance with the provisions of any of those sections.</p><br>

