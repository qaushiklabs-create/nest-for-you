<h2><b>Establishment of Central Advisory Council.</b></h2><br>
<p>(1) The Central Government may, by notification, establish with effect from such
date as it may specify in such notification, a Council to be known as the Central Advisory
Council.</p>

<p>(2) The Minister to the Government of India in charge of the Ministry of the Central
Government dealing with Housing shall be the ex officio Chairperson of the Central Advisory
Council.</p>

<p>(3) The Central Advisory Council shall consist of representatives of the Ministry of
Finance, Ministry of Industry and Commerce, Ministry of Urban Development, Ministry of
Consumer Affairs, Ministry of Corporate Affairs, Ministry of Law and Justice, Niti Aayog,
National Housing Bank, Housing and Urban Development Corporation, five representatives
of State Governments to be selected by rotation, five representatives of the Real Estate
Regulatory Authorities to be selected by rotation, and any other Central Government
department as notified.</p>

<p>(4) The Central Advisory Council shall also consist of not more than ten members to
represent the interests of real estate industry, consumers, real estate agents, construction
labourers, non-governmental organisations and academic and research bodies in the real
estate sector.</p>

<h2><b>Functions of Central Advisory Council.</b></h2><br>
<p>(1) The functions of the Central Advisory Council shall be to advise and recommend
the Central Government,—
(a) on all matters concerning the implementation of this Act;
(b) on major questions of policy;
(c) towards protection of consumer interest;
(d) to foster the growth and development of the real estate sector;
(e) on any other matter as may be assigned to it by the Central Government.</p>

<p>(2) The Central Government may specify the rules to give effect to the recommendations
of the Central Advisory Council on matters as provided under sub-section (1).</p><br>

