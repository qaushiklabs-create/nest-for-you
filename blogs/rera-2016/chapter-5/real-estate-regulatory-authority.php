<h2><b>Establishment and incorporation of Real Estate Regulatory Authority.</b></h2><br>
<p>(1) The appropriate Government shall, within a period of one year from the date of coming into force of this Act, by notification, establish an Authority to be known as the Real Estate Regulatory Authority to exercise the powers conferred on it and to perform the functions assigned to it under this Act:</p>
<p>Provided that the appropriate Government of two or more States or Union territories may, if it deems fit, establish one single Authority:</p>
<p>Provided further that, the appropriate Government may, if it deems fit, establish more than one Authority in a State or Union territory, as the case may be:</p>
<p>Provided also that until the establishment of a Regulatory Authority under this section, the appropriate Government shall, by order, designate any Regulatory Authority or any officer preferably the Secretary of the department dealing with Housing, as the Regulatory Authority for the purposes under this Act:</p>
<p>Provided also that after the establishment of the Regulatory Authority, all applications, complaints or cases pending with the Regulatory Authority designated, shall stand transferred to the Regulatory Authority so established and shall be heard from the stage such applications, complaints or cases are transferred.</p>

<p>(2) The Authority shall be a body corporate by the name aforesaid having perpetual succession and a common seal, with the power, subject to the provisions of this Act, to acquire, hold and dispose of property, both movable and immovable, and to contract, and shall, by the said name, sue or be sued.</p>

<h2><b>Qualifications of Chairperson and Members of Authority</b></h2><br>
<p>The Chairperson and other Members of the Authority shall be appointed by the appropriate Government on the recommendations of a Selection Committee consisting of the Chief Justice of the High Court or his nominee, the Secretary of the Department dealing with Housing, and the Law Secretary, in such manner as may be prescribed, from amongst persons having adequate knowledge of and professional experience of at least twenty years in the case of the Chairperson and fifteen years in the case of the Members in urban development, housing, real estate development, infrastructure, economics, technical experts from relevant fields, planning, law, commerce, accountancy, industry, management, social service, public affairs, or administration:</p>
<p>Provided that a person who is, or has been, in the service of the State Government shall not be appointed as a Chairperson unless such person has held the post of Additional Secretary to the Central Government or any equivalent post in the Central Government or State Government:</p>
<p>Provided further that a person who is, or has been, in the service of the State Government shall not be appointed as a member unless such person has held the post of Secretary to the State Government or any equivalent post in the State Government or Central Government.</p>

<h2><b>Term of office of Chairperson and Members.</b></h2><br>
<p>(1) The Chairperson and Members shall hold office for a term not exceeding five years from the date on which they enter upon their office, or until they attain the age of sixty-five years, whichever is earlier and shall not be eligible for re-appointment.</p>

<p>(2) Before appointing any person as a Chairperson or Member, the appropriate Government shall satisfy itself that the person does not have any such financial or other interest as is likely to affect prejudicially his functions as such Member.</p>

<h2><b>Salary and allowances payable to Chairperson and Members.</b></h2><br>
<p>(1) The salary and allowances payable to, and the other terms and conditions of service of, the Chairperson and other Members shall be such as may be prescribed and shall not be varied to their disadvantage during their tenure.</p>

<p>(2) Notwithstanding anything contained in sub-sections (1) and (2) of section 23, the Chairperson or a Member, as the case may be, may,—</p>
<p>(a) relinquish his office by giving in writing, to the appropriate Government, notice of not less than three months; or</p>
<p>(b) be removed from his office in accordance with the provisions of section 26 of this Act.</p>

<p>(3) Any vacancy caused to the office of the Chairperson or any other Member shall be filled-up within a period of three months from the date on which such vacancy occurs.</p>

<h2><b>Removal of Chairperson and Members from office in certain circumstances.</b></h2><br>
<p>(1) The appropriate Government may, in accordance with the procedure notified, remove from office the Chairperson or other Members, if the Chairperson or such other Member, as the case may be,—</p>
<p>(a) has been adjudged as an insolvent; or</p>
<p>(b) has been convicted of an offence, involving moral turpitude; or</p>
<p>(c) has become physically or mentally incapable of acting as a Member; or</p>
<p>(d) has acquired such financial or other interest as is likely to affect prejudicially his functions; or</p>
<p>(e) has so abused his position as to render his continuance in office prejudicial to the public interest.</p>

<p>(2) The Chairperson or Member shall not be removed from his office on the ground specified under clause (d) or clause (e) of sub-section (1) except by an order made by the appropriate Government after an inquiry made by a Judge of the High Court in which such Chairperson or Member has been informed of the charges against him and given a reasonable opportunity of being heard in respect of those charges.</p>

<h2><b>Restrictions on Chairperson or Members on employment after cessation of office</b></h2><br>
<p>(1) The Chairperson or a Member, ceasing to hold office as such, shall not—</p>
<p>(a) accept any employment in, or connected with, the management or administration of, any person or organisation which has been associated with any work under this Act, from the date on which he ceases to hold office:</p>
<p>Provided that nothing contained in this clause shall apply to any employment under the appropriate Government or a local authority or in any statutory authority or any corporation established by or under any Central, State or provincial Act or a Government Company, as defined under clause (45) of section 2 of the Companies Act, 2013, which is not a promoter as per the provisions of this Act;</p>
<p>(b) act, for or on behalf of any person or organisation in connection with any specific proceeding or transaction or negotiation or a case to which the Authority is a party and with respect to which the Chairperson or such Member had, before cessation of office, acted for or provided advice to, the Authority;</p>
<p>(c) give advice to any person using information which was obtained in his capacity as the Chairperson or a Member and being unavailable to or not being able to be made available to the public;</p>
<p>(d) enter into a contract of service with, or accept an appointment to a board of directors of, or accept an offer of employment with, an entity with which he had direct and significant official dealings during his term of office as such.</p>

<p>(2) The Chairperson and Members shall not communicate or reveal to any person any matter which has been brought under his consideration or known to him while acting as such</p>

<h2><b>Meetings of Authority.</b></h2><br>
<p>(1) The Authority shall meet at such places and times, and shall follow such rules of procedure in regard to the transaction of business at its meetings, (including quorum at such meetings), as may be specified by the regulations made by the Authority.</p>

<p>(2) If the Chairperson for any reason, is unable to attend a meeting of the Authority, any other Member chosen by the Members present amongst themselves at the meeting, shall preside at the meeting.</p>

<p>(3) All questions which come up before any meeting of the Authority shall be decided by a majority of votes by the Members present and voting, and in the event of an equality of votes, the Chairperson or in his absence, the person presiding shall have a second or casting vote.</p>

<p>(4) The questions which come up before the Authority shall be dealt with as expeditiously as possible and the Authority shall dispose of the same within a period of sixty days from the date of receipt of the application:</p>
<p>Provided that where any such application could not be disposed of within the said period of sixty days, the Authority shall record its reasons in writing for not disposing of the application within that period.</p>

<h2><b>Vacancies, etc., not to invalidate proceeding of Authority.</b></h2><br>
<p>No act or proceeding of the Authority shall be invalid merely by reason of—</p>
<p>(a) any vacancy in, or any defect in the constitution of, the Authority; or</p>
<p>(b) any defect in the appointment of a person acting as a Member of the Authority; or</p>
<p>(c) any irregularity in the procedure of the Authority not affecting the merits of the case</p>


<h2><b>Filing of complaints with the Authority or the adjudicating officer.</b></h2><br>
<p>(1) Any aggrieved person may file a complaint with the Authority or the adjudicating officer, as the case may be, for any violation or contravention of the provisions of this Act or the rules and regulations made thereunder against any promoter, allottee, or real estate agent, as the case may be.</p>
<p><b>Explanation.—</b>For the purpose of this sub-section "person" shall include the association of allottees or any voluntary consumer association registered under any law for the time being in force.</p>


<h2><b>Functions of Authority for promotion of real estate sector</b></h2><br>
<p>The Authority shall in order to facilitate the growth and promotion of a healthy, transparent, efficient and competitive real estate sector make recommendations to the appropriate Government or the competent authority, as the case may be, on,—</p>
<p>(a) protection of interest of the allottees, promoter and real estate agent;</p>
<p>(b) creation of a single window system for ensuring time bound project approvals and clearances for timely completion of the project;</p>
<p>(c) creation of a transparent and robust grievance redressal mechanism against acts of omission and commission of competent authorities and their officials;</p>
<p>(d) measures to encourage investment in the real estate sector including measures to increase financial assistance to affordable housing segment;</p>
<p>(e) measures to encourage construction of environmentally sustainable and affordable housing, promoting standardisation and use of appropriate construction materials, fixtures, fittings and construction techniques;</p>
<p>(f) measures to encourage grading of projects on various parameters of development including grading of promoters;</p>
<p>(g) measures to facilitate amicable conciliation of disputes between the promoters and the allottees through dispute settlement forums set up by the consumer or promoter associations;</p>
<p>(h) measures to facilitate digitization of land records and system towards conclusive property titles with title guarantee;</p>
<p>(i) to render advice to the appropriate Government in matters relating to the development of real estate sector;</p>
<p>(j) any other issue that the Authority may think necessary for the promotion of the real estate sector</p>

<h2><b>Advocacy and awareness measures.</b></h2><br>

<p>(1) The appropriate Government may, while formulating a policy on the real estate sector (including review of laws related to the real estate sector) or any other matter, make a reference to the Authority for its opinion on the possible effect of such policy or law on the real estate sector. On receipt of such a reference, the Authority shall, within a period of sixty days, give its opinion to the appropriate Government, which may thereafter take further action as it deems fit.</p>

<p>(2) The opinion given by the Authority under sub-section (1) shall not be binding upon the appropriate Government in formulating such policy or laws.</p>

<p>(3) The Authority shall take suitable measures for the promotion of advocacy, creating awareness, and imparting training about laws relating to the real estate sector and policies.</p>

<h2><b>Functions of Authority.</b></h2><br>
<p>The functions of the Authority shall include—</p>
<ul>
  <li><b>(a)</b> to register and regulate real estate projects and real estate agents registered under this Act;</li>
  <li><b>(b)</b> to publish and maintain a website of records, for public viewing, of all real estate projects for which registration has been given, with such details as may be prescribed, including information provided in the application for which registration has been granted;</li>
  <li><b>(c)</b> to maintain a database, on its website, for public viewing, and enter the names and photographs of promoters as defaulters including the project details, registration for which has been revoked or have been penalised under this Act, with reasons therefor, for access to the general public;</li>
  <li><b>(d)</b> to maintain a database, on its website, for public viewing, and enter the names and photographs of real estate agents who have applied and registered under this Act, with such details as may be prescribed, including those whose registration has been rejected or revoked;</li>
  <li><b>(e)</b> to fix through regulations for each area under its jurisdiction the standard fees to be levied on the allottees or the promoter or the real estate agent, as the case may be;</li>
  <li><b>(f)</b> to ensure compliance of the obligations cast upon the promoters, the allottees and the real estate agents under this Act and the rules and regulations made thereunder;</li>
  <li><b>(g)</b> to ensure compliance of its regulations or orders or directions made in exercise of its powers under this Act;</li>
  <li><b>(h)</b> to perform such other functions as may be entrusted to the Authority by the appropriate Government as may be necessary to carry out the provisions of this Act.</li>
</ul>

<h2><b>Powers of Authority to call for information, conduct investigations.</b></h2><br>
<p>(1) Where the Authority considers it expedient to do so, on a complaint or suo motu,
relating to this Act or the rules or regulations made thereunder, it may, by order in writing
and recording reasons therefor, call upon any promoter or allottee or real estate agent, as the
case may be, at any time to furnish in writing such information or explanation relating to its
affairs as the Authority may require and appoint one or more persons to make an inquiry
in relation to the affairs of any promoter or allottee or the real estate agent, as the case
may be.</p>
<p>(2) Notwithstanding anything contained in any other law for the time being in force,
while exercising the powers under sub-section (1), the Authority shall have the same powers
as are vested in a civil court under the Code of Civil Procedure, 1908 while trying a suit, in
respect of the following matters, namely:—</p>
<ul>
  <li><b>(i)</b> the discovery and production of books of account and other documents, at
  such place and at such time as may be specified by the Authority;</li>
  <li><b>(ii)</b> summoning and enforcing the attendance of persons and examining them on
  oath;</li>
  <li><b>(iii)</b> issuing commissions for the examination of witnesses or documents;</li>
  <li><b>(iv)</b> any other matter which may be prescribed.</li>
</ul>

<h2><b>Powers of Authority to issue directions. </b></h2><br>
<p>The Authority may, for the purpose of discharging its functions under the provisions
of this Act or rules or regulations made thereunder, issue such directions from time to time, to
the promoters or allottees or real estate agents, as the case may be, as it may consider
necessary and such directions shall be binding on all concerned.</p>

<h2><b>Powers of Authority.</b></h2><br>
<p>(1) The Authority shall have powers to impose penalty or interest, in regard to any
contravention of obligations cast upon the promoters, the allottees and the real estate agents,
under this Act or the rules and the regulations made thereunder.</p>

<p>(2) The Authority shall be guided by the principles of natural justice and, subject to the
other provisions of this Act and the rules made thereunder, the Authority shall have powers
to regulate its own procedure.</p>

<p>(3) Where an issue is raised relating to agreement, action, omission, practice or
procedure that—
(a) has an appreciable prevention, restriction or distortion of competition in
connection with the development of a real estate project; or
(b) has the effect of market power of monopoly situation being abused for affecting
interest of allottees adversely,
then the Authority may suo motu make reference in respect of such issue to the Competition
Commission of India.</p>

<h2><b>Recovery of interest or penalty or compensation and enforcement of order, etc.</b></h2><br>
<p>(1) If a promoter or an allottee or a real estate agent, as the case may be, fails to pay
any interest or penalty or compensation imposed on him, by the adjudicating officer or the
Regulatory Authority or the Appellate Authority, as the case may be, under this Act or the
rules and regulations made thereunder, it shall be recoverable from such promoter or allottee
or real estate agent, in such manner as may be prescribed as an arrears of land revenue.</p>

<p>(2) If any adjudicating officer or the Regulatory Authority or the Appellate Tribunal, as
the case may be, issues any order or directs any person to do any act, or refrain from doing
any act, which it is empowered to do under this Act or the rules or regulations made thereunder,
then in case of failure by any person to comply with such order or direction, the same shall be
enforced, in such manner as may be prescribed.</p><br>

