<h2><b>Rights and duties of allottees. </b></h2><br>
<p>19 (1) The allottee shall be entitled to obtain the information relating to sanctioned plans, layout plans along with the specifications, approved by the competent authority and such other information as provided in this Act or the rules and regulations made thereunder or the agreement for sale signed with the promoter.</p>

<p>(2) The allottee shall be entitled to know the stage-wise time schedule of completion of the project, including the provisions for water, sanitation, electricity, and other amenities and services as agreed to between the promoter and the allottee in accordance with the terms and conditions of the agreement for sale.</p>

<p>(3) The allottee shall be entitled to claim the possession of the apartment, plot, or building, as the case may be, and the association of allottees shall be entitled to claim the possession of the common areas, as per the declaration given by the promoter under sub-clause (C) of clause (I) of sub-section (2) of section 4.</p>

<p>(4) The allottee shall be entitled to claim the refund of amount paid along with interest at such rate as may be prescribed and compensation in the manner as provided under this Act, from the promoter, if the promoter fails to comply or is unable to give possession of the apartment, plot, or building, as the case may be, in accordance with the terms of agreement for sale or due to discontinuance of his business as a developer on account of suspension or revocation of his registration under the provisions of this Act or the rules or regulations made thereunder.</p>

<p>(5) The allottee shall be entitled to have the necessary documents and plans, including that of common areas, after handing over the physical possession of the apartment or plot or building as the case may be, by the promoter.</p>

<p>(6) Every allottee, who has entered into an agreement for sale to take an apartment, plot, or building as the case may be, under section 13, shall be responsible to make necessary payments in the manner and within the time as specified in the said agreement for sale and shall pay at the proper time and place, the share of the registration charges, municipal taxes, water and electricity charges, maintenance charges, ground rent, and other charges, if any.</p>

<p>(7) The allottee shall be liable to pay interest, at such rate as may be prescribed, for any delay in payment towards any amount or charges to be paid under sub-section (6).</p>

<p>(8) The obligations of the allottee under sub-section (6) and the liability towards interest under sub-section (7) may be reduced when mutually agreed to between the promoter and such allottee.</p>

<p>(9) Every allottee of the apartment, plot, or building as the case may be, shall participate towards the formation of an association or society or cooperative society of the allottees, or a federation of the same.</p>

<p>(10) Every allottee shall take physical possession of the apartment, plot, or building as the case may be, within a period of two months of the occupancy certificate issued for the said apartment, plot, or building, as the case may be.</p>

<p>(11) Every allottee shall participate towards the registration of the conveyance deed of the apartment, plot, or building, as the case may be, as provided under sub-section (1) of section 17 of this Act.</p><br>

