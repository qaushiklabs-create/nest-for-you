<h2><b>Prior Registration of Real Estate Project with Real Estate Regulatory Authority</b></h2><br>
<p>3. (1) No promoter shall advertise, market, book, sell or offer for sale, or invite persons to purchase in any manner any plot, apartment or building, as the case may be, in any real estate project or part of it, in any planning area, without registering the real estate project with the Real Estate Regulatory Authority established under this Act:</p><br>

<p>Provided that projects that are ongoing on the date of commencement of this Act and for which the completion certificate has not been issued, the promoter shall make an application to the Authority for registration of the said project within a period of three months from the date of commencement of this Act:</p><br>

<p>Provided further that if the Authority thinks necessary, in the interest of allottees, for projects which are developed beyond the planning area but with the requisite permission of the local authority, it may, by order, direct the promoter of such project to register with the Authority, and the provisions of this Act or the rules and regulations made thereunder, shall
apply to such projects from that stage of registration.</p><br>

<p>(2) Notwithstanding anything contained in sub-section (1), no registration of the real estate project shall be required—<br><br>
(a) where the area of land proposed to be developed does not exceed five hundred
square meters or the number of apartments proposed to be developed does not exceed eight inclusive of all phases:<br><br>
Provided that, if the appropriate Government considers it necessary, it may,
reduce the threshold below five hundred square meters or eight apartments, as the case may be, inclusive of all phases, for exemption from registration under this Act;<br><br>
(b) where the promoter has received completion certificate for a real estate project prior to commencement of this Act;<br><br>
(c) for the purpose of renovation or repair or re-development which does not
involve marketing, advertising selling or new allotment of any apartment, plot or building, as the case may be, under the real estate project.<br><br>
<b>Explanation.</b>—For the purpose of this section, where the real estate project is to be developed in phases, every such phase shall be considered a stand alone real estate project, and the promoter shall obtain registration under this Act for each phase separately</p>

<h2><b>Application for registration of real estate projects.
</b></h2><br>
<p>4. (1) Every promoter shall make an application to the Authority for registration of the real estate project in such form, manner, within such time and accompanied by such fee as may be specified by the regulations made by the Authority.<br><br>
(2) The promoter shall enclose the following documents along with the application referred to in sub-section (1), namely:—<br><br>
(a) a brief details of his enterprise including its name, registered address, type of enterprise (proprietorship, societies, partnership, companies, competent authority), and the particulars of registration, and the names and photographs of the promoter;<br><br>
(b) a brief detail of the projects launched by him, in the past five years, whether already completed or being developed, as the case may be, including the current status of the said projects, any delay in its completion, details of cases pending, details of type of land and payments pending;<br><br>
(c) an authenticated copy of the approvals and commencement certificate from
the competent authority obtained in accordance with the laws as may be applicable for the real estate project mentioned in the application, and where the project is proposed to be developed in phases, an authenticated copy of the approvals and commencement certificate from the competent authority for each of such phases;<br><br>
(d) the sanctioned plan, layout plan and specifications of the proposed project
or the phase thereof, and the whole project as sanctioned by the competent authority;<br><br>
(e) the plan of development works to be executed in the proposed project and
the proposed facilities to be provided thereof including fire fighting facilities, drinking water facilities, emergency evacuation services, use of renewable energy;<br><br>
(f) the location details of the project, with clear demarcation of land dedicated for the project along with its boundaries including the latitude and longitude of the end points of the project;<br><br>
(g) proforma of the allotment letter, agreement for sale, and the conveyance deed proposed to be signed with the allottees;<br><br>
(h) the number, type and the carpet area of apartments for sale in the project
along with the area of the exclusive balcony or verandah areas and the exclusive open terrace areas apartment with the apartment, if any;<br><br>
(i) the number and areas of garage for sale in the project;<br><br>
(j) the names and addresses of his real estate agents, if any, for the proposed
project;<br><br>
(k) the names and addresses of the contractors, architect, structural engineer, if any and other persons concerned with the development of the proposed project;<br><br>
(l) a declaration, supported by an affidavit, which shall be signed by the promoter or any person authorised by the promoter, stating:—<br><br>
(A) that he has a legal title to the land on which the development is proposed
along with legally valid documents with authentication of such title, if such land is owned by another person;<br><br>
(B) that the land is free from all encumbrances, or as the case may be
details of the encumbrances on such land including any rights, title, interest or name of any party in or over such land along with details;<br><br>
(C) the time period within which he undertakes to complete the project or
phase thereof, as the case may be;<br><br>
(D) that seventy per cent. of the amounts realised for the real estate project
from the allottees, from time to time, shall be deposited in a separate account to be maintained in a scheduled bank to cover the cost of construction and the land cost and shall be used only for that purpose:<br><br>

Provided that the promoter shall withdraw the amounts from the separate
account, to cover the cost of the project, in proportion to the percentage of
completion of the project:<br><br>
Provided further that the amounts from the separate account shall be
withdrawn by the promoter after it is certified by an engineer, an architect and a chartered accountant in practice that the withdrawal is in proportion to the percentage of completion of the project:<br><br>
Provided also that the promoter shall get his accounts audited within six
months after the end of every financial year by a chartered accountant in practice, and shall produce a statement of accounts duly certified and signed by such chartered accountant and it shall be verified during the audit that the amounts collected for a particular project have been utilised for the project and the withdrawal has been in compliance with the proportion to the percentage of completion of the project.<br><br>

<b>Explanation.—</b> For the purpose of this clause, the term "schedule bank"
means a bank included in the Second Schduled to the Reserve Bank of India
Act, 1934<br><br>
(E) that he shall take all the pending approvals on time, from the competent
authorities;<br><br>
(F) that he has furnished such other documents as may be prescribed by
the rules or regulations made under this Act; and (m) such other information and documents as may be prescribed.<br><br>
(3) The Authority shall operationalise a web based online system for submitting
applications for registration of projects within a period of one year from the date of its establishment
</p>

<h2><b>Grant of registration.</b></h2><br>
<p>5. (1) On recipt of the application under sub-section (1) of section 4, the Authority shall within a period of thirty days.<br><br>
(a) grant registration subject to the provisions of this Act and the rules and
regulations made thereunder, and provide a registration number, including a Login Id and password to the applicant for accessing the website of the Authority and to create his web page and to fill therein the details of the proposed project; or<br><br>
(b) reject the application for reasons to be recorded in writing,if such application does not conform to the provisions of this Act or the rules or regulations made thereunder:<br><br>
Provided that no application shall be rejected unless the applicant has been given an opportunity of being heard in the matter.<br><br>
(2) If the Authority fails to grant the registration or reject the application, as the case may be, as provided under sub-section (1), the project shall be deemed to have been registered, and the Authority shall within a period of seven days of the expiry of the said period of thirty days specified under sub-section (1), provide a registration number and a Login Id and
password to the promoter for accessing the website of the Authority and to create his web page and to fill therein the details of the proposed project.<br><br>
(3) The registration granted under this section shall be valid for a period declared by the promoter under sub-clause (C) of clause (1) of sub-section (2) of section 4 for completion of the project or phase thereof, as the case may be.</p>

<h2><b>Extension of registration.</b></h2><br>
<p>6. The registration granted under section 5 may be extended by the Authority on an application made by the promoter due to force majeure, in such form and on payment of such fee as may be specified by regulations made by the Authority:<br>
Provided that the Authority may in reasonable circumstances, without default on the part of the promoter, based on the facts of each case, and for reasons to be recorded in writing, extend the registration granted to a project for such time as it considers necessary, which shall, in aggregate, not exceed a period of one year:<br>
Provided further that no application for extension of registration shall be rejected unless the applicant has been given an opportunity of being heard in the matter.<br><br>
<b>Explanation.—</b> For the purpose of this section, the expression "force majeure" shall mean a case of war, flood, drought, fire, cyclone, earthquake or any other calamity caused by nature affecting the regular development of the real estate project</p>
<p>7. (1) The Authority may, on receipt of a complaint or suo motu in this behalf or on the recommendation of the competent authority, revoke the registration granted under section 5, after being satisfied that—<br><br>
(a) the promoter makes default in doing anything required by or under this Act or the rules or the regulations made thereunder;<br><br>
(b) the promoter violates any of the terms or conditions of the approval given by the competent authority;<br><br>
(c) the promoter is involved in any kind of unfair practice or irregularities.
Explanation.—For the purposes of this clause, the term "unfair practice means" a
practice which, for the purpose of promoting the sale or development of any real estate project adopts any unfair method or unfair or deceptive practice including any of the following practices, namely:—<br><br>
(A) the practice of making any statement, whether in writing or by visible
representation which,—<br><br>
(i) falsely represents that the services are of a particular standard or grade;<br>
(ii) represents that the promoter has approval or affiliation which such
promoter does not have;<br>
(iii) makes a false or misleading representation concerning the services;<br><br>
(B) the promoter permits the publication of any advertisement or prospectus
whether in any newspaper or otherwise of services that are not intended to be offered;<br><br>
(c) the promoter indulges in any fraudulent practices.<br><br>
(2) The registration granted to the promoter under section 5 shall not be revoked unless the Authority has given to the promoter not less than thirty days notice, in writing, stating the grounds on which it is proposed to revoke the registraton, and has considered any cause shown by the promoter within the period of that notice against the proposed revocation.<br><br>
(3) The Authority may, instead of revoking the registration under sub-section (1), permit it to remain in force subject to such further terms and conditions as it thinks fit to impose in the interest of the allottees, and any such terms and conditions so imposed shall be binding upon the promoter.<br><br>
(4) The Authority, upon the revocation of the registration,—<br><br>
(a) shall debar the promoter from accessing its website in relation to that project and specify his name in the list of defaulters and display his photograph on its website and also inform the other Real Estate Regulatory Authority in other States and Union territories about such revocation or registration;<br>
(b) shall facilitate the remaining development works to be carried out in accordance with the provisions of section 8;<br>
(c) shall direct the bank holding the project back account, specified under sub-clause (D) of clause (I) of sub-section (2) of section 4, to freeze the account, and thereafter take such further necessary actions, including consequent de-freezing of the said account, towards facilitating the remaining development works in accordance with the provisions of section 8;<br>
(d) may, to protect the interest of allottees or in the public interest, issue such directions as it may deem necessary.</p>

<h2><b>Obligation of Authority consequent upon lapse of or on revocation of registration</b></h2><br>
<p>8. Upon lapse of the registration or on revocation of the registration under this Act, the Authority, may consult the appropriate Government to take such action as it may deem fit including the carrying out of the remaining development works by competent authority or by the association of allottees or in any other manner, as may be determined by the Authority:<br><br>
Provided that no direction, decision or order of the Authority under this section shall take effect until the expiry of the period of appeal provided under the provisions of this Act:<br><br>
Provided further that in case of revocation of registration of a project under this Act, the association of allottees shall have the first right of refusal for carrying out of the remaining development works.</p>

<h2><b>Registration of real estate agents</b></h2><br>
<p>9. (1) No real estate agent shall facilitate the sale or purchase of or act on behalf of any person to facilitate the sale or purchase of any plot, apartment or building, as the case may be, in a real estate project or part of it, being the part of the real estate project registered under section 3, being sold by the promoter in any planning area, without obtaining registration under this section.<br><br>
(2) Every real estate agent shall make an application to the Authority for registration in such form, manner, within such time and accompanied by such fee and documents as may be prescribed.<br><br>
(3) The Authority shall, within such period, in such manner and upon satisfying itself of the fulfillment of such conditions, as may be prescribed—<br><br>
(a) grant a single registration to the real estate agent for the entire State of Union territory, as the case may be;<br>
(b) reject the application for reasons to be recorded in writing, if such application does not conform to the provisions of the Act or the rules or regulations made thereunder:<br>
Provided that no application shall be rejected unless the applicant has been given an opportunity of being heard in the matter.<br><br>
(4) Whereon the completion of the period specified under sub-section (3), if the
applicant does not receive any communication about the deficiencies in his application or the rejection of his application, he shall be deemed to have been registered.<br><br>
(5) Every real estate agent who is registered as per the provisions of this Act or the rules and regulations made thereunder, shall be granted a registration number by the Authority, which shall be quoted by the real estate agent in every sale facilitated by him under this Act.<br><br>
(6) Every registration shall be valid for such period as may be prescribed, and shall be renewable for a period in such manner and on payment of such fee as may be prescribed.<br><br>
(7) Where any real estate agent who has been granted registration under this Act
commits breach of any of the conditions thereof or any other terms and conditions specified under this Act or any rules or regulations made thereunder, or where the Authority is satisified that such registration has been secured by the real estate agent through misrepresentation or fraud, the Authority may, without prejudice to any other provisions under this Act, revoke the registration or suspend the same for such period as it thinks fit:<br>
Provided that no such revocation or suspension shall be made by the Authority unless an opportunity of being heard has been given to the real estate agent</p>
<h2><b>Functions of real estate agents</b></h2><br>
<p>Every real estate agent registered under section 9 shall—<br><br>
(a) not facilitate the sale or purchase of any plot, apartment or building, as the case may be, in a real estate project or part of it, being sold by the promoter in any planning area, which is not registered with the Authority;<br><br>
(b) maintain and preserve such books of account, records and documents as
may prescribed;<br><br>
(c) not involve himself in any unfair trade practices, namely:—<br><br>
(i) the practice of making any statement, whether orally or in writing or by
visible representation which—<br><br>
(A) falsely represents that the services are of a particular standard or
grade;<br>
(B) represents that the promoter or himself has approval or affiliation
which such promoter or himself does not have;<br>
(C) makes a false or misleading representation concerning the
services;<br>
(ii) permitting the publication of any advertisement whether in any
newspaper or otherwise of services that are not intended to be offered.<br><br>
(d) facilitate the possession of all the information and documents, as the allottee, is entitled to, at the time of booking of any plot, apartment or building, as the case may be;<br><br>
(e) discharge such other functions as may be prescribed.
</p><br>

