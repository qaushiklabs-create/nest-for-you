<li>(c) the period, manner and conditions under which the registration is to be granted under sub-section (3) of section 9;</li>
<li>(d) the validity of the period of registration and the manner and fee for renewal under sub-section (6) of section 9;</li>
<li>(e) the maintenance and preservation of books of account, records and documents under clause (b) of section 10;</li>
