<h2><b>Power to make regulations.</b></h2><br>
<p>(1) The Authority shall, within a period of three months of its establishment, by notification, make regulations, consistent with this Act and the rules made thereunder to carry out the purposes of this Act.</p>

<p>(2) In particular, and without prejudice to the generality of the foregoing power, such regulations may provide for all or any of the following matters, namely:—</p>
<ul>
<li>(a) the form and manner of making application and fee payable herewith under sub-section (1) of section 4;</li>
<li>(b) the form of application and the fees for extension of registration under section 6;</li>
<li>(c) such other information and documents required under clause (f) of sub-section (1) of section 11;</li>
<li>(d) display of sanctioned plans, layout plans along with specifications, approved by the competent authority, for display under clause (a) of sub-section (3) of section 11;</li>
<li>(e) preparation and maintenance of other details under sub-section (6) of section 11;</li>
<li>(f) time, places and the procedure in regard to transaction of business at the meetings of the Authority under sub-section (1) of section 29;</li>
<li>(g) the form, manner and fees for filing a complaint under sub-section (2) of section 31;</li>
<li>(h) standard fees to be levied on the promoter, the allottees or the real estate agent under clause (e) of section 34;</li>
<li>(i) any other matter which is required to be, or may be, specified by regulation or in respect of which provision is to be made by regulations.</li>
</ul>

<h2><b>Laying of rules.</b></h2><br>
<p>(1) Every rule made by the Central Government, every regulation made by the Authority under the Union territory of Delhi and the Union territories without Legislature and every notification issued by the Central Government under this Act shall be laid, as soon as may be after it is made, before each House of Parliament, while it is in session, for a total period of thirty days which may be comprised in one session or in two or more successive sessions, and if, before the expiry of the session immediately following the session or the successive sessions aforesaid, both Houses agree in making any modification in the rule or regulation or in the notification, as the case may be, or both Houses agree that the rule or regulation or the notification should not be made, the rule or regulation or notification, as the case may be, shall thereafter have effect only in such modified form or be of no effect, as the case may be; so, however, that any such modification or annulment shall be without prejudice to the validity of anything previously done under that rule or regulation or notification, as the case may be.</p>

<p>(2) Every rule made by a State Government or the Union territory Government, as the case may be, every regulation made by the Authority under the State Government or the Union territory Government of Puducherry, as the case may be, and every notification issued by the State Government or the Union territory Government of Puducherry, as the case may be, under this Act, shall be laid as soon as may be, after it is made, before the State Legislature, or the Union territory Legislature, as the case may be, where it consists of two Houses, or where such legislature consists of one House, before that House.</p>

<h2><b>Members etc., to be public servants</b></h2><br>
<p>87. The Chairperson, Members and other officers and employees of the Authority, and the Appellate Tribunal and the adjudicating officer shall be deemed to be public servants within the meaning of section 21 of the Indian Penal Code</p>

<h2><b>Application of other laws not barred.</b></h2><br>
<p>88. The provisions of this Act shall be in addition to, and not in derogation of, the provisions of any other law for the time being in force.</p>

<h2><b>Act to have overriding effect.</b></h2><br>
<p>89. The provisions of this Act shall have effect, notwithstanding anything inconsistent therewith contained in any other law for the time being in forc</p>

<h2><b>Protection of action taken in good faith.</b></h2><br>
<p>90. No suit, prosecution or other legal proceedings shall lie against the appropriate Government or the Authority or any officer of the appropriate Government or any member, officer or other employees of the Authority for anything which is in good faith done or intended to be done under this Act or the rules or regulations made thereunder.</p>

<h2><b>Power to remove difficulties</b></h2><br>
<p>91. (1) If any difficulty arises in giving effect to the provisions of this Act, the Central Government may, by order, published in the Official Gazette, make such provisions not inconsistent with the provisions of this Act as may appear to be necessary for removing the difficulty:</p>
<p>Provided that no order shall be made under this section after the expiry of two years from the date of the commencement of this Act</p>
<p>(2) Every order made under this section shall be laid, as soon as may be after it is made, before each House of Parliament.</p>

