<h2><b>Bar of jurisdiction.</b></h2><br>
<p>79. No civil court shall have jurisdiction to entertain any suit or proceeding in respect of any matter which the Authority or the adjudicating officer or the Appellate Tribunal is empowered by or under this Act to determine and no injunction shall be granted by any court or other authority in respect of any action taken or to be taken in pursuance of any power
conferred by or under this Act.</p>

<h2><b>Cognizance of offences.</b></h2><br>
<p>80. (1) No court shall take cognizance of any offence punishable under this Act or the rules or regulations made thereunder save on a complaint in writing made by the Authority or by any officer of the Authority duly authorised by it for this purpose</p>
<p>(2) No court inferior to that of a Metropolitan Magistrate or a Judicial Magistrate of the first class shall try any offence punishable under this Act</p>
<h2><b>Delegation.</b></h2><br>
<p>81. The Authority may, by general or special order in writing, delegate to any member, officer of the Authority or any other person subject to such conditions, if any, as may be specified in the order, such of its powers and functions under this Act (except the power to make regulations under section 85, as it may deem necessary</p>
<h2><b>Power of appropriate Government to supersede Authority</b></h2><br>
<p>(1) If, at any time, the appropriate Government is of the opinion,—<br>
(a) that, on account of circumstances beyond the control of the Authority, it is
unable to discharge the functions or perform the duties imposed on it by or under the provisions of this Act; or<br>
(b) that the Authority has persistently defaulted in complying with any direction given by the appropriate Government under this Act or in the discharge of the functions or performance of the duties imposed on it by or under the provisions of this Act and as a result of such default the financial position of the Authority or the administration
of the Authority has suffered; or<br>
(c) that circumstances exist which render it necessary in the public interest so to do, the appropriate Government may, by notification, supersede the Authority for such period, not exceeding six months, as may be specified in the notification and appoint a person or persons as the President or the Governor, as the case may be, may direct to exercise powers
and discharge functions under this Act:<br>
Provided that before issuing any such notification, the appropriate Government shall give a reasonable opportunity to the Authority to make representations against the proposed supersession and shall consider the representations, if any, of the Authority.<br>
(2) Upon the publication of a notification under sub-section (1) superseding the
Authority,—<br>
(a) the Chairperson and other Members shall, as from the date of supersession,
vacate their offices as such;<br>
(b) all the powers, functions and duties which may, by or under the provisions
of this Act, be exercised or discharged by or on behalf of the Authority shall, until the Authority is reconstituted under sub-section (3), be exercised and discharged by the person or persons referred to in sub-section (1); and<br>
(c) all properties owned or controlled by the Authority shall, until the Authority is reconstituted under sub-section (3), vest in the appropriate Government.<br>
(3) On or before the expiration of the period of supersession specified in the notification issued under sub-section (1), the appropriate Government shall reconstitute the Authority by a fresh appointment of its Chairperson and other members and in such case any person who had vacated his office under clause (a) of sub-section (2) shall not be deemed to be disqualified for re-appointment.<br>
(4) The appropriate Government shall cause a copy of the notification issued under sub-section (1) and a full report of any action taken under this section and the circumstances leading to such action to be laid before each House of Parliament or, as the case may be, before the State Legislature, or the Union Territory Legislature, as the case may be, where it consists of two Houses, or where such legislature consists of one House, before that House.</p>

<h2><b>Powers of appropriate Government to issue directions to Authority and obtain reports and returns.</b></h2><br>
<p>(1) Without prejudice to the foregoing provisions of this Act, the Authority shall, in exercise of its powers and in performance of its functions under this Act, be bound by such directions on questions of policy, as the appropriate Government may give in writing to it from time to time:
Provided that the Authority shall, as far as practicable, be given an opportunity to express its views before any direction is given under this sub-section.
(2) If any dispute arises between the appropriate Government and the Authority as to whether a question is or is not a question of policy, the decision of the appropriate Government thereon shall be final.
(3) The Authority shall furnish to the appropriate Government such returns or other information with respect to its activities as the appropriate Government may, from time to time, require.</p>

<h2><b>Power of appropriate Government to make rules.</b></h2><br>
<p>(1) The appropriate Government shall, within a period of six months of the commencement of this Act, by notification, make rules for carrying out the provisions of this Act.</p>

