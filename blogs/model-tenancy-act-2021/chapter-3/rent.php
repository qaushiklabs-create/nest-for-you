<h2><b>Q: How is the rent payable for a premises determined under this Act?</b></h2><br>
<p>A: The rent payable for a premises is determined by the <b>agreement</b> between the landlord and the tenant, as outlined in the tenancy agreement.</p><br>

<h2><b>Q: How is the revision of rent handled?</b></h2><br>
<p>A: The revision of rent is to be done in accordance with the <b>terms of the tenancy agreement</b> between the landlord and the tenant.</p><br>

<h2><b>Q: Can the landlord increase the rent if they carry out improvements, additions, or structural alterations to the premises?</b></h2><br>
<p>A: Yes, if the landlord enters into a <b>written agreement</b> with the tenant prior to the commencement of the work and incurs expenditure for improvements, additions, or structural alterations (excluding necessary repairs under section 15), the landlord may <b>increase the rent</b> by an amount agreed upon with the tenant. This increase becomes effective <b>one month</b> after the completion of the work.</p><br>
<h2><b>Q: What can be done if there is a dispute between the landlord and tenant regarding the revision of rent?</b></h2><br>
<p>A: In case of a dispute regarding the revision of rent, either the landlord or tenant can apply to the <b>Rent Authority</b>. The Rent Authority will then determine the revised rent and other charges payable by the tenant and will also fix the date from which the revised rent becomes payable.</p><br>

<h2><b>Q: What are the restrictions on the amount of security deposit a landlord can ask for?</b></h2><br>
<p>The security deposit to be paid by the tenant in advance must be agreed upon in the tenancy agreement, but it is restricted as follows:<br>
   (a) For <b>residential premises</b>, the security deposit <b>cannot exceed two months' rent</b>.<br>
   (b) For <b>non-residential premises</b>, the security deposit <b>cannot exceed six months' rent</b>.</p><br>

<h2><b>Q: When must the landlord refund the security deposit?</b></h2><br>
<p>The landlord must <b>refund the security deposit</b> to the tenant on the date of taking over vacant possession of the premises, after deducting any liabilities of the tenant.</p>





