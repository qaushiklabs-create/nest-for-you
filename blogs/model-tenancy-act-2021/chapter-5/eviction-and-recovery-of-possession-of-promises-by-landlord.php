<h2><b>Q: Under what conditions can a tenant be evicted during the continuance of the tenancy agreement?</b></h2><br>
<p>A: A tenant can be evicted during the continuance of the tenancy agreement under the following conditions:
   <ul>
      <li>1. If the eviction is agreed to in writing by both the landlord and tenant.</li>
      <li>2. In accordance with the provisions outlined in sub-section (2) or section 22 of the Act.</li>
   </ul>
</p><br>

<h2><b>Q: What are the grounds on which the Rent Court may order eviction and recovery of possession of the premises?</b></h2><br>
<p>A: The Rent Court may order eviction and recovery of possession on the following grounds:
   <ul>
      <li>(a) The tenant does not agree to pay the agreed rent.</li>
      <li>(b) The tenant has not paid arrears of rent and other charges for two consecutive months after receiving a notice of demand.</li>
      <li>(c) The tenant has transferred possession of the premises or any part of it without written consent from the landlord.</li>
      <li>(d) The tenant has misused the premises, despite receiving notice from the landlord to stop such misuse.</li>
      <li>(e) The landlord needs to carry out repairs, construction, rebuilding, alteration, or demolition that requires the premises to be vacated.</li>
      <li>(f) The premises are needed for repairs, construction, or demolition due to a change in land use by a competent authority.</li>
      <li>(g) The tenant has given written notice to vacate, and the landlord has taken steps such as contracting to sell the premises, which would cause serious loss if the tenant is not evicted.</li>
      <li>(h) The tenant has made structural changes or erected permanent structures without the landlord's written consent.</li>
   </ul>
</p><br>

<h2><b>Q: What relief is available to a tenant who fails to pay rent but wishes to avoid eviction?</b></h2><br>
<p>A: If a tenant fails to pay rent, they can avoid eviction by:
   <ul>
      <li>1. Making payment of the arrears of rent, other charges, and interest within <b>one month</b> from the date of service of the demand notice to the landlord or depositing the amount with the Rent Court.</li>
      <li>2. However, if the tenant fails to pay rent consecutively for two months after this relief, they will not be entitled to this relief again in the future.</li>
   </ul>
</p><br>

<h2><b>Q: Can eviction be partial if repairs or construction are required?</b></h2><br>
<p>A: Yes, if the eviction is due to repairs, construction, or related activities as per clause (e) of sub-section (2), the Rent Court may allow eviction from only a part of the premises if the landlord agrees to it.</p><br>
<h2><b>Q: What provisions apply for eviction and recovery of possession of premises in the case of the landlord's death?</b></h2><br>
<p>A: In the event of the landlord's death:
   <ul>
      <li><b>(1)</b> The legal heirs of the deceased landlord can file an application for eviction and recovery of possession of the premises if they have a bona fide requirement for the property.</li>
      <li><b>(2)</b> If the Rent Court is satisfied with the bona fide requirement, it may pass orders for the tenant to vacate the premises and hand over possession to the legal heirs.</li>
   </ul>
</p><br>

<h2><b>Q: What are the consequences for a tenant who fails to vacate the premises as per the tenancy agreement after the tenancy period expires?</b></h2><br>
<p>A: If the tenant does not vacate the premises on expiration of the tenancy period or after termination of tenancy:
   <ul>
      <li><b>(a)</b> The tenant will be liable to pay twice the monthly rent for the first two months.</li>
      <li><b>(b)</b> For any period beyond the initial two months, the tenant will be liable to pay four times the monthly rent until they vacate the premises.</li>
   </ul>
</p><br>
<h2><b>Q: What is the procedure for refunding advance rent when the landlord recovers possession of the premises?</b></h2><br>
<p><b>Refund of Advance Rent:</b><br>
   <ul>
      <li><b>(1)</b> If a landlord recovers possession of the premises under sections 21 or 22 and had received any advance rent or payment from the tenant, the landlord must refund the amount to the tenant after deducting any due rent and charges.</li>
      <li><b>(2)</b> If the landlord fails to make the refund, they are liable to pay simple interest on the unpaid amount at a rate prescribed by law.</li>
   </ul>
</p><br>

<h2><b>Q: What happens if a tenant contests an eviction claim on grounds other than non-payment of rent?</b></h2><br>
<p><b>Payment of Rent During Eviction Proceedings:</b><br>
   <ul>
      <li><b>25</b> If a tenant contests an eviction claim on grounds other than non-payment of rent, the landlord can apply to the Rent Court for an order directing the tenant to pay the rent and other charges due, including any penal charges for delay in payment.</li>
   </ul>
</p><br>

<h2><b>Q: What are the rules regarding structural changes or additional structures in rented premises?</b></h2><br>
<p><b>Structural Changes and Improvements:</b><br>
   <ul>
      <li><b>(1)</b> Tenants must not make structural changes or erect permanent structures in the rented premises without the landlord's written consent.</li>
      <li><b>(2)</b> If a landlord wishes to make improvements or construct additional structures and the tenant refuses, the landlord can apply to the Rent Court.</li>
      <li><b>(3)</b> If the Rent Court is satisfied that the landlord is prepared to commence the necessary work, it may allow the work to proceed, ensuring it does not reduce the accommodation or housing services in a way that causes undue hardship to the tenant. The tenant must remove any unauthorized structures they have built without consent.</li>
   </ul>
</p><br>
<h2><b>Q: What are the provisions related to vacant land rented out, especially if the landlord wants to build on it?</b></h2><br>
<p><b>Special Provision Regarding Vacant Land:</b><br>
   <ul>
      <p><b>(1)</b> If a landlord wants to build on vacant land let out for rent and cannot obtain possession based on the tenancy agreement, the landlord or, in the case of death, the landlord’s legal heirs, can file an application to the Rent Court.</p>
      <p><b>(2)</b> The Rent Court, upon reviewing the application, may:
         <ul>
            <li><b>(a)</b> Direct the severance of the vacant land from the rest of the premises if it deems fit.</li>
            <li><b>(b)</b> Place the landlord in possession of the vacant land.</li>
            <li><b>(c)</b> Determine the rent for the remaining part of the premises.</li>
            <li><b>(d)</b> Make any other orders it considers appropriate in the circumstances.</li>
         </ul>
      </p>
   </ul>
</p><br>

<h2><b>Q: What happens when the landlord’s interest in the premises is determined, or in the case of the landlord's death?</b></h2><br>
<p><b>Binding Orders for Recovery of Possession:</b><br>
   <ul>
      <p><b>28</b> If a landlord's interest in the premises is terminated or if there is a death of the landlord, any order made by the Rent Court for the recovery of possession will be binding on all occupants. All occupants must vacate the premises and hand over possession to the landlord or the landlord’s legal heirs, subject to the provisions of sub-section (3) of section 21.</p>
   </ul>
</p>

