<h2><b>Q: How does the State Government/Union Territory Administration support the Rent Authority, Rent Court, and Rent Tribunal in carrying out their functions?</b></h2><br>
<p><b>A:</b> The State Government/Union Territory Administration, in consultation with the Rent Authority, Rent Court, or Rent Tribunal, may determine and appoint the necessary officers and other employees for the efficient discharge of their functions under the Act.</p><br>

<h2><b>Q: Can a civil court entertain suits or proceedings related to the provisions of this Act?</b></h2><br>
<p><b>A:</b> No, a civil court cannot entertain any suit or proceeding related to the provisions of this Act, except as otherwise provided within the Act.</p><br>

<h2><b>Q: What is the jurisdiction of the Rent Court?</b></h2><br>
<p><b>A:</b> The jurisdiction of the Rent Court is limited to matters concerning the tenancy agreement as specified in the First Schedule of the Act. It does not extend to questions of title or ownership of the premises.</p><br>
<h2><b>Q: How do the provisions of the Court Fees Act, 1870 apply to applications or appeals under this Act?</b></h2><br>
<p><b>A:</b> The provisions of the Court Fees Act, 1870 apply to applications or appeals presented before the Rent Authority, Rent Court, or Rent Tribunal. For court fee computation, an application for recovery of possession to the Rent Court and a memorandum of appeal to the Rent Tribunal are treated as suits between landlord and tenant. The court fees for applications filed before the Rent Authority are equivalent to those for interlocutory applications in a civil court.</p><br>

<h2><b>Q: What is the legal status of members of the Rent Authority, Rent Court, and Rent Tribunal under this Act?</b></h2><br>
<p><b>A:</b> Every member of the Rent Authority, Rent Court, and Rent Tribunal is deemed to be a public servant within the meaning of section 21 of the Indian Penal Code.</p><br>

<h2><b>Q: Can legal action be taken against individuals or entities acting under this Act?</b></h2><br>
<p><b>A:</b> No, no suit, prosecution, or other legal proceeding can be initiated against any person, Rent Authority, Rent Court, or Rent Tribunal for anything done in good faith in pursuance of this Act.</p><br>
<h2><b>Q: What powers does the State Government/Union Territory Administration have regarding the implementation of this Act?</b></h2><br>
<p><b>A:</b> The State Government/Union Territory Administration has the power to make rules for carrying out the provisions of this Act. These rules, subject to prior publication, may cover various matters, including:</p>
<ul>
    <li>1. The form and manner of a digital platform for submitting documents.</li>
    <li>2. Methods for payment and deposit of rent and other charges.</li>
    <li>3. Application procedures for recovery of possession of premises.</li>
    <li>4. The rate of interest payable to tenants when refunds are not made.</li>
    <li>5. The form and manner of filing applications and appeals before Rent Courts and Tribunals.</li>
    <li>6. Execution of orders made under this Act.</li>
    <li>7. Any other matters required to be or that may be prescribed.</li>
</ul><br>

<h2><b>Q: How are the rules made under this Act handled in terms of legislative oversight?</b></h2><br>
<p><b>A:</b> Every rule made by the State Government/Union Territory Administration under this Act must be laid before the State Legislature or Union Territory Legislature. If the legislature consists of two houses, the rules are laid before both houses; if it consists of one house, the rules are laid before that house.</p><br>
<h2><b>Q: What provisions are in place if difficulties arise in implementing the Act?</b></h2><br>
<p><b>A:</b> If difficulties arise in giving effect to the provisions of this Act, the State Government/Union Territory Administration can issue an order to remove the difficulty. This order must be published in the Official Gazette and must not be inconsistent with the Act. However, such an order cannot be made after two years from the commencement of the Act. Once made, the order must be laid before each House of the State Legislature or Union Territory Legislature as soon as possible.</p><br>

<h2><b>Q: What happens to existing rent control laws and proceedings when this Act comes into force?</b></h2><br>
<p><b>A:</b> The State/Union Territory Rent Control Act in force immediately before the commencement of this Act is repealed. However, any pending cases and proceedings under the old Rent Control Act at the time this Act commences will continue and be disposed of according to the provisions of the old Act, as if the new Act had not been enacted.</p><br>

