<h2><b>Q: Who appoints the Rent Court, and what is the required rank of the appointed officer?</b></h2><br>
<p><b>A:</b> The District Collector or District Magistrate appoints the Rent Court, with prior approval from the State Government or Union Territory Administration. The appointed officer must be an Additional Collector, Additional District Magistrate, or an officer of equivalent rank.</p><br>

<h2><b>Q: How does the State Government or Union Territory Administration appoint the Rent Tribunal?</b></h2><br>
<p><b>A:</b> The State Government or Union Territory Administration, in consultation with the jurisdictional High Court, appoints a District Judge or Additional District Judge as the Rent Tribunal in each district.</p><br>

<h2><b>Q: What procedural guidelines are Rent Courts and Rent Tribunals required to follow?</b></h2><br>
<p><b>A:</b> Rent Courts and Rent Tribunals are guided by the principles of natural justice and have the power to regulate their own procedures. The procedures include:</p>
<ul>
    <li>1. Filing an application or appeal with affidavits and documents.</li>
    <li>2. Issuing notices to the opposite party with copies of all documents.</li>
    <li>3. Receiving replies and rejoinders with copies served to the respective parties.</li>
    <li>4. Fixing a date for hearing and holding necessary summary inquiries.</li>
</ul><br>

<h2><b>Q: What is the maximum period within which the Rent Court or Rent Tribunal should dispose of a case?</b></h2><br>
<p><b>A:</b> The Rent Court or Rent Tribunal should dispose of the case as expeditiously as possible, not exceeding sixty days from the date of receipt of the application or appeal. If it exceeds this period, the reasons must be recorded in writing.</p><br>

<h2><b>Q: How is evidence presented in the Rent Court or Rent Tribunal, and can witnesses be examined?</b></h2><br>
<p><b>A:</b> Evidence is generally given by affidavit. However, the Rent Court or Rent Tribunal may order the attendance of witnesses for examination or cross-examination if necessary for justice.</p><br>

<h2><b>Q: Are the provisions of the Code of Civil Procedure, 1908, applicable to Rent Courts and Rent Tribunals?</b></h2><br>
<p><b>A:</b> The Code of Civil Procedure, 1908, regarding the service of summons is applicable mutatis mutandis for service of notice by the Rent Court or Rent Tribunal.</p><br>

<h2><b>Q: How many adjournments can be requested during proceedings, and what happens if more are needed?</b></h2><br>
<p><b>A:</b> A party may request no more than three adjournments throughout the proceedings. If more are requested due to reasonable and sufficient cause, the reasons must be recorded in writing, and the party may be ordered to pay a reasonable cost.</p><br>

<h2><b>Q: What are the time limits for deciding certain types of applications in the Rent Court?</b></h2><br>
<p><b>A:</b> Applications under clauses (a), (b), (e), (f), and (g) of sub-section (2) of section 21 or under section 22 must be decided within ninety days from the date of filing. Applications under clauses (c) and (d) of sub-section (2) of section 21 must be decided within thirty days from the date of filing.</p><br>
<h2><b>Q: What powers do the Rent Court and Rent Tribunal have under this Act?</b></h2><br>
<p><b>A:</b> The Rent Court and Rent Tribunal have the same powers as a civil court under the Code of Civil Procedure, 1908. This includes:</p>
<ul>
    <li>1. Summoning and enforcing the attendance of persons and examining them on oath.</li>
    <li>2. Requiring the discovery and production of documents.</li>
    <li>3. Issuing commissions for examining witnesses or documents and for local investigations.</li>
    <li>4. Receiving evidence on affidavits.</li>
    <li>5. Dismissing applications or appeals for default or deciding them ex parte.</li>
    <li>6. Setting aside orders of dismissal for default or other ex parte orders.</li>
    <li>7. Executing orders and decisions without reference to a civil court.</li>
    <li>8. Reviewing and revising their own orders and decisions.</li>
    <li>9. Any other prescribed matters.</li>
</ul><br>

<h2><b>Q: Are proceedings before the Rent Court and Rent Tribunal considered judicial proceedings?</b></h2><br>
<p><b>A:</b> Yes, proceedings before the Rent Court and Rent Tribunal are deemed to be judicial proceedings within the meaning of sections 193 and 228 of the Indian Penal Code. They are also considered civil courts for the purposes of section 195 and Chapter XXVI of the Code of Criminal Procedure, 1973.</p><br>

<h2><b>Q: What authority does the Rent Court have for conducting inquiries or inspections?</b></h2><br>
<p><b>A:</b> The Rent Court can:</p>
<ul>
    <li>1. Enter and inspect any premises with at least twenty-four hours written notice, or authorize an officer to do so, between sunrise and sunset.</li>
    <li>2. Require any person to produce relevant books or documents for inspection by written order.</li>
</ul><br>

<h2><b>Q: Can the Rent Court appoint experts to assist in proceedings?</b></h2><br>
<p><b>A:</b> Yes, the Rent Court may appoint one or more persons with special knowledge of the matter under consideration as assessors or valuers to advise it during proceedings.</p><br>

<h2><b>Q: How can clerical or arithmetical mistakes in Rent Court orders be corrected?</b></h2><br>
<p><b>A:</b> Clerical or arithmetical mistakes, or errors arising from accidental omissions, can be corrected by the Rent Court on an application from any of the parties or otherwise.</p><br>

<h2><b>Q: What powers does the Rent Court have regarding fines under the Code of Criminal Procedure, 1973?</b></h2><br>
<p><b>A:</b> The Rent Court can exercise the powers of a Judicial Magistrate of the first class for the recovery of fines under the Code of Criminal Procedure, 1973 and is deemed to be a Magistrate for this purpose.</p><br>

<h2><b>Q: How are orders made by the Rent Court enforced?</b></h2><br>
<p><b>A:</b> Orders made by the Rent Court, including those passed in appeal or review, are executable as decrees of a civil court, and the Rent Court has the powers of a civil court for this purpose.</p><br>

<h2><b>Q: Can a party request to set aside an ex-parte order?</b></h2><br>
<p><b>A:</b> Yes, the Rent Court may set aside an ex-parte order if the aggrieved party files an application and demonstrates that notice was not duly served or that they were prevented by sufficient cause from appearing at the hearing.</p><br>

<h2><b>Q: Are Rent Court orders subject to further questioning or appeal?</b></h2><br>
<p><b>A:</b> Save as expressly provided in the Act, every order made by the Rent Court is final and not subject to question in any original suit, application, or execution proceedings, subject to decisions in appeal.</p><br>
<h2><b>Q: How can a person appeal an order passed by the Rent Court?</b></h2><br>
<p><b>A:</b> A person aggrieved by an order passed by the Rent Court can file an appeal to the jurisdictional Rent Tribunal within thirty days from the date of the order. The appeal must be accompanied by a certified copy of the Rent Court's order.</p><br>

<h2><b>Q: What is the procedure for handling an appeal by the Rent Tribunal?</b></h2><br>
<p><b>A:</b> Upon receiving an appeal, the Rent Tribunal will:</p>
<ul>
    <li>1. Serve notice, along with a copy of the appeal, to the respondent.</li>
    <li>2. Fix a hearing within thirty days from the date of service of the notice.</li>
    <li>3. Dispose of the appeal within sixty days from the date of service.</li>
</ul><br>

<h2><b>Q: Can the Rent Tribunal allow the introduction of new documents during an appeal?</b></h2><br>
<p><b>A:</b> Yes, the Rent Tribunal may allow new documents at any stage of the appeal proceedings. However, no document shall be allowed more than once during the hearing.</p><br>

<h2><b>Q: Can the Rent Tribunal issue interlocutory orders during the appeal process?</b></h2><br>
<p><b>A:</b> Yes, the Rent Tribunal may issue interlocutory orders at its discretion during the pendency of the appeal.</p><br>

<h2><b>Q: What options does the Rent Tribunal have when deciding an appeal?</b></h2><br>
<p><b>A:</b> The Rent Tribunal may confirm, set aside, or modify the order passed by the Rent Court, after recording reasons for its decision.</p><br>

<h2><b>Q: How does the Rent Court execute its own orders or those of the Rent Tribunal?</b></h2>
<p><b>A:</b> The Rent Court executes orders by:</p>
<ul>
    <li>1. Delivering possession of the premises to the person in whose favor the decision was made.</li>
    <li>2. Attaching one or more bank accounts of the opposite party to recover the amount specified in the order.</li>
    <li>3. Appointing an advocate, a competent person, or officers of the Rent Court/local administration/local body for execution.</li>
</ul><br>

<h2><b>Q: Can the Rent Court request assistance from local authorities for executing orders?</b></h2><br>
<p><b>A:</b> Yes, the Rent Court may seek assistance from the Local Government, local body, or local police for executing final orders. However, the applicant must pay any costs decided by the Rent Court for police help.</p><br>

<h2><b>Q: How are execution proceedings handled by the Rent Court?</b></h2><br>
<p><b>A:</b> Execution proceedings are conducted in a summary manner, and the Rent Court must dispose of the application for execution within thirty days from the date of service of notice on the opposite party.</p><br>





