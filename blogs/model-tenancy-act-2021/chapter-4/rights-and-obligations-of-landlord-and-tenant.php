<h2><b>Q: How should the tenancy agreement be executed?</b></h2><br>
<p>A: The tenancy agreement must be <b>signed in duplicate</b> by both the landlord and the tenant. Each party should retain one of the original signed copies.</p><br>

<h2><b>Q: When should the tenant pay rent and other charges?</b></h2><br>
<p>A: The tenant must pay rent and other charges <b>within the period agreed upon</b> in the tenancy agreement.</p><br>

<h2><b>Q: What is the landlord or property manager required to do after receiving payment of rent and other charges?</b></h2><br>
<p>A: Upon receiving payment, the landlord or property manager must <b>immediately provide</b> a duly signed receipt for the amount received, with an acknowledgment.</p><br>

<h2><b>Q: What serves as proof of payment if rent or other charges are paid electronically?</b></h2><br>
<p>If payment is made through electronic mode, the <b>bank acknowledgment</b> will serve as <b>conclusive proof</b> of payment.</p><br>
<h2><b>Q: What can a tenant do if the landlord refuses to accept rent and other charges or refuses to give a receipt?</b></h2><br>
<p>A: If the landlord refuses to accept rent and other charges or refuses to give a receipt, the tenant can pay the rent and charges to the landlord by <b>postal money order</b> or another prescribed method for <b>two consecutive months</b>. If the landlord still refuses to accept the payment, the tenant can deposit the amount with the <b>Rent Authority</b> as prescribed.</p><br>

<h2><b>Q: What should a tenant do if they are unsure to whom the rent is payable during the tenancy agreement?</b></h2><br>
<p>If the tenant is unable to decide to whom the rent is payable during the tenancy agreement, they can deposit the rent with the <b>Rent Authority</b> as prescribed.</p><br>

<h2><b>Q: What will the Rent Authority do after receiving the rent deposit under subsections (1) or (2)?</b></h2><br>
<p>The Rent Authority will <b>inquire into the case</b> to determine to whom the rent is payable and will pass orders based on the facts of the case.</p><br>

<h2><b>Q: Does the withdrawal of rent and other charges deposited with the Rent Authority affect the landlord's rights?</b></h2><br>
<p>No, the withdrawal of rent and other charges deposited with the Rent Authority does <b>not constitute an admission</b> against the landlord or affect any claims made by the tenant. The landlord may withdraw the rent to the extent agreed upon under the tenancy agreement without prejudice to their rights.</p><br>
<h2><b>Q: What responsibilities do the landlord and tenant have regarding the condition of the premises?</b></h2><br>
<p>A: Both the landlord and tenant are responsible for keeping the premises in as good a condition as at the commencement of the tenancy, except for <b>normal wear and tear</b>. Their specific responsibilities for repair and maintenance are detailed in the Second Schedule or agreed upon in the tenancy agreement.</p><br>

<h2><b>Q: How should the repair and maintenance responsibilities for common facilities be handled?</b></h2><br>
<p>A: For common facilities shared among tenants or with the landlord, the responsibilities for repair and maintenance shall be specified in the <b>tenancy agreement</b>.</p><br>

<h2><b>Q: What can the landlord do if the tenant fails to carry out required repairs?</b></h2><br>
<p>If the tenant fails to carry out repairs, the landlord may:
   <ul>
      <li>1. Carry out the repairs or remove any additional structures erected by the tenant without consent.</li>
      <li>2. Deduct the cost of repairs or removal from the tenant's security deposit.</li>
      <li>3. If the repair costs exceed the security deposit, the tenant must pay the excess amount, including the deducted security deposit, within <b>one month</b> of receiving a notice from the landlord.</li>
   </ul>
</p><br>

<h2><b>Q: What can the tenant do if the landlord refuses to carry out repairs?</b></h2><br>
<p>If the landlord refuses to carry out necessary repairs, the tenant may:
   <ul>
      <li>1. Perform the repairs themselves and deduct the cost from the rent for the following months.</li>
      <li>2. Ensure that deductions from the rent do not exceed <b>fifty percent</b> of the agreed rent for any one month.</li>
   </ul>
</p><br>

<h2><b>Q: What can a tenant do if the premises becomes uninhabitable and the landlord refuses to make repairs?</b></h2><br>
<p>If the premises becomes uninhabitable and the landlord refuses to repair it after being requested in writing, the tenant may:
   <ul>
      <li>1. Abandon the premises after giving the landlord <b>fifteen days’ notice</b> in writing.</li>
   </ul>
</p><br>

<h2><b>Q: What happens if the premises becomes uninhabitable due to a force majeure event?</b></h2><br>
<p>If the premises becomes uninhabitable due to a force majeure event, the landlord cannot charge rent until the premises is restored to a habitable condition. If the landlord fails to make the premises inhabitable or if it cannot be made inhabitable, the landlord must refund the security deposit and advance rent to the tenant within <b>fifteen days</b> of the notice period expiry, after deducting any liabilities of the tenant.</p><br>

<h2><b>Q: What are the tenant's responsibilities during the tenancy regarding the condition of the premises?</b></h2><br>
<p>During the tenancy, the tenant must:
   <ul>
      <li>1. Not intentionally or negligently damage the premises or permit such damage.</li>
      <li>2. Inform the landlord in writing of any damage.</li>
      <li>3. Take reasonable care of the premises and its contents, including fittings and fixtures, and keep the premises reasonably habitable considering its condition at the start of the tenancy and normal living conditions.</li>
   </ul>
</p><br>
<h2><b>Q: Under what circumstances can a landlord or property manager enter the premises?</b></h2><br>
<p>A: A landlord or property manager can enter the premises after serving a notice to the tenant at least <b>twenty-four hours</b> before the time of entry for the following reasons:
   <ul>
      <li>(a) To carry out repairs or replacements, or to perform work in the premises.</li>
      <li>(b) To inspect the premises to determine if they are in a habitable state.</li>
      <li>(c) For any other reasonable cause specified in the tenancy agreement.</li>
   </ul>
</p><br>

<h2><b>Q: What should the notice for entry specify?</b></h2><br>
<p>A: The notice must specify the <b>day</b>, <b>time</b>, and <b>reason</b> for entry. The entry must occur between sunrise and sunset.</p><br>

<h2><b>Q: Can a landlord or property manager enter the premises without prior notice in any situation?</b></h2><br>
<p>A: Yes, the landlord or property manager can enter the premises without prior notice in case of <b>emergent situations</b> such as war, flood, fire, cyclone, earthquake, or any other natural calamity affecting the premises.</p><br>

<h2><b>Q: What information must a landlord provide to the tenant if a property manager is engaged?</b></h2><br>
<p>If a property manager is engaged, the landlord must provide the tenant with the following information:
   <ul>
      <li>(a) <b>Name</b> of the property manager.</li>
      <li>(b) Proof that the property manager is <b>authorized</b> by the landlord.</li>
      <li>(c) The specific <b>purposes</b> for which the property manager has been authorized and the <b>period</b> of such authorization.</li>
      <li>(d) If the property manager is a legal entity, the name of the entity and the <b>contact person</b> authorized by the entity regarding the tenancy agreement.</li>
   </ul>
</p><br>
<h2><b>Q: What are the duties of a property manager?</b></h2><br>
<p>A: The duties of a property manager include:
   <ul>
      <li>(a) Collecting rent and providing receipts.</li>
      <li>(b) Performing essential repairs on behalf of the landlord.</li>
      <li>(c) Inspecting the premises periodically.</li>
      <li>(d) Issuing notices to the tenant for:
         
            <li>(i) Proper maintenance of the premises.</li>
            <li>(ii) Delay in payment of rent.</li>
            <li>(iii) Revision of rent.</li>
            <li>(iv) Vacation of premises.</li>
            <li>(v) Renewal of tenancy.</li>
         
      </li>
      <li>(e) Assisting in the resolution of disputes among tenants and between the landlord and tenant.</li>
      <li>(f) Handling other tenancy-related matters as instructed by the landlord.</li>
   </ul>
</p><br>

<h2><b>Q: What actions can the Rent Authority take if a property manager contravenes their duties?</b></h2><br>
<p>A: If a property manager acts contrary to their duties or against the landlord's instructions, the Rent Authority may:
   <ul>
      <li>1. Remove the property manager.</li>
      <li>2. Impose costs on the property manager to compensate for any loss incurred by the landlord or tenant due to such contravention.</li>
   </ul>
</p><br>

<h2><b>Q: Is it permissible for a landlord or property manager to withhold essential supplies or services?</b></h2><br>
<p>A: No, a landlord or property manager cannot withhold any essential supply or service from the tenant. Essential services include water, electricity, piped cooking gas, lights, lifts, conservancy, parking, communication links, sanitary services, and security fixtures.</p><br>

<h2><b>Q: What can a tenant do if essential services are withheld?</b></h2><br>
<p>If essential services are withheld, the tenant can:
   <ul>
      <li>1. Apply to the Rent Authority.</li>
      <li>2. The Rent Authority may issue an interim order to restore the essential services immediately, pending further inquiry.</li>
   </ul>
</p><br>

<h2><b>Q: How does the Rent Authority handle applications regarding withheld essential services?</b></h2><br>
<p>The Rent Authority will:
   <ul>
      <li>1. Conduct an inquiry into the application within <b>one month</b> of filing.</li>
      <li>2. After giving both parties a chance to be heard, it may award compensation not exceeding <b>two months’ rent</b> to the tenant for the loss incurred.</li>
      <li>3. Impose a penalty of up to <b>twice the monthly rent</b> if the application is found to be frivolous or vexatious.</li>
   </ul>
</p><br>







