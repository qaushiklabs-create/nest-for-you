<h2><b>What is MODEL TENANCY ACT, 2021 ?</b></h2><br>
<p><b>THE MODEL TENANCY ACT, 2021 is An Act</b> to establish Rent Authority to regulate renting of premises and to protect
the interests of landlords and tenants and to provide speedy adjudication
mechanism for resolution of disputes and matters connected therewith or
incidental thereto. </p><br>

<h2><b>Q: What is the title of the Act mentioned in the document?</b></h2><br>
<p>A: The Act is called the <b>(Name of State/Union territory) Tenancy Act, 2020</b>.</p><br>

<h2><b>Q: To which areas does the Act extend?</b></h2><br>
<p>A: The Act extends to the <b>whole of the State/Union territory of (Name of State/Union territory)</b>.</p><br>

<h2><b>Q: When does the Act come into force?</b></h2><br>
<p>A: The Act comes into force on a date appointed by the <b>State Government/Union territory Administration</b>, as notified in the Official Gazette. <b>Different dates may be appointed for different provisions</b> of the Act.</p><br>

<h2><b>Q: Who is considered a "landlord" under this Act?</b></h2><br>
<p>A: A "landlord" is a person who receives or is entitled to receive rent for any premises on their own account if the premises are let to a tenant. The term also includes:</p>
<ul>
    <li>(i) The landlord's successor-in-interest.</li>
    <li>(ii) A trustee, guardian, or receiver who receives or is entitled to receive rent on behalf of another person, such as a minor or someone of unsound mind.</li>
</ul><br>

<h2><b>Q: What does the term "local authority" refer to in this Act?</b></h2><br>
<p>A: "Local authority" refers to bodies such as Village Panchayats, Panchayat Samitis, Zila Parishads, Municipal Corporations, Municipal Councils, Nagar Panchayats, Planning or Development Authorities, and Cantonment Boards, or any civil area committee under section 47 of the Cantonment Act, 2006, or any other body entitled to function as a local authority in any city or town.</p><br>

<h2><b>Q: How is the term "notification" defined in the Act?</b></h2><br>
<p>A: "Notification" means a notification published in the Official Gazette of the State or the Union territory. The term "notify" is to be construed accordingly with its grammatical variations.</p><br>

<h2><b>Q: What does "premises" mean under this Act?</b></h2><br>
<p>A: "Premises" refers to any building or part of a building intended to be let on rent for residential or commercial use, excluding hotels, lodging houses, dharamshalas, inns, and industrial use. It includes:</p>
<ul>
    <li>(i) Gardens, garages, closed parking areas, vacant land, grounds, and out-houses associated with the building.</li>
    <li>(ii) Any fittings to the building for more beneficial enjoyment.</li>
</ul><br>

<h2><b>Q: What does "prescribed" mean in the context of this Act?</b></h2><br>
<p>A: "Prescribed" refers to rules made by the State Government or Union territory Administration under this Act.</p><br>

<h2><b>Q: Who is a "property manager" according to this Act?</b></h2><br>
<p>A: A "property manager" is a person or legal entity, including rental agents, authorized by the landlord to manage the premises and represent the landlord in dealings with the tenant.</p><br>

<h2><b>Q: What is the role of a "rental agent" under this Act?</b></h2><br>
<p>A: A "rental agent" is any person who negotiates or acts on behalf of the landlord, tenant, or both in a rental transaction and receives remuneration or fees for their services. This includes property dealers, brokers, or middlemen.</p><br>

<h2><b>Q: Who or what is the "Rent Authority"?</b></h2><br>
<p>A: The "Rent Authority" is an officer appointed under section 30 of the Act.</p><br>

<h2><b>Q: What is a "Rent Court" in this Act?</b></h2><br>
<p>A: A "Rent Court" is a court constituted under section 33 of the Act.</p><br>

<h2><b>Q: How is "Rent payable" defined?</b></h2><br>
<p>A: "Rent payable" refers to the rent amount specified in section 8 of the Act.</p><br>

<h2><b>Q: What is a "Rent Tribunal"?</b></h2><br>
<p>A: A "Rent Tribunal" is a tribunal constituted under section 34 of the Act.</p><br>

<h2><b>Q: What does the term "Schedule" refer to in this Act?</b></h2><br>
<p>A: "Schedule" refers to a schedule annexed to this Act.</p><br>

<h2><b>Q: Who is a "Sub-tenant" under this Act?</b></h2><br>
<p>A: A "Sub-tenant" is a person to whom a tenant sublets the whole or part of the premises, or transfers or assigns rights accrued under the tenancy agreement through a supplementary agreement.</p><br>

<h2><b>Q: How is a "Tenant" defined in this Act?</b></h2><br>
<p>A: A "Tenant" is a person by whom or on whose account rent is payable to the landlord under a tenancy agreement. This includes sub-tenants and persons continuing in possession after the termination of their tenancy. However, it does not include anyone against whom an order or decree for eviction has been made.</p><br>

<h2><b>Q: Does this Act apply to all premises?</b></h2><br>
<p>A: No, the Act does not apply to certain premises, including:</p>
<ul>
    <li>(a) Premises owned or promoted by the Central Government, State Government, Union territory Administration, local authorities, government undertakings, enterprises, statutory bodies, or Cantonment Boards.</li>
    <li>(b) Premises owned by companies, universities, or organizations that are rented to their employees as part of a service contract.</li>
    <li>(c) Premises owned by religious or charitable institutions, as specified by notification by the State Government or Union territory Administration.</li>
    <li>(d) Premises owned by auqaf registered under the Waqf Act, 1995, or by any trust registered under the public trust law of the State or Union territory.</li>
    <li>(e) Other buildings or categories of buildings specifically exempted in the public interest by notification by the State Government or Union territory Administration.</li>
</ul><br>

<h2><b>Q: Can premises that are exempted from the Act be regulated under it?</b></h2><br>
<p>A: Yes, if the owner and tenant of the exempted premises agree that their tenancy agreement should be regulated under the provisions of the Act, the landlord can inform the Rent Authority of this agreement when providing information about the tenancy agreement under section 4 of the Act.</p><br>
