<h2><b>Q: Who appoints the Rent Authority, and what is their rank?</b></h2><br>
<p><b>A:</b> The District Collector or District Magistrate appoints the Rent Authority, with prior approval from the State Government or Union Territory Administration. The appointed officer must be of at least the rank of Deputy Collector.</p><br>

<h2><b>Q: What powers does the Rent Authority have?</b></h2><br>
<p><b>A:</b> The Rent Authority has the same powers as a Rent Court concerning proceedings under sections 4, 9, 10, 14, 15, 19, or 20 of the Act. The procedures outlined in sections 35 and 36 will apply to these proceedings.</p><br>

<h2><b>Q: How can someone appeal an order from the Rent Authority?</b></h2><br>
<p><b>A:</b> Any person aggrieved by an order of the Rent Authority can appeal to the Rent Court with territorial jurisdiction. The appeal must be filed within thirty days from the date of the Rent Authority’s order.</p>




