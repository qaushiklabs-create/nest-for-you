<h2><b>Q: What is required for letting or renting any premises after the commencement of this Act?</b></h2><br>
<p>A: After the commencement of this Act, no person can let or take on rent any premises except by a <b>written agreement</b>. This agreement must be jointly informed to the Rent Authority by the landlord and tenant within <b>two months</b> from the date of the tenancy agreement, using the form specified in the First Schedule.</p><br>

<h2><b>Q: What happens if the landlord and tenant fail to jointly inform the Rent Authority about the tenancy agreement within the specified time?</b></h2><br>
<p>A: If the landlord and tenant fail to jointly inform the Rent Authority within the specified two months, they must <b>separately</b> inform the Rent Authority within <b>one month</b> from the expiry of the initial two-month period.</p><br>

<h2><b>Q: What is the Rent Authority required to do within three months of its appointment?</b></h2><br>
<p>A: The Rent Authority must establish a <b>digital platform</b> in the local vernacular language or the language of the State/Union territory to enable the submission of documents as prescribed.</p><br>

<h2><b>Q: What actions does the Rent Authority take after receiving information about the tenancy agreement?</b></h2><br>
<p>A: After receiving the information and documents specified in the First Schedule, the Rent Authority will:</p>
<ul>
    <li>(a) Provide a <b>unique identification number</b> to the parties.</li>
    <li>(b) Upload details of the tenancy agreement on its website in the local vernacular language or the language of the State/Union territory within <b>seven working days</b>.</li>
</ul><br>

<h2><b>Q: How are the terms of authorization of the property manager established?</b></h2><br>
<p>A: The terms of authorization of the property manager, if any, are agreed upon by the landlord and tenant in the tenancy agreement.</p><br>

<h2><b>Q: What is the significance of the information provided under sub-section (1) and sub-section (2)?</b></h2><br>
<p>A: The information provided under these sub-sections serves as <b>conclusive proof</b> of the facts relating to the tenancy and related matters. In the absence of such information, the landlord and tenant will <b>not be entitled to any relief</b> under the provisions of this Act.</p><br>
<h2><b>Q: How is the validity period of a tenancy determined under this Act?</b></h2><br>
<p>A: The validity period of a tenancy is determined by the <b>agreement</b> between the landlord and tenant and is specified in the tenancy agreement.</p><br>

<h2><b>Q: Can a tenant request a renewal or extension of the tenancy?</b></h2><br>
<p>A: Yes, the tenant can request a renewal or extension of the tenancy within the period agreed upon in the tenancy agreement. If the landlord agrees, they may enter into a new tenancy agreement on <b>mutually agreed</b> terms and conditions.</p><br>

<h2><b>Q: What happens if a tenancy for a fixed term ends and is not renewed or if the tenant fails to vacate the premises?</b></h2><br>
<p>A: If the tenancy ends and is not renewed or the tenant fails to vacate the premises, the tenant is liable to pay <b>enhanced rent</b> to the landlord as provided in section 23 of the Act.</p><br>

<h2><b>Q: What exception is made if the term of tenancy expires during a force majeure event?</b></h2><br>
<p>A: If the tenancy term expires during a force majeure event (e.g., war, flood, earthquake), the landlord, upon the tenant's request, must allow the tenant to remain in the premises for up to <b>one month</b> after the cessation of the event, on the same terms and conditions as the original tenancy agreement.</p><br>

<h2><b>Q: What does "force majeure" mean in the context of this section?</b></h2><br>
<p>A: "Force majeure" refers to situations such as <b>war, flood, drought, fire, cyclone, earthquake</b>, or any other natural calamity affecting the tenant's ability to inhabit the rented premises.</p><br>
<h2><b>Q: What happens to the tenancy agreement if the landlord or tenant dies?</b></h2><br>
<p>A: In the event of the death of the landlord or tenant, the terms of the tenancy agreement will be <b>binding</b> on their successors. The successors will have the <b>same rights and obligations</b> as agreed to in the tenancy agreement for the remaining period of the tenancy.</p><br>

<h2><b>Q: Can a tenant sub-let the premises or transfer their rights in the tenancy agreement after the commencement of this Act?</b></h2><br>
<p>A: No, after the commencement of this Act, a tenant cannot sub-let the premises or transfer their rights in the tenancy agreement <b>without entering into a supplementary agreement</b> to the existing tenancy agreement.</p><br>

<h2><b>Q: What must the landlord and tenant do if they enter into a supplementary agreement for sub-letting?</b></h2><br>
<p>A: If a supplementary agreement for sub-letting is made, the landlord and tenant must <b>jointly inform the Rent Authority</b> about the sub-tenancy within <b>two months</b> from the date of the agreement, using the form specified in the First Schedule.</p><br><br>





