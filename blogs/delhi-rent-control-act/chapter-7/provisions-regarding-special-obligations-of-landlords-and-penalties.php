<h2><b>Q: What is the landlord's primary responsibility concerning the maintenance of the premises?</b></h2><br>
<p>A: The landlord is obligated to keep the premises in good and tenantable repair at all times.</p><br>

<h2><b>Q: What can a tenant do if the landlord fails to make necessary repairs after receiving written notice?</b></h2><br>
<p>A: If the landlord neglects or fails to make repairs within a reasonable time after receiving written notice, the tenant may undertake the repairs themselves and deduct the costs from the rent. The amount that can be deducted or recovered in a year cannot exceed one-twelfth of the annual rent.</p><br>

<h2><b>Q: What if the repairs are crucial to making the premises habitable or usable?</b></h2><br>
<p>A: For essential repairs that affect the habitability or usability of the premises, the tenant can apply to the Controller for permission to make these repairs. The tenant must submit an estimate of the repair costs, and the Controller may grant permission for the repairs and specify the maximum cost that can be deducted from the rent. This cost must not exceed one-half of the tenant's annual rent.</p><br>

<h2><b>Q: Can the tenant cover additional repair costs beyond the specified amount?</b></h2><br>
<p>A: Yes, if the Controller deems additional repairs necessary beyond the specified amount, the tenant can agree to bear the excess cost themselves, with the Controller's permission.</p><br>

<h2><b>Q: What are the restrictions on landlords regarding essential supplies or services?</b></h2><br>
<p>A: Landlords cannot cut off or withhold any essential supply or service enjoyed by the tenant without just and sufficient cause.</p><br>

<h2><b>Q: What should a tenant do if their essential supply or service is cut off or withheld by the landlord?</b></h2><br>
<p>A: The tenant should file a complaint with the Controller if the landlord cuts off or withholds essential supplies or services.</p><br>

<h2><b>Q: What actions can the Controller take if the essential supply or service was unjustly withheld?</b></h2><br>
<p>A: If the Controller finds that the landlord withheld essential supplies or services without just cause, they will order the landlord to restore these services. Additionally, the Controller may issue an interim order for immediate restoration without prior notice if it is found that the landlord acted to compel the tenant to vacate or pay higher rent.</p><br>

<h2><b>Q: Can the Controller award compensation in cases of disputes over essential supplies or services?</b></h2><br>
<p>A: Yes, the Controller can award compensation. They may direct the landlord to pay compensation to the tenant if the landlord withheld services unjustly. Conversely, if the tenant’s application was frivolous or vexatious, the Controller might direct the tenant to pay compensation to the landlord. The compensation amount is capped at fifty rupees.</p><br>

<h2><b>Q: What constitutes "essential supplies or services" under these provisions?</b></h2><br>
<p>A: Essential supplies or services include the supply of water, electricity, lighting in passages and staircases, conservancy, and sanitary services.</p><br>

<h2><b>Q: How does withholding essential supplies or services by the landlord affect the tenant's situation?</b></h2><br>
<p>A: Withholding essential supplies or services can lead to complaints and legal action. If the landlord's actions are deemed unjustified, they will be required to restore the services and may face financial penalties or compensation claims.</p><br>

<h2><b>Q: What is the landlord required to do after constructing new premises?</b></h2><br>
<p><b>A:</b> The landlord must inform the Director of Estates or any other designated officer in writing about the completion of the new construction within thirty days.</p><br>

<h2><b>Q: To which types of premises does the lease provision apply?</b></h2><br>
<p><b>A:</b> The provision applies to residential premises in areas that were part of the New Delhi Municipal Committee as of April 7, 1958, and have a standard rent of at least two thousand and four hundred rupees per year.</p><br>

<h2><b>Q: What steps must a landlord take when such a premises becomes vacant?</b></h2><br>
<p><b>A:</b> The landlord must notify the Director of Estates in writing within seven days of the premises becoming vacant.</p><br>

<h2><b>Q: What happens if the landlord fails to provide this notification?</b></h2><br>
<p><b>A:</b> Even if the landlord does not provide the notification, the Director of Estates can serve a notice to the landlord, informing them that the government requires the premises and directing them to deliver possession.</p><br>

<h2><b>Q: What is the time frame for issuing the notice by the Director of Estates?</b></h2><br>
<p><b>A:</b> The Director of Estates can only issue the notice within seven days after receiving the landlord's notification. If the landlord fails to notify, the notice must be issued within seven days of the premises becoming vacant.</p><br>

<h2><b>Q: Are there any exemptions from this requirement?</b></h2><br>
<p><b>A:</b> Yes, the provisions do not apply if the landlord has obtained possession based on an order related to specific grounds under section 14 or if the premises were released from requisition for the landlord’s personal use.</p><br>

<h2><b>Q: What is the effect of the notice from the Director of Estates?</b></h2><br>
<p><b>A:</b> Upon receiving the notice, the premises are deemed to be leased to the government for the specified period. The terms of the lease are either agreed upon between the government and the landlord or determined by the Controller if an agreement is not reached.</p><br>

<h2><b>Q: What compensation does the landlord receive if the government does not take the premises on lease?</b></h2><br>
<p><b>A:</b> If the government does not lease the premises after the landlord has given proper notice, the government must pay the landlord a sum equal to one-fifty-second of the standard rent per year.</p><br>

<h2><b>Q: How can the government use the premises taken on lease under this section?</b></h2><br>
<p><b>A:</b> The government can use the premises for any purpose, including public institutions, foreign embassies, legations, consulates, or residences for government officers or officials of foreign entities.</p><br>

<h2><b>Q: Can the terms of the lease be contested if the landlord and government do not agree?</b></h2><br>
<p><b>A:</b> Yes, if the landlord and the government cannot agree on the terms of the lease, the Controller will determine the lease terms according to the provisions of the Act.</p><br>

<h2><b>Q: What are the penalties for contravening the provisions of section 5?</b></h2><br>
<p><b>A:</b> Penalties depend on the specific subsection of section 5 violated:</p>
<ul>
  <li><b>(a) For violating sub-section (1) of section 5:</b> Simple imprisonment for up to three months, a fine up to one thousand rupees more than the unlawful charge claimed or received, or both.</li>
  <li><b>(b) For violating sub-sections (2) or (3) of section 5:</b> Simple imprisonment for up to six months, a fine up to five thousand rupees more than the unlawful charge claimed or received, or both.</li>
</ul><br>

<h2><b>Q: What is the penalty for a tenant who sub-lets, assigns, or parts with possession in violation of the provisions of section 14?</b></h2><br>
<p><b>A:</b> The tenant may be fined up to one thousand rupees.</p><br>

<h2><b>Q: What are the penalties for a landlord who re-lets or transfers premises in violation of section 19?</b></h2><br>
<p><b>A:</b> The landlord may face imprisonment for up to six months, a fine, or both.</p><br>

<h2><b>Q: What penalties does a landlord face for contravening section 45 regarding the withholding of essential services?</b></h2><br>
<p><b>A:</b> The landlord may be punished with imprisonment for up to three months, a fine, or both.</p><br>

<h2><b>Q: What happens if a landlord fails to comply with section 46, which requires notifying new construction to the government?</b></h2><br>
<p><b>A:</b> The landlord may be fined up to one hundred rupees.</p><br>

<h2><b>Q: What are the penalties for violating the provisions related to the lease of vacant premises to the government under section 47?</b></h2><br>
<p><b>A:</b> Violations of clause (a) of sub-section (2) or failure to comply with a requirement under clause (b) of section 47 may result in:</p>
<ul>
  <li>1. Simple imprisonment for up to three months,</li>
  <li>2. A fine up to one thousand rupees,</li>
  <li>3. Or both.</li>
</ul>
<p>These penalties ensure adherence to the provisions related to rent control, maintenance of properties, and appropriate dealings with government leasing.</p><br>

<h2><b>Q: Which court has jurisdiction to try offences punishable under this Act?</b></h2><br>
<p><b>A:</b> Only a court of a Metropolitan Magistrate or higher can try offences punishable under this Act.</p><br>

<h2><b>Q: What is the time limit for filing a complaint regarding an offence under this Act?</b></h2><br>
<p><b>A:</b> Complaints must be made within three months from the date of the commission of the offence.</p><br>

<h2><b>Q: Can a Metropolitan Magistrate impose a fine exceeding five thousand rupees for an offence under this Act?</b></h2><br>
<p><b>A:</b> Yes, notwithstanding section 29 of the Code of Criminal Procedure, 1973, a Metropolitan Magistrate can impose a fine exceeding five thousand rupees.</p><br>







