<h2><b>Q: When is rent considered due from a tenant?</b></h2><br>
<p>A: Rent is due within the time specified by the contract. If there is no such contract, rent must be paid by the fifteenth day of the month following the month for which it is payable. If the tenant defaults on payment, they are liable to pay simple interest at 15% per annum from the due date until the payment is made.</p><br>

<h2><b>Q: What rights does a tenant have when paying rent to a landlord?</b></h2><br>
<p>A: Every tenant who pays rent is entitled to receive a written receipt from the landlord or their authorized agent. The receipt should be provided immediately and must be signed by the landlord or their authorized agent. Tenants can also remit rent via postal money order.</p><br>

<h2><b>Q: What can a tenant do if the landlord or their authorized agent refuses to provide a receipt?</b></h2><br>
<p>A: If the landlord or their authorized agent refuses or neglects to provide a receipt, the tenant can apply to the Controller within two months of the payment date. After hearing both parties, the Controller may order the landlord or agent to pay the tenant damages up to double the amount of the rent paid, cover the costs of the application, and issue a certificate for the rent paid.</p><br>

<h2><b>Q: Can the Controller issue a certificate for the rent paid if the receipt is not provided?</b></h2><br>
<p>A: Yes, the Controller can grant a certificate to the tenant regarding the rent paid if they order damages due to the landlord's failure to issue a receipt.</p><br>


<h2><b>Q: Under what circumstances can a tenant deposit rent with the Controller?</b></h2><br>
<p>A: A tenant may deposit rent with the Controller in the following circumstances:</p>
<ul>
  <li>1. If the landlord does not accept the rent tendered by the tenant within the time specified.</li>
  <li>2. If the landlord refuses or neglects to provide a receipt for the rent.</li>
  <li>3. If there is a bona fide doubt about the person or persons to whom the rent is payable. In such cases, the tenant may also remit the rent to the Controller by postal money order.</li>
</ul><br>

<h2><b>Q: What information must a tenant include in their application when depositing rent with the Controller?</b></h2><br>
<p>A: The tenant's application for depositing rent must include:</p>
<ul>
  <li>1. A description of the premises for which the rent is deposited.</li>
  <li>2. The period for which the rent is deposited.</li>
  <li>3. The name and address of the landlord or the person claiming the rent.</li>
  <li>4. The reasons and circumstances for making the deposit.</li>
  <li>5. Any other prescribed particulars.</li>
</ul><br>

<h2><b>Q: What happens after the rent is deposited with the Controller?</b></h2><br>
<p>A: After the deposit, the Controller will send a copy of the application to the landlord or persons claiming the rent, along with an endorsement of the deposit date.</p><br>

<h2><b>Q: How does a landlord or other claimant withdraw deposited rent?</b></h2><br>
<p>A: If a person claims to be entitled to the deposited rent, the Controller will order the payment of the rent to that person if satisfied of their entitlement. The Controller must also give all persons named in the tenant's application an opportunity to be heard before making such an order. The order will be subject to any rights of such persons being determined by a competent court.</p><br>

<h2><b>Q: What happens if a landlord or claimant disputes the tenant’s reasons for depositing the rent?</b></h2><br>
<p>A: If, within thirty days of receiving notice of the deposit, the landlord or claimant contests the tenant’s reasons for depositing the rent as untrue, the Controller may levy a fine on the tenant up to two months’ rent if the statements are found to be materially untrue. The Controller may also order that part of the fine be paid to the landlord as compensation.</p><br>

<h2><b>Q: What recourse does a tenant have if a landlord refuses to accept rent without reasonable cause?</b></h2><br>
<p>A: If a landlord refuses to accept rent tendered within the specified time without reasonable cause, the tenant can complain to the Controller. The Controller may then levy a fine on the landlord up to two months’ rent and may direct that part of the fine be paid to the tenant as compensation.</p><br>

<h2><b>Q: What is the time limit for making a rent deposit under section 27?</b></h2><br>
<p>A: The rent must be deposited within twenty-one days from the time specified in section 26 for payment of the rent. Any deposit made after this period will not be considered valid.</p><br>

<h2><b>Q: What happens if a tenant makes a false statement in their application for depositing rent?</b></h2><br>
<p>A: If a tenant wilfully makes a false statement in the application for depositing rent, the deposit may not be considered valid, unless the landlord has withdrawn the deposited amount before the tenant files an application for recovery of possession of the premises.</p><br>

<h2><b>Q: What are the consequences if a rent deposit is made within the specified time and does not become invalid due to false statements?</b></h2><br>
<p>A: If the deposit is made within the required time and remains valid, it will be treated as if the rent had been validly tendered to the landlord.</p><br>

<h2><b>Q: Does the withdrawal of rent deposited under section 27 admit the correctness of the tenant’s claims in their application?</b></h2><br>
<p>A: No, withdrawing the rent deposited does not admit the correctness of the rate of rent, period of default, amount due, or any other facts stated in the tenant's application for depositing the rent.</p><br>

<h2><b>Q: What happens to rent deposits that are not withdrawn?</b></h2><br>
<p>A: Any rent deposited that is not withdrawn by the landlord or the person entitled to receive it will be forfeited to the Government if not withdrawn within five years from the date the notice of deposit was posted.</p><br>

<h2><b>Q: How does the Controller handle the forfeiture of unclaimed rent deposits?</b></h2><br>
<p>A: Before forfeiting the rent deposit, the Controller must give notice to the landlord or the person entitled to the rent by registered post at their last known address. The notice must also be published in the Controller's office and in a local newspaper.</p><br>




