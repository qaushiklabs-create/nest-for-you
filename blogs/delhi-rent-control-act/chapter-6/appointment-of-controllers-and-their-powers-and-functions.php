<h2><b>Q: Who has the authority to appoint Controllers and Additional Controllers?</b></h2><br>
<p>A: The Central Government has the authority to appoint Controllers and Additional Controllers. This is done through a notification in the Official Gazette.</p><br>

<h2><b>Q: What are the qualifications required for someone to be appointed as a Controller or Additional Controller?</b></h2><br>
<p>A: To be appointed as a Controller or Additional Controller, a person must meet one of the following criteria:</p>
<ul>
    <li>1. Have held a judicial office in India for at least five years, or</li>
    <li>2. Have practiced as an advocate or pleader in India for at least seven years.</li>
</ul><br>

<h2><b>Q: What powers does the Controller have concerning proceedings?</b></h2><br>
<p>A: The Controller has the power to:</p>
<ul>
    <li>1. Transfer any proceeding pending before him to an Additional Controller.</li>
    <li>2. Withdraw any proceeding from an Additional Controller and either dispose of it himself or transfer it to another Additional Controller.</li>
</ul><br>

<h2><b>Q: What powers does the Controller have that are similar to those of a civil court?</b></h2><br>
<p>A: The Controller has the same powers as a civil court under the Code of Civil Procedure, 1908, including:</p>
<ul>
    <li>1. Summoning and enforcing the attendance of any person and examining them on oath.</li>
    <li>2. Requiring the discovery and production of documents.</li>
    <li>3. Issuing commissions for the examination of witnesses.</li>
    <li>4. Any other matter that may be prescribed by regulations.</li>
</ul><br>

<h2><b>Q: How is a proceeding before the Controller treated legally?</b></h2><br>
<p>A: A proceeding before the Controller is deemed a judicial proceeding under sections 193 and 228 of the Indian Penal Code, and the Controller is considered a civil court within the meaning of sections 480 and 482 of the Code of Criminal Procedure, 1898.</p><br>

<h2><b>Q: What powers does the Controller have for inspection and document production?</b></h2><br>
<p>A: The Controller can:</p>
<ul>
    <li>1. Enter and inspect any premises with at least twenty-four hours’ notice in writing, or authorize a subordinate officer to do so, during the time between sunrise and sunset.</li>
    <li>2. By written order, require any person to produce relevant accounts, books, or documents for inspection at a specified time and place.</li>
</ul><br>

<h2><b>Q: Can the Controller appoint experts to assist in proceedings?</b></h2><br>
<p>A: Yes, the Controller may appoint one or more persons with special knowledge of the matter under consideration as assessors to advise him in the proceedings.</p><br>


<h2><b>Q: What is required before the Controller can make an order that prejudicially affects a person?</b></h2><br>
<p>A: Before making any order that prejudicially affects a person, the Controller must:</p>
<ul>
    <li>1. Give the affected person a reasonable opportunity to show cause against the proposed order.</li>
    <li>2. Consider any objections and evidence presented by the affected person.</li>
</ul><br>

<h2><b>Q: What procedural rules does the Controller follow during inquiries?</b></h2><br>
<p>A: The Controller is required to follow the practice and procedure of a Court of Small Causes, including:</p>
<ul>
    <li>1. The recording of evidence.</li>
    <li>2. Subject to any rules made under the Act, the Controller should adhere as closely as possible to these procedures.</li>
</ul><br>

<h2><b>Q: How are costs handled in proceedings before the Controller?</b></h2><br>
<p>A: The Controller must consider the question of costs in all proceedings and award costs to or against any party as deemed reasonable.</p><br>

<h2><b>Q: What is the procedure for appealing an order made by the Controller?</b></h2><br>
<p>A:</p>
<ul>
    <li><b>1. Appeal Basis:</b> Appeals can be made only on questions of law to the Rent Control Tribunal, which consists of one person appointed by the Central Government.</li>
    <li><b>2. Time Limit:</b> Appeals must be filed within thirty days from the date of the Controller’s order. The Tribunal may extend this period if there is sufficient cause for the delay.</li>
    <li><b>3. Powers of Tribunal:</b> The Tribunal has all the powers vested in a court under the Code of Civil Procedure, 1908, when hearing an appeal.</li>
</ul><br>

<h2><b>Q: Can the Tribunal transfer proceedings between Controllers?</b></h2><br>
<p>A: Yes, the Tribunal may transfer any proceeding pending before a Controller or Additional Controller to another Controller or Additional Controller. The Controller to whom the proceeding is transferred may dispose of it according to any special directions given in the transfer order.</p><br>

<h2><b>Q: What are the qualifications required for appointment to the Tribunal?</b></h2><br>
<p>A: A person appointed to the Tribunal must:</p>
<ul>
    <li>1. Be, or have been, a district judge, or</li>
    <li>2. Have held a judicial office in India for at least ten years.</li>
</ul><br>


<h2><b>Q: What is the purpose of constituting Additional Rent Control Tribunals?</b></h2><br>
<p>A: The Additional Rent Control Tribunals are established to expedite the disposal of appeals and applications under section 38. The Central Government can constitute these tribunals as needed and appoint qualified individuals to them.</p><br>

<h2><b>Q: How are the functions and powers of Additional Rent Control Tribunals determined?</b></h2><br>
<p>A: The Tribunal may:</p>
<ul>
    <li>1. Specify which appeals or classes of appeals each Additional Tribunal can handle.</li>
    <li>2. Determine the types of cases where Additional Tribunals can exercise the Tribunal’s powers.</li>
    <li>3. Transfer appeals or proceedings between the Tribunal and Additional Tribunals as needed.</li>
</ul><br>

<h2><b>Q: What are the procedural similarities between the main Tribunal and Additional Tribunals?</b></h2><br>
<p>A: The provisions of sub-sections (2) and (3) of section 38, which cover the power to transfer and the handling of appeals, apply to Additional Tribunals in the same way they apply to the main Tribunal.</p><br>

<h2><b>Q: What role does the High Court play in the transfer of appeals and proceedings?</b></h2><br>
<p>A: The High Court has the power to:</p>
<ul>
    <li>1. Transfer any appeal or proceeding from the Tribunal to an Additional Tribunal.</li>
    <li>2. Transfer any appeal or proceeding from an Additional Tribunal to the Tribunal or to another Additional Tribunal.</li>
</ul><br>

<h2><b>Q: What happened to the provision for a second appeal?</b></h2><br>
<p>A: The provision for a second appeal was omitted by The Delhi Rent Control (Amendment) Act, 1988. As a result, the option for a second appeal is no longer available under this Act.</p><br>

<h2><b>Q: How can clerical or arithmetical mistakes in orders be corrected?</b></h2><br>
<p>A: Clerical or arithmetical mistakes, or errors arising from accidental slips or omissions in any order passed by the Controller, the Tribunal, or an Additional Tribunal can be corrected at any time. This can be done either on an application received from any of the parties or otherwise by the Controller or the Tribunal.</p><br>

<h2><b>Q: What are the powers of the Controller regarding the recovery of fines?</b></h2><br>
<p>A: If a fine is imposed by the Controller, it must be paid within the time allowed by the Controller. The Controller may extend this time for good and sufficient reasons. If the fine is not paid within the extended time, it can be recovered as a fine under the provisions of the Code of Criminal Procedure, 1898, and the Controller will be deemed to be a magistrate for this purpose.</p><br>

<h2><b>Q: What are the powers of the Controller for the execution of orders, other than recovery of fines?</b></h2><br>
<p>A: Except for the recovery of fines, any order made by the Controller or an order passed on appeal under this Act is executable as a decree of a civil court. The Controller, in this regard, has all the powers of a civil court.</p><br>

<h2><b>Q: What is the finality of orders made by the Controller or on appeal?</b></h2><br>
<p>A: Every order made by the Controller or on appeal under this Act is final and cannot be questioned in any original suit, application, or execution proceeding, unless otherwise expressly provided in the Act.</p><br>






