<h2><b>Q: Can a civil court handle cases related to the fixation of standard rent or eviction of tenants under this Act?</b></h2><br>
<p><b>A:</b> No, civil courts cannot entertain suits or proceedings related to the fixation of standard rent, eviction of tenants, or any matter that the Controller is empowered to decide under this Act. Civil courts are also barred from granting injunctions regarding actions taken by the Controller.</p><br>

<h2><b>Q: What happens to ongoing civil court proceedings related to tenant eviction if the premises are covered under this Act?</b></h2><br>
<p><b>A:</b> If a suit or proceeding for eviction is pending in a civil court and pertains to premises constructed after June 1, 1951, but before June 9, 1955, the suit or proceeding will abate upon the commencement of this Act.</p><br>

<h2><b>Q: What recourse does an evicted tenant have if they were evicted after August 16, 1958, from premises constructed between June 1, 1951, and June 9, 1955?</b></h2><br>
<p><b>A:</b> An evicted tenant can apply to the Controller within six months of eviction. The Controller may then direct the landlord to either restore possession of the premises to the tenant or pay compensation as deemed appropriate.</p><br>

<h2><b>Q: Can a civil court decide on questions of title or the entitlement to receive rent for premises under this Act?</b></h2><br>
<p><b>A:</b> Yes, civil courts can entertain suits or proceedings concerning the title to premises or the persons entitled to receive the rent, even if the premises fall under the purview of this Act.</p><br>


<h2><b>Q: What is the status of Controllers and additional Controllers appointed under this Act?</b></h2><br>
<p><b>A:</b> Controllers and additional Controllers are considered public servants as defined by section 21 of the Indian Penal Code. This means they are subject to the same legal responsibilities and protections afforded to public servants under the law.</p><br>

<h2><b>Q: Are Controllers and additional Controllers protected from legal actions for their actions taken under this Act?</b></h2><br>
<p><b>A:</b> Yes, Controllers and additional Controllers are protected from suits, prosecutions, or other legal proceedings if their actions are done in good faith while performing their duties under this Act. This protection ensures that they can perform their functions without fear of legal repercussions for actions that are intended to be in accordance with the law.</p><br>

<h2><b>Q: Does this Act affect the provisions of other existing legislation?</b></h2><br>
<p><b>A:</b> No, this Act does not affect the provisions of the following laws:</p>
<ul>
    <li>1. The Administration of Evacuee Property Act, 1950</li>
    <li>2. The Slum Areas (Improvement and Clearance) Act, 1956</li>
    <li>3. The Delhi Tenants (Temporary Protection) Act, 1956</li>
</ul>
<p>These laws continue to operate independently of this Act.</p><br>

<h2><b>Q: What happens to decrees or orders for recovery of possession under the Delhi Tenants (Temporary Protection) Act, 1956, if this Act comes into force?</b></h2><br>
<p><b>A:</b> If a decree or order for the recovery of possession is sought to be executed after the Delhi Tenants (Temporary Protection) Act, 1956 ceases to apply, the executing court may, upon application or otherwise, review the case. If the court finds that the decree or order could not have been passed if this Act had been in force at that time, it may set aside the decree or order or issue an appropriate order in line with the provisions of this Act.</p><br>

<h2><b>Q: Who has the authority to make rules under this Act?</b></h2><br>
<p><b>A:</b> The Central Government has the authority to make rules to carry out the purposes of this Act. This is done through notifications in the Official Gazette.</p><br>

<h2><b>Q: What types of matters can these rules cover?</b></h2><br>
<p><b>A:</b> The rules can cover a wide range of matters, including but not limited to:</p>
<ul>
    <li>1. The approval and procedures for valuers (under the proviso to sub-section (2) of section 9).</li>
    <li>2. The form and manner of applications to the Controller, including timelines.</li>
    <li>3. The process for applications related to deposits or rent, including required details.</li>
    <li>4. Procedures for how a Controller should conduct inquiries.</li>
    <li>5. The powers of a Controller that are equivalent to those of a civil court.</li>
    <li>6. The form and process for making appeals or transferring proceedings to the Tribunal.</li>
    <li>7. The manner of serving notices under the Act.</li>
    <li>8. Any other matter that needs to be prescribed.</li>
</ul><br>

<h2><b>Q: What is the process for the approval of these rules?</b></h2><br>
<p><b>A:</b> After the rules are made, they must be laid before each House of Parliament as soon as possible. This presentation must occur while Parliament is in session and will be for a period of thirty days, which can be in one session or across multiple sessions. If both Houses of Parliament agree to modify or annul the rules before the end of the session following the session during which the rules were laid, the rules will only have effect in the modified form or be of no effect at all. However, any actions taken under the rules before such modification or annulment will remain valid.</p><br>

<h2><b>Q: Which Act is repealed by this Act?</b></h2><br>
<p><b>A:</b> The Delhi and Ajmer Rent Control Act, 1952 (38 of 1952) is repealed in so far as it applies to the Union territory of Delhi.</p><br>

<h2><b>Q: What happens to suits and proceedings that were pending under the repealed Act when this new Act commenced?</b></h2><br>
<p><b>A:</b> All suits and other proceedings pending under the Delhi and Ajmer Rent Control Act, 1952 at the commencement of this Act shall continue and be disposed of as if the repealed Act had continued in force. This means that the proceedings will be governed by the provisions of the repealed Act.</p><br>

<h2><b>Q: Are there any exceptions to this rule for pending suits and proceedings?</b></h2><br>
<p><b>A:</b> Yes, for suits or proceedings related to the fixation of standard rent or eviction of a tenant from premises not covered by section 54 of this Act, the court or other authority must consider the provisions of the new Act.</p><br>

<h2><b>Q: How are appeals handled for suits and proceedings disposed of under the repealed Act?</b></h2><br>
<p><b>A:</b> The provisions for appeal under the repealed Act will continue to apply to suits and proceedings that were disposed of under that Act.</p><br>

<h2><b>Q: Does this Act affect the operation of the repealed Act's provisions for pending cases?</b></h2><br>
<p><b>A:</b> While the repealed Act’s provisions apply to pending cases, the new Act’s provisions must be considered where applicable, especially for matters involving standard rent and eviction not covered by section 54 of the new Act.</p><br>





