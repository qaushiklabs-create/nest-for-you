<h2><b>Q: How do the provisions of Chapter IIIA relate to other laws and provisions in this Act?</b></h2><br>
<p>A: The provisions of Chapter IIIA, or any rule made under it, have an <b>overriding effect</b>. This means they take precedence over any inconsistent provisions found elsewhere in this Act or any other law in force.</p><br>

<h2><b>Q: What is the procedure for handling applications for eviction based on bona fide requirement?</b></h2><br>
<p>A: The procedure for handling these applications is as follows:<br>
<ul>
    <p>1. The Controller will issue <b>summons</b> using the form specified in the Third Schedule.</p>
    <p>2. Summons will be served by <b>registered post with acknowledgment due</b>, and may also be published in a local newspaper if necessary.</p>
    <p>3. If the tenant or their agent refuses to accept the registered summons or it is returned with an endorsement of refusal, the Controller may <b>declare the service of summons as valid</b>.</p>
    <p>4. The tenant must file an affidavit stating the grounds for contesting the eviction and obtain leave from the Controller to contest. Failure to do so will result in the landlord’s statement being deemed admitted, leading to an border for eviction.</p>
    <p>5. If leave to contest is granted, the Controller will <b>commence the hearing as soon as possible</b>.</p>
    <p>6. The Controller follows the practice and procedure of a <b>Court of Small Causes</b>, including recording evidence.</p>
</ul></p><br>

<h2><b>Q: Can a tenant appeal against an eviction order made by the Controller under this procedure?</b></h2><br>
<p>A: No, there is <b>no appeal</b> or second appeal against such an eviction order. However, the High Court can <b>review the order</b> to ensure it is according to law by calling for the case records and passing appropriate orders.</p><br>

<h2><b>Q: Can the Controller review their own eviction order?</b></h2><br>
<p>A: Yes, if no revision application has been made to the High Court, the Controller can exercise <b>review powers</b> in accordance with Order XLVII of the First Schedule to the Code of Civil Procedure, 1908.</p><br>

<h2><b>Q: Is the procedure for eviction on the grounds specified in section 14 or 14A different from other eviction procedures?</b></h2><br>
<p>A: The procedure for eviction based on grounds specified in clause (e) of the proviso to sub-section (1) of section 14, or under section 14A, follows the <b>same general procedure</b> as other eviction applications, with specific rules detailed in Chapter IIIA.</p>


<h2><b>Q: How does Section 25C modify the application of certain provisions of the Act?</b></h2><br>
<p>A: Section 25C provides specific modifications to the application of the Act in relation to certain landlords:<br>
<ul>
    <p><b>1. Sub-section (6) of section 14</b>, which typically deals with restrictions on eviction, does not apply to landlords who occupy residential premises allotted by the Central Government or a local authority and are required to vacate such premises by order.</p>
    <p>2. It also does not apply if the landlord owns residential accommodation in the Union territory of Delhi, whether in their own name or in the name of their spouse or dependent child.</p>
</ul></p><br>

<h2><b>Q: What is the effect of Section 25C on eviction orders obtained by landlords in specific situations?</b></h2><br>
<p>A: For landlords who fall into the category specified in sub-section (1) of Section 25C and who have obtained an eviction order on the grounds of bona fide requirement (under clause (e) of the proviso to sub-section (1) of section 14 or under section 14A), the provision in sub-section (7) of section 14 will be modified. Specifically, the <b>period for which the tenant is required to vacate will be reduced from six months to two months</b>.</p><br>

<h2><b>Q: Who does Section 25C apply to?</b></h2><br>
<p>A: Section 25C applies to landlords who are:<br>
<ul>
    <li><b>1. Occupants of residential premises allotted by the Central Government or a local authority</b>, and are required by an order from the Government or authority to vacate such premises, or</li>
    <li><b>2. Owners of residential accommodation in the Union territory of Delhi</b>, either in their own name or in the name of their spouse or dependent child.</li>
</ul></p><br>

<h2><b>Q: What does the reduction in the notice period mean for tenants facing eviction under Section 25C?</b></h2><br>
<p>A: For tenants facing eviction under the grounds specified in Section 25C, the <b>notice period for vacating the premises is reduced from six months to two months</b>, which means they have less time to vacate the premises.</p><br>





