<h2><b>Q: What is the title of the Act?</b></h2><br>
<p>A: The title of the Act is the <b>"Delhi Rent Control Act, 1958."</b></p><br>

<h2><b>Q: To which areas does the Delhi Rent Control Act, 1958, extend?</b></h2><br>
<p>A: The Act extends to the following areas:<br>
<ul>
    <p>1. Areas included within the limits of the <b>New Delhi Municipal Committee.</b></p>
    <p>2. Areas within the <b>Delhi Cantonment Board</b>.</p>
    <p>3. Specified urban areas within the limits of the <b>Municipal Corporation of Delhi</b>, as mentioned in the <b>First Schedule</b>.</p>
</ul></p><br>

<h2><b>Q: Can the Central Government modify the areas covered by the Act?</b></h2><br>
<p>A: Yes, the Central Government can, by notification in the <b>Official Gazette</b>, extend the Act or any of its provisions to any other urban area within the limits of the Municipal Corporation of Delhi, or exclude any area from the operation of the Act or any of its provisions.</p><br>

<h2><b>Q: When will the Act come into force?</b></h2><br>
<p>A: The Act will come into force on a date appointed by the <b>Central Government</b>, which will be notified in the <b>Official Gazette</b>.</p>

<h2><b>Q: What does "basic rent" refer to in the context of the Delhi Rent Control Act, 1958?</b></h2><br>
<p>A: "Basic rent" refers to the rent of premises let out before June 2, 1944, as determined in accordance with the provisions of the <b>Second Schedule</b> of the Act.</p><br>

<h2><b>Q: Who is a "Controller" under the Delhi Rent Control Act, 1958?</b></h2><br>
<p>A: A "Controller" is a person appointed under <b>Section 35(1)</b> of the Act, and this term also includes an additional Controller appointed under <b>Section 35(2)</b>.</p><br>

<h2><b>Q: What is the meaning of "fair rate" in this Act?</b></h2><br>
<p>A: "Fair rate" refers to the rate fixed under <b>Section 31</b> of the Act and includes any revised rate under <b>Section 32</b>.</p><br>

<h2><b>Q: How is a "hotel or lodging house" defined under the Act?</b></h2><br>
<p>A: A "hotel or lodging house" is a building or part of a building where lodging, with or without board or other services, is provided for monetary consideration.</p><br>

<h2><b>Q: Who is considered a "landlord" under this Act?</b></h2><br>
<p>A: A "landlord" is a person who receives or is entitled to receive rent for any premises, whether on their own behalf or for the benefit of others, or who would receive the rent if the premises were let to a tenant.</p><br>

<h2><b>Q: What does "lawful increase" in rent mean?</b></h2><br>
<p>A: "Lawful increase" refers to an increase in rent that is permitted under the provisions of this Act.</p><br>

<h2><b>Q: Who is the "manager of a hotel" according to this Act?</b></h2><br>
<p>A: The "manager of a hotel" is any person in charge of the management of the hotel.</p><br>

<h2><b>Q: How is the "owner of a lodging house" defined?</b></h2><br>
<p>A: The "owner of a lodging house" is a person who receives or is entitled to receive monetary consideration for providing board, lodging, or other services in the lodging house.</p><br>

<h2><b>Q: What constitutes "premises" under the Act?</b></h2><br>
<p>A: "Premises" refers to any building or part of a building intended to be let separately for use as a residence, commercial use, or any other purpose, and includes gardens, grounds, outhouses, and furniture supplied by the landlord. However, it does not include a room in a hotel or lodging house.</p><br>

<h2><b>Q: What does "prescribed" mean in the context of the Act?</b></h2><br>
<p>A: "Prescribed" means as specified by the rules made under this Act.</p><br>

<h2><b>Q: How is "standard rent" defined under the Act?</b></h2><br>
<p>A: "Standard rent" refers to the rent mentioned in <b>Section 6</b> or any increased rent under <b>Section 7</b>.</p><br>

<h2><b>Q: Who qualifies as a "tenant" under this Act?</b></h2><br>
<p>A: A "tenant" is a person who pays or is liable to pay rent for any premises, and includes sub-tenants and those continuing in possession after the termination of their tenancy. In case of the tenant's death, their spouse, children, parents, or daughter-in-law living in the premises with the tenant may continue as tenants, with specific conditions and succession rules.</p><br>

<h2><b>Q: What is meant by "urban area" in the context of this Act?</b></h2><br>
<p>A: "Urban area" has the same meaning as defined in the <b>Delhi Municipal Corporation Act, 1957</b>.</p>

<h2><b>Q: Does the Delhi Rent Control Act, 1958 apply to government-owned premises?</b></h2><br>
<p>A: No, the Act does not apply to premises belonging to the Government.</p><br>

<h2><b>Q: Does the Act apply to tenancies or relationships created by a grant from the Government for premises taken on lease or requisitioned by the Government?</b></h2><br>
<p>A: No, the Act does not apply to such tenancies or relationships.</p><br>

<h2><b>Q: Is there any exception for premises belonging to the Government that have been let out by a person with the Government's agreement?</b></h2><br>
<p>A: Yes, if any premises belonging to the Government have been lawfully let by any person through an agreement with the Government, the provisions of this Act will apply to such tenancy, regardless of any court or authority's judgment, decree, or order.</p><br>

<h2><b>Q: Does the Delhi Rent Control Act, 1958 apply to premises with a monthly rent exceeding a certain amount?</b></h2><br>
<p>A: No, the Act does not apply to premises, whether residential or not, whose monthly rent exceeds ₹3,500.</p><br>

<h2><b>Q: Are newly constructed premises exempt from the Act?</b></h2><br>
<p>A: Yes, the Act does not apply to premises constructed on or after the commencement of the <b>Delhi Rent Control (Amendment) Act, 1988</b>, for a period of ten years from the date of completion of such construction.</p><br>



