<h2><b>Q: To which hotels and lodging houses does this Chapter apply?</b></h2><br>
<p>A: The provisions of this Chapter apply to all hotels and lodging houses in the areas that were included in the New Delhi Municipal Committee, Municipal Committee, Delhi, and the Notified Area Committee, Civil Station, Delhi as of April 7, 1958. Additionally, the Central Government may extend these provisions to other urban areas within the Municipal Corporation of Delhi through a notification in the Official Gazette.</p><br>

<h2><b>Q: Can the Central Government exempt certain hotels or lodging houses from the provisions of this Chapter?</b></h2><br>
<p>A: Yes, the Central Government can exempt specific classes of hotels or lodging houses from the provisions of this Chapter if it deems it undesirable in the public interest. This exemption is made through a notification in the Official Gazette.</p><br>

<h2><b>Q: What action can the Controller take if the charges for services in a hotel or lodging house are deemed excessive?</b></h2><br>
<p>A: If the Controller believes that the charges for board, lodging, or any other services are excessive, based on a written complaint or otherwise, he can fix a fair rate for these services. This fair rate will be specified separately for lodging, board, or other services.</p><br>

<h2><b>Q: What factors does the Controller consider when determining a fair rate?</b></h2><br>
<p>A: In fixing a fair rate, the Controller considers the circumstances of the case, the prevailing rates for similar accommodations, board, and services during the twelve months immediately preceding June 1, 1951, and any general increase in the cost of living since that date.</p><br>

<h2><b>Q: Can the Controller adjust the fair rates periodically?</b></h2><br>
<p>A: While the text does not specify periodic adjustments, the Controller's determination of fair rates considers historical rates and cost-of-living changes. This suggests that the Controller's decisions are based on up-to-date assessments of costs and standards, but further details on periodic reviews would be subject to additional regulations or updates not specified in the given text.</p><br>


<h2><b>Q: How can the fair rate for board, lodging, or other services in a hotel or lodging house be revised?</b></h2><br>
<p>A: The fair rate can be revised by the Controller upon receiving a written application from the manager of the hotel or the owner of the lodging house, or otherwise. The Controller may revise the rate based on general rises or falls in the cost of living that have occurred since the last revision.</p><br>

<h2><b>Q: What restrictions apply to the manager of a hotel or owner of a lodging house once the Controller has determined the fair rate?</b></h2><br>
<p>A: Once the fair rate is determined by the Controller:</p>
<ul>
    <li>1. The manager or owner cannot charge more than the fair rate.</li>
    <li>2. They cannot withdraw any concessions or services provided at the time the fair rate was set without prior written permission from the Controller.</li>
</ul><br>

<h2><b>Q: What happens to agreements that specify charges in excess of the fair rate?</b></h2><br>
<p>A: Any agreement specifying charges beyond the fair rate is deemed void concerning the excess amount. The agreement is considered to be for the payment of only the fair rate as determined by the Controller.</p><br>

<h2><b>Q: Can a lodger recover any amount paid in excess of the fair rate?</b></h2><br>
<p>A: Yes, a lodger can recover any excess amount paid within six months from the date of payment. This amount can be recovered from the manager of the hotel or the owner of the lodging house or their legal representatives. Additionally, the lodger may deduct the excess amount from any future payments due to the manager or owner.</p><br>

<h2><b>Q: Are there any other provisions for recovering excess charges beyond those described?</b></h2><br>
<p>A: Besides the direct recovery from the manager or owner or deduction from future payments, the lodger may pursue other legal avenues for recovery if necessary. The specific procedures or additional methods for recovery beyond the described options would be subject to further legal provisions or regulations not detailed in the text provided.</p><br>


<h2><b>Q: Under what conditions can the manager of a hotel or the owner of a lodging house recover possession of the accommodation provided to a lodger?</b></h2><br>
<p>A: The manager or owner can recover possession under the following conditions, provided they obtain a certificate from the Controller:</p>
<ul>
    <p><b>Nuisance or Annoyance:</b> If the lodger has engaged in conduct that is a nuisance or causes annoyance to neighboring lodgers. This includes acts that constitute an offence under the Suppression of Immoral Traffic in Women and Girls Act, 1956.</p>
    <p><b>Reasonable Requirement:</b> If the accommodation is reasonably and bona fide required by the owner for their own use or for the use of someone else for whom the accommodation is held, or for any other satisfactory cause as deemed by the Controller.</p>
    <p><b>Failure to Vacate:</b> If the lodger fails to vacate the accommodation after the agreement period has ended.</p>
    <p><b>Inconsistent Use:</b> If the lodger has used the accommodation in a manner inconsistent with its intended purpose or in a way that adversely affects the owner's interests.</p>
    <p><b>Failure to Pay Rent:</b> If the lodger has not paid the rent due.</p>
</ul><br>

<h2><b>Q: What is meant by “nuisance” in this context?</b></h2><br>
<p>A: For the purposes of this clause, “nuisance” includes any act that constitutes an offence under the Suppression of Immoral Traffic in Women and Girls Act, 1956.</p><br>

<h2><b>Q: What is required for the manager or owner to legally recover possession?</b></h2><br>
<p>A: The manager or owner must obtain a certificate from the Controller certifying that one or more of the specified conditions for recovery of possession are met.</p><br>

<h2><b>Q: Can the manager or owner recover possession without a certificate from the Controller?</b></h2><br>
<p>A: No, the manager or owner cannot legally recover possession without obtaining the necessary certificate from the Controller.</p><br>

<h2><b>Q: How does the Controller determine if the conditions for recovery of possession are met?</b></h2><br>
<p>A: The Controller evaluates the evidence and circumstances related to each condition outlined (such as nuisance, reasonable requirement, failure to vacate, inconsistent use, and rent arrears) before issuing a certificate.</p><br>

<h2><b>Q: What is the significance of obtaining a certificate from the Controller?</b></h2><br>
<p>A: The certificate from the Controller serves as official confirmation that the manager or owner has a valid reason under the law to recover possession of the accommodation from the lodger. It provides legal authorization to proceed with the recovery process.</p><br>






