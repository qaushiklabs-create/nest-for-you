<h2><b>Q: What are the grounds on which a landlord can apply for the recovery of possession of premises from a tenant under Section 14?</b></h2><br>
<p>A: Under Section 14, a landlord can apply for recovery of possession on the following grounds:<br>
<ul>
    <li>(a) Tenant has not paid or tendered the arrears of rent within two months after receiving a demand notice.</li>
    <li>(b) Tenant has sub-let, assigned, or parted with possession of the premises without landlord's written consent.</li>
    <li>(c) Tenant has used the premises for a purpose other than the one for which they were let without the landlord’s consent.</li>
    <li>(d) The premises were let for residence, but neither the tenant nor their family has resided there for six months before the application.</li>
    <li>(e) The premises are required bona fide by the landlord for their own use or for a dependent family member, with no other suitable accommodation available.</li>
    <li>(f) The premises are unsafe or unfit for habitation and are required for repairs that necessitate vacation.</li>
    <li>(g) The premises are needed for building, rebuilding, or making substantial alterations that cannot be done without vacation.</li>
    <li>(h) Tenant has acquired or been allotted another residence.</li>
    <li>(i) Tenant has built a residence and ten years have passed since.</li>
    <li>(j) The premises were let due to tenant’s employment with the landlord, and the tenant has ceased such employment.</li>
    <li>(k) Tenant has caused substantial damage to the premises.</li>
    <li>(l) Tenant has used or dealt with the premises contrary to conditions imposed by government or authorities.</li>
    <li>(m) The landlord needs the premises for building work under an improvement or development scheme.</li>
</ul></p><br>

<h2><b>Q: What protections are available to tenants under Section 14?</b></h2><br>
<p>A: Tenants have the following protections:<br>
<ul>
    <li>(2) No order for eviction will be made for non-payment of rent if the tenant pays or deposits the arrears as per section 15. However, if the tenant defaults again after obtaining this benefit, they lose this protection.</li>
    <li>(3) Sub-tenants must be made parties to the eviction proceedings if their rights are to be affected.</li>
    <li>(4) If premises are used for business purposes, the tenant will be deemed to have sub-let if they allow another person to occupy the premises ostensibly as a partner in the business.</li>
    <li>(5) For misuse of premises, the landlord must first issue a notice requiring the tenant to stop the misuse before seeking eviction.</li>
    <li>(6) Landlords who acquire premises by transfer cannot evict tenants under the ground of bona fide requirement unless five years have elapsed since acquisition.</li>
    <li>(7) If eviction is granted on the grounds of bona fide requirement, the landlord cannot obtain possession before six months from the order.</li>
    <li>(8) For eviction on grounds of building or rebuilding, the Controller must ensure the proposed reconstruction does not radically alter the premises’ purpose, or that such alteration is in the public interest.</li>
    <li>(9) If there is a bona fide dispute about whether the tenant has ceased to be in the landlord’s service or employment, no order for eviction will be made.</li>
    <li>(10) If the tenant causes damage to the premises, they may avoid eviction by repairing the damage or paying compensation as directed by the Controller.</li>
    <li>(11) For eviction due to conditions imposed by authorities, the tenant can avoid eviction by complying with conditions or paying compensation as directed.</li>
</ul></p><br>

<h2><b>Q: Can a tenant contest an eviction order under Section 14?</b></h2><br>
<p>A: Yes, tenants can contest an eviction order by:<br>
<ul>
    <li>1. Filing an affidavit stating their grounds for contesting the eviction.</li>
    <li>2. Obtaining leave from the Controller to contest the application. The Controller will grant leave if the affidavit discloses facts that could prevent the landlord from obtaining the order for eviction.</li>
</ul></p><br>
<h2><b>Q: What is the right of a landlord to recover possession of premises under Section 14A?</b></h2><br>
<p>A: Under Section 14A:<br>
<ul>
    <li>(1) A landlord who is required by the Central Government or a local authority to vacate residential accommodation and owns another residential accommodation in Delhi (either in their name or that of a dependent) can recover possession of any premises let out by them. This right accrues from the date of such an order.</li>
    <li>(2) The landlord cannot claim compensation from the tenant or any other party for recovering possession. However, if the landlord has received rent in advance or other payments, they must refund the unexpired portion of the contract to the tenant within 90 days of recovering possession. Failure to refund will attract simple interest at 6% per annum on the omitted amount.</li>
</ul></p><br>

<h2><b>Q: What rights do members of the armed forces or their dependents have under Section 14B?</b></h2><br>
<p>A: Under Section 14B:<br>
<ul>
    <li>(1) A landlord who is a released or retired member of the armed forces, or a dependent of a deceased armed forces member, can apply to the Controller to recover immediate possession of premises let out by them. The application must be made within one year of their release, retirement, or the death of the armed forces member, or within one year from the commencement of the Delhi Rent Control (Amendment) Act, 1988, whichever is later.</li>
    <li>(2) If the landlord is a current member of the armed forces with less than one year remaining before retirement, they can apply for recovery of possession within one year before their retirement.</li>
    <li>(3) If the landlord has let out more than one premises, they can choose only one premises for which to apply for recovery of possession under this section.</li>
</ul></p><br>

<h2><b>Q: What is the definition of "armed forces" in Section 14B?</b></h2><br>
<p>A: In Section 14B, "armed forces" refers to:<br>
<ul>
    <li>1. An armed force of the Union constituted under an Act of Parliament.</li>
    <li>2. It also includes members of the police force constituted under Section 3 of the Delhi Police Act, 1978.</li>
</ul></p><br>
<h2><b>Q: What is the timeframe for a retired employee of the Central Government or Delhi Administration to apply for the recovery of premises for personal use?</b></h2><br>
<p>A: A retired employee of the Central Government or Delhi Administration can apply for the recovery of the premises within one year from the date of retirement or within one year from the date of commencement of the Delhi Rent Control (Amendment) Act, 1988, whichever is later.</p><br>

<h2><b>Q: What should a current employee of the Central Government or Delhi Administration do if they need their premises for personal use after retirement?</b></h2><br>
<p>A: A current employee who will retire within one year can apply to the Controller for the recovery of the premises at any time within one year before their retirement date.</p><br>

<h2><b>Q: If a landlord covered under the provisions of sub-sections (1) or (2) has more than one premises, how many premises can they apply to recover?</b></h2><br>
<p>A: If the landlord has more than one premises, they can apply for the recovery of only one of the premises chosen by them.</p><br>

<h2><b>Q: What rights does a widow landlord have regarding the recovery of premises?</b></h2><br>
<p>A: A widow landlord, or a widow whose husband was the landlord, can apply to the Controller to recover the immediate possession of the premises if they require it for their own residence.</p><br>

<h2><b>Q: If a widow landlord has multiple premises, how many can she apply to recover?</b></h2><br>
<p>A: The widow can apply to recover any one of the premises chosen by her if she has more than one.</p><br>

<h2><b>Q: What must a tenant do to receive protection against eviction when the landlord seeks possession of the premises?</b></h2><br>
<p>A: To receive protection against eviction, the tenant must pay or deposit with the Controller an amount equal to the rent at the last paid rate for the period of legally recoverable arrears, including any subsequent period up to the end of the month before payment or deposit is made. The tenant must also continue to pay or deposit the rent monthly by the fifteenth of each succeeding month.</p><br>

<h2><b>Q: What happens if the tenant disputes the claim for eviction on grounds other than those mentioned in sub-section (1)?</b></h2><br>
<p>A: If the tenant disputes the eviction claim, the landlord can apply to the Controller at any stage of the proceeding. The Controller, after hearing both parties, may order the tenant to pay the rent legally recoverable.</p><br>

<h2><b>Q: How does the Controller handle disputes about the amount of rent payable by the tenant?</b></h2><br>
<p>A: In case of a rent dispute, the Controller will fix an interim rent within fifteen days of the first hearing. The tenant must pay or deposit this interim rent until the standard rent is fixed. Any arrears based on the standard rent must be paid within one month of its fixation or within additional time allowed by the Controller.</p><br>

<h2><b>Q: What if there is a dispute over who the rent should be paid to?</b></h2><br>
<p>A: If there is a dispute over the recipient of the rent, the Controller may direct the tenant to deposit the amount with the Controller. No one can withdraw the deposit until the Controller resolves the dispute and makes an order for its payment.</p><br>

<h2><b>Q: What can the Controller do if they believe the dispute over the rent recipient is false or frivolous?</b></h2><br>
<p>A: If the Controller finds that the dispute over the rent recipient is false or frivolous, they may strike out the tenant's defense against eviction and proceed with hearing the landlord's application.</p><br>

<h2><b>Q: What happens if a tenant complies with the payment or deposit requirements under sub-section (1) or sub-section (3)?</b></h2><br>
<p>A: If the tenant makes the required payment or deposit, no order for recovery of possession will be made based on default in rent payment. However, the Controller may award costs to the landlord as deemed fit.</p><br>

<h2><b>Q: What are the consequences if a tenant fails to make the required payment or deposit?</b></h2><br>
<p>A: If the tenant fails to comply with the payment or deposit requirements, the Controller may strike out the tenant’s defense against eviction and continue with the eviction proceedings.</p><br>

<h2><b>Q: What are the rules regarding the legality of sub-letting before June 9, 1952?</b></h2><br>
<p>A: If a tenant sub-let the whole or any part of the premises before June 9, 1952, and the sub-tenant is occupying the premises at the start of this Act, the sub-letting is deemed lawful, even if the landlord's consent was not obtained.</p><br>

<h2><b>Q: What about sub-letting that occurred after June 9, 1952?</b></h2><br>
<p>A: Any premises sub-let in whole or in part after June 9, 1952, without obtaining the landlord’s written consent, shall not be considered as lawfully sub-let.</p><br>

<h2><b>Q: What must a tenant do after the commencement of this Act regarding sub-letting or transfer of tenancy?</b></h2><br>
<p>A: After the Act’s commencement, a tenant must obtain the landlord’s prior written consent to:</p>
<ul>
    <li>1. Sub-let the whole or any part of the premises, or</li>
    <li>2. Transfer or assign their tenancy rights or any part thereof.</li>
</ul><br>

<h2><b>Q: Can a landlord demand a premium or any consideration for giving consent to sub-letting?</b></h2><br>
<p>A: No, a landlord cannot claim or receive any premium, pugree, or any form of consideration, either in cash or kind, for giving consent to the sub-letting of the premises.</p><br>

<h2><b>Q: What is required when a tenant lawfully sub-lets premises with the landlord’s written consent?</b></h2><br>
<p>A: After lawful sub-letting with the landlord’s consent, the tenant or the sub-tenant must notify the landlord of the sub-tenancy creation within one month and of its termination within one month of such termination.</p><br>

<h2><b>Q: What if the premises were lawfully sub-let before the commencement of the Act?</b></h2><br>
<p>A: For premises lawfully sub-let before the Act’s commencement, the tenant or sub-tenant must notify the landlord of the sub-tenancy creation within six months of the Act's commencement and of its termination within one month of such termination.</p><br>

<h2><b>Q: What happens if there is a dispute over the lawfulness of a sub-letting?</b></h2><br>
<p>A: If there is a dispute over whether a sub-letting was lawful, the Controller will decide the dispute if an application is made by either the landlord or the sub-tenant within two months of the notice of sub-letting or its issuance.</p><br>

<h2><b>Q: What occurs if an eviction order is made against a tenant but not a sub-tenant?</b></h2><br>
<p>A: If an eviction order is made against a tenant but not against a sub-tenant who has given notice of their sub-tenancy, the sub-tenant will become a direct tenant under the landlord, with the same terms and conditions as the original tenant.</p><br>

<h2><b>Q: How are sub-tenants treated if the tenant's interest is determined before the commencement of the Act?</b></h2><br>
<p>A: If a tenant's interest in the premises was determined before the Act’s commencement, and the premises were lawfully sub-let, the sub-tenant will be deemed to have become a direct tenant under the landlord as of the Act's commencement, on the same terms as if the original tenancy had continued.</p><br>

<h2><b>Q: What restrictions apply to a landlord who recovers possession of premises under sections 14, 14A, 14B, 14C, 14D, or 21?</b></h2><br>
<p>A: If a landlord recovers possession of premises under these sections, they cannot re-let the premises or any part of them within three years from the date of possession without obtaining permission from the Controller. The Controller may also direct the landlord to reinstate the evicted tenant.</p><br>

<h2><b>Q: What happens if the landlord does not occupy the premises or re-lets them within three years after recovering possession?</b></h2><br>
<p>A: If the landlord does not occupy the premises or re-lets them to someone other than the evicted tenant within two months of obtaining possession, or if the premises are transferred to another person for non-bona fide reasons, the Controller may order the landlord to reinstate the evicted tenant or pay compensation.</p><br>

<h2><b>Q: What must a tenant do if they are evicted for repairs or rebuilding?</b></h2><br>
<p>A: If a tenant is evicted for repairs or rebuilding and elects to be placed back in the premises, the Controller will specify a date for delivering possession to allow the landlord to commence work. The landlord must then return the tenant to the premises once the work is completed.</p><br>

<h2><b>Q: What if the landlord fails to commence or complete the work after the tenant has delivered possession?</b></h2><br>
<p>A: If the landlord fails to start the work within one month of the specified date, does not complete it in a reasonable time, or does not return the tenant to the premises after completing the work, the Controller may order the landlord to place the tenant back in occupation or pay compensation.</p><br>

<h2><b>Q: What are the provisions for tenancies for a limited period?</b></h2><br>
<p>A: If a landlord leases premises for a specific period with the Controller’s permission and the tenant does not vacate at the end of this period, the Controller can order the eviction of the tenant and any other occupants, and may award damages for the period from the order until the tenant vacates.</p><br>

<h2><b>Q: How does the law address the recovery of possession for premises required by a company, local authority, or public institution?</b></h2><br>
<p>A: If a company, local authority, or public institution needs premises for its employees or activities, the Controller can order eviction if:</p>
<ul>
    <li>1. The tenant has ceased employment with the landlord,</li>
    <li>2. The tenant has violated the terms of occupancy,</li>
    <li>3. Another person is in unauthorized occupation,</li>
    <li>4. The premises are required bona fide for the institution's activities.</li>
</ul><br>

<h2><b>Q: What is considered a “public institution” under these provisions?</b></h2><br>
<p>A: For these provisions, a “public institution” includes educational institutions, libraries, hospitals, and charitable dispensaries, but does not include institutions set up by private trusts.</p><br>




