<h2><b>Q: Can a tenant be required to pay rent exceeding the standard rent under the Delhi Rent Control Act, 1958?</b></h2><br>
<p>A: No, except in cases where rent is liable to periodical increase by virtue of an agreement made before January 1, 1939, a tenant cannot be required to pay rent in excess of the standard rent, regardless of any agreement to the contrary, unless the increase is lawful under the provisions of the Act.</p><br>

<h2><b>Q: What happens if there is an agreement to pay rent higher than the standard rent?</b></h2><br>
<p>A: If there is an agreement to pay rent exceeding the standard rent, the agreement will be interpreted as an agreement to pay only the standard rent, subject to the provisions of the Act.</p><br>

<h2><b>Q: Is there any situation where a tenant may be liable to pay rent higher than the standard rent?</b></h2><br>
<p>A: Yes, a tenant may be liable to pay higher rent if there is an agreement for a periodical increase in rent made before January 1, 1939, or if the increase is lawful under the provisions of this Act.</p>

<h2><b>Q: Can a landlord claim or receive rent in excess of the standard rent under the Delhi Rent Control Act, 1958?</b></h2><br>
<p>A: No, a landlord cannot claim or receive rent in excess of the standard rent, regardless of any agreement to the contrary.</p><br>

<h2><b>Q: Is it lawful to claim any additional payments, such as premium or pugree, for granting, renewing, or continuing a tenancy?</b></h2><br>
<p>A: No, it is unlawful to claim or receive any additional payments, such as premium or pugree, in addition to rent for granting, renewing, or continuing a tenancy or sub-tenancy.</p><br>

<h2><b>Q: Can a landlord receive rent in advance?</b></h2><br>
<p>A: A landlord can only receive rent in advance up to one month's rent unless they have received prior permission from the Controller.</p><br>

<h2><b>Q: Is it permissible for a tenant to receive payment for relinquishing, transferring, or assigning their tenancy or sub-tenancy?</b></h2><br>
<p>A: No, it is not lawful for a tenant or any person acting on behalf of the tenant to claim or receive any payment in consideration for relinquishing, transferring, or assigning their tenancy or sub-tenancy.</p><br>

<h2><b>Q: Are there any exceptions to the prohibition on claiming or receiving unlawful charges?</b></h2><br>
<p>A: Yes, the following are exceptions:<br>
<ul>
    <li>1. Payments made under agreements entered into before January 1, 1939.</li>
    <li>2. Payments made under an agreement for financing the construction of premises on the landlord's land, where the landlord agrees to let the premises to the person financing the construction or a member of their family. However, the payment should not exceed the rent for five years of the premises.</li>
</ul></p><br>

<h2><b>Q: How is "member of the family" defined in the context of financing agreements for construction?</b></h2><br>
<p>A: In the case of an undivided Hindu family, a "member of the family" includes any member of that family. For other families, it includes the husband, wife, son, daughter, father, mother, brother, sister, or any other relative dependent on the person.</p>

<h2><b>Q: What does "standard rent" mean in relation to residential premises let out before June 2, 1944?</b></h2><br>
<p>A: For residential premises let out before June 2, 1944:<br>
<ul>
    <li>1. If the basic rent per annum does not exceed ₹600, the standard rent is the basic rent.</li>
    <li>2. If the basic rent per annum exceeds ₹600, the standard rent is the basic rent plus 10% of the basic rent.</li>
</ul></p><br>

<h2><b>Q: How is the standard rent determined for residential premises let out on or after June 2, 1944?</b></h2><br>
<p>A: For residential premises let out on or after June 2, 1944:<br>
<ul>
    <li>1. If the rent was fixed under previous rent control laws and does not exceed ₹1200 per annum, the standard rent is the rent so fixed.</li>
    <li>2. If the rent exceeds ₹1200 per annum, the standard rent is the rent so fixed plus 10%.</li>
    <li>3. In other cases, the standard rent is calculated as 10% per annum of the aggregate of the actual cost of construction and the market price of the land at the time of construction.</li>
</ul></p><br>

<h2><b>Q: How is the standard rent determined for non-residential premises let out before June 2, 1944?</b></h2><br>
<p>A: For non-residential premises let out before June 2, 1944, the standard rent is the basic rent plus 10%. If the calculated rent exceeds ₹1200 per annum, the standard rent is the basic rent plus 15%.</p><br>

<h2><b>Q: What is the standard rent for premises constructed between June 2, 1951, and June 9, 1955?</b></h2><br>
<p>A: For premises constructed between June 2, 1951, and June 9, 1955, the standard rent is the annual rent based on the rent at which the premises were let in March 1958. If the premises were not let at that time, the rent at which they were last let out will be the standard rent, applicable for seven years from the date of construction.</p><br>

<h2><b>Q: How is the standard rent determined for premises constructed on or after June 9, 1955?</b></h2><br>
<p>A: For premises constructed on or after June 9, 1955 (but before the commencement of the Delhi Rent Control (Amendment) Act, 1988), the standard rent is the annual rent agreed upon when the premises were first let out. This rent is considered standard for five years from the date of letting.</p><br>

<h2><b>Q: How is the standard rent determined for premises constructed after the commencement of the Delhi Rent Control (Amendment) Act, 1988?</b></h2><br>
<p>A: For premises constructed after the commencement of the Delhi Rent Control (Amendment) Act, 1988, the standard rent is calculated as 10% per annum of the aggregate of the actual cost of construction and the market price of the land at the time of construction.</p><br>

<h2><b>Q: Are premises used for public services like hospitals or educational institutions considered residential for rent control purposes?</b></h2><br>
<p>A: Yes, premises let out for public hospitals, educational institutions, public libraries, reading rooms, or orphanages are considered residential premises under this section.</p>

<h2><b>Q: What does Section 6A of the Delhi Rent Control Act, 1958, allow in terms of rent revision?</b></h2><br>
<p>A: Section 6A permits a rent increase of <b>10% every three years</b>. This applies to both standard rent and agreed-upon rent if no standard rent has been fixed.</p><br>

<h2><b>Q: How often can rent be revised under Section 6A?</b></h2><br>
<p>A: Rent can be revised every <b>three years</b> with a <b>10% increase</b>.</p><br>

<h2><b>Q: Under what circumstances can a landlord lawfully increase the standard rent under Section 7(1)?</b></h2><br>
<p>A: A landlord can lawfully increase the standard rent if they have incurred expenses for improvements, additions, or structural alterations to the premises. This increase can be up to <b>10% of the cost</b> of such improvements, provided that these expenses have not already been factored into the rent.</p><br>

<h2><b>Q: Is tenant approval required for increasing rent under Section 7(1)?</b></h2><br>
<p>A: Yes, for improvements made <b>after the commencement of the Act</b>, tenant approval or approval from the Controller is required. However, for improvements made <b>before the commencement of the Act</b>, tenant approval is not necessary.</p><br>

<h2><b>Q: Can a landlord recover charges for utilities like electricity or water from the tenant under Section 7(2)?</b></h2><br>
<p>A: Yes, a landlord can recover charges for electricity, water, or other charges levied by a local authority, provided these are ordinarily payable by the tenant.</p><br>

<h2><b>Q: Can a landlord increase rent to recover taxes on the building or land under Section 7(2)?</b></h2><br>
<p>A: No, a landlord cannot increase rent or otherwise recover taxes on the building or land from the tenant, except where an agreement was made before January 1, 1952.</p><br>

<h2><b>Q: What impact does Section 7(2) have on agreements made before January 1, 1952?</b></h2><br>
<p>A: Any agreement made before January 1, 1952, that requires the tenant to pay building or land taxes remains valid, and the tenant remains liable under such agreements.</p>

<h2><b>Q: What is the procedure for a landlord to increase the rent under Section 8?</b></h2><br>
<p>A: The landlord must provide a <b>written notice</b> to the tenant, indicating the intention to increase the rent. This notice must be <b>signed by the landlord</b> or on their behalf.</p><br>

<h2><b>Q: When does the rent increase become due and recoverable?</b></h2><br>
<p>A: The rent increase becomes due and recoverable <b>30 days after the notice is given</b>, but only for the period of the tenancy that starts after the 30-day notice period.</p><br>

<h2><b>Q: Is there a specific legal format that the notice must follow?</b></h2><br>
<p>A: Yes, the notice must comply with the provisions of <b>Section 106 of the Transfer of Property Act, 1882</b>, which outlines the manner of giving notices.</p><br>

<h2><b>Q: What happens if the landlord fails to give the required notice?</b></h2><br>
<p>A: If the required notice is not given, the rent increase is <b>not legally enforceable</b>, meaning the tenant would not be obligated to pay the increased amount.</p><br>

<h2><b>Q: Can the tenant dispute the rent increase?</b></h2><br>
<p>A: The tenant can potentially dispute the increase if it does not comply with the law or if the notice is not provided correctly. However, if the increase is lawful and the notice is properly given, the tenant must adhere to the new rent.</p>
<h2><b>Q: Who can apply to the Controller to fix the standard rent or lawful increase?</b></h2><br>
<p>A: Either the <b>landlord or the tenant</b> can make an application to the Controller for fixing the standard rent or the lawful increase of rent.</p><br>

<h2><b>Q: How does the Controller determine the standard rent or lawful increase?</b></h2><br>
<p>A: The Controller fixes an amount that seems <b>reasonable</b>, considering the provisions of sections 6 or 7 and the specific circumstances of the case. The Controller may also use the assistance of a <b>valuer approved by the Central Government</b> to assess the cost of construction or improvements.</p><br>

<h2><b>Q: Can the Controller set the standard rent for a part of a premises that has been sub-let?</b></h2><br>
<p>A: Yes, the Controller can fix the standard rent for both the <b>main premises</b> and any part that has been <b>lawfully sub-let</b>.</p><br>

<h2><b>Q: What if it is not possible to determine the standard rent using the principles set out in section 6?</b></h2><br>
<p>A: If the standard rent cannot be determined as per section 6, the Controller may fix a <b>reasonable rent</b> based on the situation, locality, condition of the premises, and the rents of similar premises in the locality.</p><br>

<h2><b>Q: For what duration is the standard rent fixed?</b></h2><br>
<p>A: The standard rent is fixed for a <b>tenancy of twelve months</b>. If the tenancy is for a shorter period, the standard rent will be proportional to the tenancy period.</p><br>

<h2><b>Q: How does the Controller address the issue of furnished premises?</b></h2><br>
<p>A: The Controller fixes the standard rent for the premises in an <b>unfurnished state</b> but may determine an additional charge for any fittings or furniture provided by the landlord. This additional charge can be recovered by the landlord from the tenant.</p><br>

<h2><b>Q: From what date does the fixed standard rent take effect?</b></h2><br>
<p>A: The standard rent fixed by the Controller will be effective from a date specified by the Controller, but this date cannot be earlier than <b>one year prior</b> to the date of filing the application for the fixation of the standard rent.</p>
<h2><b>Q: What is the purpose of an interim rent fixation under section 10?</b></h2><br>
<p>A: <b>Interim rent fixation</b> allows the Controller to specify an amount of rent or lawful increase to be paid by the tenant to the landlord while the final decision on the application for fixing the standard rent or determining the lawful increase is pending.</p><br>

<h2><b>Q: When does the interim rent or lawful increase specified by the Controller take effect?</b></h2><br>
<p>A: The Controller will appoint a date from which the <b>interim rent or lawful increase</b> is deemed to have effect. This date is specified in the order made by the Controller.</p><br>

<h2><b>Q: How quickly must the Controller act on an application for fixing the standard rent or lawful increase?</b></h2><br>
<p>A: The Controller is required to act as <b>expeditiously</b> as possible in making an order for interim rent or lawful increase.</p><br>

<h2><b>Q: What does section 11 state about the liability of collectors of rent or middlemen?</b></h2><br>
<p>A: Section 11 limits the liability of collectors of rent or middlemen to ensure they are not required to pay their principal any sum exceeding the amount they are authorized to collect from the tenants under the Act.</p><br>

<h2><b>Q: Can a middleman be held liable for rental charges beyond what is permitted under the Act?</b></h2><br>
<p>A: No, a collector of rent or middleman cannot be held liable to pay any amount beyond what is <b>authorized</b> for collection from tenants under the Act.</p>

<h2><b>Q: What is the time limit for filing an application for fixation of standard rent or lawful increase?</b></h2><br>
<p>A: The time limits are as follows:<br>
<ul>
    <li>1. For premises let or where the cause of action arose before the Act's commencement: <b>within two years from the Act's commencement.</b></li>
    <p>2. For premises let between the commencement of the Act and the Delhi Rent Control (Amendment) Act, 1988:<br>
            <p><b>a) Landlord's application:</b> within two years from the letting date.</p>
            <p><b>b) Tenant's application:</b> within two years from the letting date.</p>
    </p>
    <li>3. For premises where the cause of action for lawful increase arises after the Act's commencement: <b>within two years from the cause of action.</b></li>
    <li>For premises referred to in clause (c) of sub-section (2) of section 6: <b>within two years from the date of the application.</b></li>
</ul></p><br>

<h2><b>Q: Can the Controller entertain an application if the two-year period has expired?</b></h2><br>
<p>A: Yes, the Controller may entertain an application after the two-year period if the applicant can show that they were prevented by <b>sufficient cause</b> from filing the application on time.</p><br>

<h2><b>Q: What provisions are there for refunding rent or other payments made in contravention of the Act?</b></h2><br>
<p>A: If any sum or other consideration has been paid in contravention of the Act, the Controller may order a <b>refund</b> or adjustment of the sum against the rent payable. This must be applied for <b>within one year</b> from the date of such payment.</p><br>

<h2><b>Q: How can a tenant seek a refund of payments made in violation of the rent control provisions?</b></h2><br>
<p>A: The tenant must file an <b>application with the Controller</b> within one year from the date of the payment to request a refund or adjustment of the payment made in contravention of the Act.</p><br>




